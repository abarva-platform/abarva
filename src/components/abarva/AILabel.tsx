import type { CSSProperties } from "react";
import { COLORS, FONT, RADIUS } from "@/lib/design/abarva-theme";

export type AILabelStatus = "draft" | "suggested" | "pending_review";
export type AILabelVariant =
  | AILabelStatus
  | "suggestion"
  | "pending"
  | "generated"
  | "custom";

const LABEL_META: Record<
  AILabelStatus | "generated",
  { text: string; accent: string; background: string; helper: string }
> = {
  draft: {
    text: "AI Draft",
    accent: COLORS.navy,
    background: COLORS.navySoft,
    helper: "Drafted by AI. Review before using.",
  },
  suggested: {
    text: "Suggested",
    accent: COLORS.amber,
    background: COLORS.amberSoft,
    helper: "Suggested by AI. You decide whether to apply.",
  },
  pending_review: {
    text: "Pending Review",
    accent: COLORS.red,
    background: COLORS.redSoft,
    helper: "Pending your review. No action taken yet.",
  },
  generated: {
    text: "AI-Generated",
    accent: COLORS.navy,
    background: COLORS.navySoft,
    helper: "Generated by AI. Verify before relying on this content.",
  },
};

const SIZE_STYLE: Record<
  NonNullable<AILabelProps["size"]>,
  { gap: number; padding: string; fontSize: number }
> = {
  sm: { gap: 5, padding: "2px 7px", fontSize: 9 },
  md: { gap: 7, padding: "3px 9px", fontSize: 10 },
  lg: { gap: 8, padding: "5px 11px", fontSize: 11 },
};

export interface AILabelProps {
  /** Backwards-compatible state prop used by existing AbarVa surfaces. */
  status?: AILabelStatus;
  /** Label variant. Use `custom` with `label` for one-off audit labels. */
  variant?: AILabelVariant;
  /** Custom visible label when `variant="custom"`. */
  label?: string;
  /** Tooltip and screen-reader detail. Defaults to the standard copy. */
  tooltip?: string;
  /** Optional visible helper. Defaults to the standard copy. */
  detail?: string;
  /** Size for dense rails, normal cards, or prominent review frames. */
  size?: "sm" | "md" | "lg";
  /** Backwards-compatible shorthand for `size="sm"`. */
  compact?: boolean;
  className?: string;
  style?: CSSProperties;
}

function normalizeVariant(
  status: AILabelStatus | undefined,
  variant: AILabelVariant | undefined,
): AILabelStatus | "generated" | "custom" {
  const value = variant ?? status ?? "draft";
  if (value === "suggestion") return "suggested";
  if (value === "pending") return "pending_review";
  return value;
}

/**
 * Small accessible marker for AI-generated output.
 *
 * Example:
 * `<AILabel variant="draft" tooltip="Drafted by AI. Review before using." />`
 */
export function AILabel({
  status = "draft",
  variant,
  label,
  tooltip,
  detail,
  size = "md",
  compact = false,
  className,
  style,
}: AILabelProps) {
  const normalized = normalizeVariant(status, variant);
  const meta =
    normalized === "custom"
      ? {
          text: label ?? "AI Output",
          accent: COLORS.navy,
          background: COLORS.navySoft,
          helper: tooltip ?? "AI-generated output. Verify before relying on it.",
        }
      : LABEL_META[normalized];
  const helper = detail ?? tooltip ?? meta.helper;
  const ariaDetail = tooltip ?? helper;
  const visualSize = SIZE_STYLE[compact ? "sm" : size];

  return (
    <span
      role="status"
      data-ai-label-status={normalized}
      aria-label={`${meta.text}: ${ariaDetail}`}
      title={ariaDetail}
      className={className}
      style={{
        display: "inline-flex",
        alignItems: "center",
        gap: visualSize.gap,
        width: "fit-content",
        maxWidth: "100%",
        borderRadius: RADIUS.pill,
        border: `1px solid ${meta.accent}33`,
        background: meta.background,
        color: meta.accent,
        padding: visualSize.padding,
        fontFamily: FONT.mono,
        fontSize: visualSize.fontSize,
        fontWeight: 700,
        lineHeight: 1.35,
        letterSpacing: "0.08em",
        textTransform: "uppercase",
        whiteSpace: "normal",
        ...style,
      }}
    >
      <span>{meta.text}</span>
      {helper ? (
        <>
          <span aria-hidden="true" style={{ opacity: 0.45 }}>
            ·
          </span>
          <span
            style={{
              color: COLORS.muted,
              fontWeight: 600,
              letterSpacing: "0.04em",
            }}
          >
            {helper}
          </span>
        </>
      ) : null}
    </span>
  );
}
