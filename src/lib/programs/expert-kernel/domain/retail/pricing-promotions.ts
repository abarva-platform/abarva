// Domain Function Pack — Retail · Pricing & promotions.
//
// Function key: `pricing_promotions`.
//
// This is the other half of the retail margin-and-mix spine (spec §3). Pricing
// and promotions is the function that decides what every item in the
// assortment sells for and when it goes on offer: the everyday base price by
// item and zone, the promotional calendar and its mechanics, the response to
// competitor moves, the markdown glide path, and — increasingly — personalised
// prices and offers delivered to individual shoppers. It is where a percentage
// point of margin is made or lost across millions of transactions.
//
// The companion pack — merchandising-assortment.ts — sits alongside it:
// merchandising decides what the retailer carries and how the buy is sized;
// pricing decides what that assortment sells for and how it is promoted. A
// well-bought assortment can still erode in margin through undisciplined
// pricing and unprofitable promotions; together the two functions are the
// retail reference depth a merchant's gross margin turns on.
//
// Pure, deterministic, typed module — no I/O, no fabrication. Every benchmark
// is a labelled planning range, never an asserted fact (spec §6 hard fail).

