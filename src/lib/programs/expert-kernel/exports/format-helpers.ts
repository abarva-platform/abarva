// Moves Expert Kernel exports — shared formatting helpers.
//
// Deterministic, pure formatters used by every kernel artifact renderer. The
// HARD RULE the spec sets (§10.2): no fabrication. A figure that is null or a
// seed gap renders as an explicit "not recorded / seed gap" line — never blank,
// never invented. These helpers encode that rule once so every renderer obeys
// it uniformly.
//
// Pure module: deterministic, no I/O.

import type { Range } from '../types';
import type { BusinessCaseSkeleton } from '../business-case-compiler';

/** The phrase the kernel exports use for an absent figure — never blank. */
export const SEED_GAP_MARKER = 'Not recorded — seed gap';

/** Format a USD amount. Whole-dollar, thousands-separated. */
export function usd(n: number | null | undefined): string {
  if (n === null || n === undefined || !Number.isFinite(n)) {
    return SEED_GAP_MARKER;
  }
  const rounded = Math.round(n);
  const sign = rounded < 0 ? '-' : '';
  return `${sign}$${Math.abs(rounded).toLocaleString('en-US')}`;
}

/** Format a USD range as "low – high (point)". */
export function usdRange(r: Range): string {
  return `${usd(r.low)} – ${usd(r.high)} (base ${usd(r.point)})`;
}

/** Format a raw number with a unit, honest about a null (seed-gap) value. */
export function valueWithUnit(
  value: number | null | undefined,
  unit: string,
): string {
  if (value === null || value === undefined || !Number.isFinite(value)) {
    return SEED_GAP_MARKER;
  }
  return `${value} ${unit}`;
}

/** Format a 0..1 fraction as a percent string. */
export function pct(fraction: number): string {
  return `${Math.round(fraction * 100)}%`;
}

/** Format an optional number or fall back to the seed-gap marker. */
export function numberOrGap(n: number | null | undefined): string {
  if (n === null || n === undefined || !Number.isFinite(n)) {
    return SEED_GAP_MARKER;
  }
  return String(n);
}

/** Format a payback figure honestly — null becomes the not-monetisable read. */
export function paybackText(skeleton: BusinessCaseSkeleton): string {
  if (!skeleton.economics.monetisable) {
    return 'Not monetisable — the value rests on a baseline seed gap, so the ' +
      'kernel returns no payback rather than a fabricated one.';
  }
  if (skeleton.economics.paybackMonths === null) {
    return 'No payback — the base-case net return does not turn positive.';
  }
  return `${skeleton.economics.paybackMonths} months (base case)`;
}

/** Human label for the recommendation. */
export function recommendationLabel(
  recommendation: BusinessCaseSkeleton['recommendation'],
): string {
  switch (recommendation) {
    case 'fund':
      return 'FUND';
    case 'shape':
      return 'SHAPE — do not fund as-is';
    case 'kill':
      return 'KILL — do not fund';
    default:
      return String(recommendation).toUpperCase();
  }
}

/** A stable, slug-safe filename stem for an exported artifact. */
export function artifactFilenameStem(
  tenantKey: string,
  artifactId: string,
): string {
  const slug = (s: string): string =>
    s
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '');
  return `abarva-moves-${slug(tenantKey)}-${slug(artifactId)}`;
}

/**
 * The honesty footer every kernel artifact carries. States plainly that every
 * figure is the kernel's, that seed gaps are declared, and that benchmark
 * planning rates are not a quote.
 */
export const HONESTY_FOOTER =
  'Every figure in this document is produced by the Moves Expert Kernel from ' +
  'the tenant’s audited substrate. Absent data is declared a seed gap, ' +
  'never invented. Effort rests on a researched planning rate card — a ' +
  'market range, not a quote. Generated by AbarVa · Moves.';
