// Moves — deterministic starter-template outline generator.
// Turns a governed template definition into a ready-to-use Markdown outline the
// user can download and fill in. Pure + deterministic (built from the catalog),
// NO backend, NO model. This is the "sample doc / placeholder" for a template.

import type { MovePhaseTemplateDefinition, SessionType } from './types';
import { PHASE_LABELS } from './types';

const SESSION_LABEL: Record<SessionType, string> = {
  interview: 'Interview',
  workshop: 'Workshop',
  working_session: 'Working session',
  sme_review: 'SME review',
  decision_review: 'Decision review',
  final_review: 'Final review',
};

/** A downloadable Markdown starter for a template. */
export function buildTemplateOutline(t: MovePhaseTemplateDefinition): string {
  const lines: string[] = [];
  lines.push(`# ${t.label}`);
  lines.push('');
  lines.push(t.clientPurpose);
  lines.push('');
  lines.push(
    `**Phase:** ${PHASE_LABELS[t.phase]}  •  **Session:** ${SESSION_LABEL[t.recommendedSessionType]}  •  **Format:** ${
      t.fileFormat === 'XLSX' ? 'Spreadsheet' : 'Document'
    }`,
  );
  if (t.recommendedAudience.length > 0) {
    lines.push(`**Who should be in the room:** ${t.recommendedAudience.join(', ')}`);
  }
  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('## Sections to complete');
  lines.push('');
  for (const s of t.requiredSections) {
    lines.push(`### ${s.section}`);
    lines.push('');
    lines.push('_Capture your notes here._');
    lines.push('');
  }
  if (t.optionalSections.length > 0) {
    lines.push('## Optional sections');
    lines.push('');
    for (const s of t.optionalSections) {
      lines.push(`### ${s.section}`);
      lines.push('');
      lines.push('_Optional — complete if relevant._');
      lines.push('');
    }
  }
  if (t.sampleQuestions.length > 0) {
    lines.push('## Prompts to guide the discussion');
    lines.push('');
    for (const q of t.sampleQuestions) {
      lines.push(`- ${q}`);
    }
    lines.push('');
  }
  lines.push('---');
  lines.push('');
  lines.push('_Starter template generated by AbarVa. Fill it in, then upload it to this phase._');
  lines.push('');
  return lines.join('\n');
}

/** A safe download filename for a template outline. */
export function templateOutlineFilename(t: MovePhaseTemplateDefinition): string {
  const slug = t.label
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return `${slug || t.templateId}.md`;
}
