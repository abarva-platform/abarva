// EXPORT-2 · OKR Baseline workbook builder.
//
// Pure (spec) -> ExcelJS.Workbook builder. The xlsx renderer dispatcher
// (./xlsx.ts) calls this and serializes the workbook to a buffer; this
// module performs no I/O and no auth.
//
// The OKR Baseline workbook captures a "where are we today" snapshot of
// the metrics a program will move during a fiscal year:
//   • Cover sheet     -> title, cohort, capture timestamp, authors.
//   • Baseline sheet  -> one row per metric (current/target/source/...).
//   • Contradictions  -> only when the spec includes them; soft-yellow.
//   • Provenance      -> source systems + owners (text reference list).
//
// Design source: docs/build/DELIVERABLE_EXPORT_DESIGN.md §2 (taxonomy).
// Worked example for EXPORT-2 (PR #1242 follow-on; design PR #1232).

import 'server-only';

import ExcelJS from 'exceljs';

import type { DeliverableSpec } from '../types';

/** Direction the FY2026 target moves the metric vs. baseline. */
export type OkrBaselineDirection = 'increase' | 'decrease' | 'maintain';

/** One metric row in the OKR baseline sheet. */
export interface OkrBaselineMetric {
  /** Stable metric id, e.g. "kpi:apex:loyalty-rev-fy25". */
  metricId: string;
  /** Human-readable metric name. */
  metricName: string;
  /** Current value as the source records it (e.g. "$2.41B FY2025" or "8%"). */
  currentValue: string;
  /** Target value for FY2026. */
  targetValue: string;
  /** Unit string (e.g. "USD billions" or "percent"). */
  unit: string;
  /** Source system identifier (e.g. "sys:apex:sap-s4"). */
  sourceSystem: string;
  /** Optional source document reference (e.g. "Q1FY26-baseline.xlsx"). */
  sourceDoc?: string;
  /** How the metric is measured (free text). */
  measurementMethod: string;
  /** Owner — typically a person reference (e.g. "person:apex:james-wright"). */
  owner: string;
  /** Confidence score, 0..1 inclusive; rendered as a number cell. */
  confidence?: number;
  /** Free-text caveats; written safely (no formula injection). */
  caveats?: string;
  /** Direction the FY2026 target moves the metric. */
  fy2026Direction: OkrBaselineDirection;
}

/** Optional contradiction / open-question entry on the baseline. */
export interface OkrBaselineContradiction {
  /** Metric id the contradiction concerns. */
  metricId: string;
  /** Free-text description of the contradiction. */
  description: string;
}

/** OKR Baseline payload shape narrowed for this slice. */
export interface OkrBaselinePayload {
  /** Cohort being baselined (e.g. "Top-decile loyalty members"). */
  cohort: string;
  /** ISO timestamp of when the baseline was captured. */
  capturedAt: string;
  /** Metric rows. */
  metrics: ReadonlyArray<OkrBaselineMetric>;
  /** Optional contradictions / open questions. */
  contradictions?: ReadonlyArray<OkrBaselineContradiction>;
}

/** Spec narrowed to the OKR Baseline kind + payload. */
export type OkrBaselineSpec = Omit<DeliverableSpec, 'kind' | 'payload'> & {
  kind: 'okr-baseline';
  payload: OkrBaselinePayload;
};

// --- Brand tokens (mirrors src/scripts/templates/generate-xlsx.ts). ---
const HEADER_FILL = 'FF0A0A0A';
const HEADER_TEXT = 'FFF5F5F0';
const BAND_FILL = 'FFF8F7F4';
const ACCENT_FILL = 'FF2DD4C8';
const CONTRADICTION_FILL = 'FFFFF8C5';
const MUTED_TEXT = 'FF706D66';

/** Sanitize a cell value to prevent formula injection. */
function safeCell(value: string): string {
  // Excel treats =, +, -, @, and tab/CR as formula prefixes. Prefix with a
  // single quote to coerce the cell to a literal string.
  if (value.length === 0) return value;
  const first = value.charAt(0);
  if (first === '=' || first === '+' || first === '-' || first === '@') {
    return `'${value}`;
  }
  return value;
}

/** Build the Cover sheet. */
function writeCover(wb: ExcelJS.Workbook, spec: OkrBaselineSpec): void {
  const ws = wb.addWorksheet('Cover', {
    properties: { tabColor: { argb: ACCENT_FILL } },
    views: [{ state: 'normal', showGridLines: false }],
  });
  ws.getColumn(1).width = 4;
  ws.getColumn(2).width = 110;

  const lines: Array<{ text: string; bold?: boolean; size?: number; color?: string; italic?: boolean }> = [
    { text: spec.title, bold: true, size: 22 },
    ...(spec.subtitle ? [{ text: spec.subtitle, size: 13, color: MUTED_TEXT, italic: true }] : []),
    { text: '' },
    { text: `Cohort: ${spec.payload.cohort}`, size: 12, bold: true },
    { text: `Captured at: ${spec.payload.capturedAt}`, size: 11 },
    {
      text: `Authors: ${(spec.authors ?? []).length > 0 ? (spec.authors ?? []).join(', ') : '—'}`,
      size: 11,
    },
    { text: '' },
    {
      text: `Generated by ${spec.brandSubtitle ?? 'AbarVa · Programs'} at ${new Date().toISOString()}`,
      size: 10,
      color: MUTED_TEXT,
      italic: true,
    },
  ];

  lines.forEach((line, idx) => {
    const row = ws.getRow(idx + 2);
    const cell = row.getCell(2);
    cell.value = safeCell(line.text);
    cell.font = {
      name: line.size && line.size >= 18 ? 'Georgia' : 'Calibri',
      bold: !!line.bold,
      italic: !!line.italic,
      size: line.size ?? 11,
      color: { argb: line.color ?? 'FF0A0A0A' },
    };
    cell.alignment = { vertical: 'middle', horizontal: 'left' };
    row.height = line.size && line.size >= 18 ? 36 : 22;
  });

  // Lock the cover sheet (read-only) — best-effort; consumers can still
  // unprotect with a no-op password.
  ws.protect('', {
    selectLockedCells: true,
    selectUnlockedCells: true,
    formatCells: false,
    formatColumns: false,
    formatRows: false,
    insertRows: false,
    deleteRows: false,
    insertColumns: false,
    deleteColumns: false,
    sort: false,
    autoFilter: false,
    pivotTables: false,
  });
}

/** Baseline sheet header definition. */
const BASELINE_COLUMNS: ReadonlyArray<{ header: string; key: string; width: number }> = [
  { header: 'Metric ID', key: 'metricId', width: 28 },
  { header: 'Metric name', key: 'metricName', width: 38 },
  { header: 'Current value', key: 'currentValue', width: 22 },
  { header: 'Target value', key: 'targetValue', width: 22 },
  { header: 'Unit', key: 'unit', width: 14 },
  { header: 'Direction', key: 'direction', width: 12 },
  { header: 'Source system', key: 'sourceSystem', width: 24 },
  { header: 'Source doc', key: 'sourceDoc', width: 24 },
  { header: 'Measurement method', key: 'measurementMethod', width: 38 },
  { header: 'Owner', key: 'owner', width: 28 },
  { header: 'Confidence', key: 'confidence', width: 12 },
  { header: 'Caveats', key: 'caveats', width: 48 },
];

/** Build the Baseline sheet. */
function writeBaseline(wb: ExcelJS.Workbook, spec: OkrBaselineSpec): void {
  const ws = wb.addWorksheet('Baseline', {
    views: [{ state: 'frozen', ySplit: 1 }],
  });

  ws.columns = BASELINE_COLUMNS.map((c) => ({ header: c.header, key: c.key, width: c.width }));

  const headerRow = ws.getRow(1);
  headerRow.eachCell((cell) => {
    cell.font = { bold: true, size: 11, color: { argb: HEADER_TEXT } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: HEADER_FILL } };
    cell.alignment = { vertical: 'middle', horizontal: 'left', indent: 1 };
    cell.border = { bottom: { style: 'medium', color: { argb: HEADER_FILL } } };
  });
  headerRow.height = 24;

  spec.payload.metrics.forEach((metric, idx) => {
    const row = ws.addRow({
      metricId: safeCell(metric.metricId),
      metricName: safeCell(metric.metricName),
      currentValue: safeCell(metric.currentValue),
      targetValue: safeCell(metric.targetValue),
      unit: safeCell(metric.unit),
      direction: metric.fy2026Direction,
      sourceSystem: safeCell(metric.sourceSystem),
      sourceDoc: metric.sourceDoc !== undefined ? safeCell(metric.sourceDoc) : '',
      measurementMethod: safeCell(metric.measurementMethod),
      owner: safeCell(metric.owner),
      // Number-typed when present so Excel treats it as a number, not a string.
      confidence: typeof metric.confidence === 'number' ? metric.confidence : '',
      caveats: metric.caveats !== undefined ? safeCell(metric.caveats) : '',
    });

    // Row banding — alternating background for readability.
    if (idx % 2 === 1) {
      row.eachCell((cell) => {
        cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: BAND_FILL } };
      });
    }

    // Confidence cell number formatting (0.94 -> 94%).
    if (typeof metric.confidence === 'number') {
      const confidenceCell = row.getCell('confidence');
      confidenceCell.numFmt = '0%';
    }

    row.alignment = { vertical: 'top', horizontal: 'left', wrapText: true, indent: 1 };
  });
}

/** Build the Contradictions sheet (only invoked when present). */
function writeContradictions(
  wb: ExcelJS.Workbook,
  contradictions: ReadonlyArray<OkrBaselineContradiction>,
): void {
  const ws = wb.addWorksheet('Contradictions', {
    views: [{ state: 'frozen', ySplit: 1 }],
    properties: { tabColor: { argb: CONTRADICTION_FILL } },
  });
  ws.columns = [
    { header: 'Metric ID', key: 'metricId', width: 28 },
    { header: 'Description', key: 'description', width: 90 },
  ];
  const headerRow = ws.getRow(1);
  headerRow.eachCell((cell) => {
    cell.font = { bold: true, size: 11, color: { argb: HEADER_TEXT } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: HEADER_FILL } };
    cell.alignment = { vertical: 'middle', horizontal: 'left', indent: 1 };
  });
  headerRow.height = 24;

  contradictions.forEach((c) => {
    const row = ws.addRow({
      metricId: safeCell(c.metricId),
      description: safeCell(c.description),
    });
    row.eachCell((cell) => {
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: CONTRADICTION_FILL } };
      cell.alignment = { vertical: 'top', horizontal: 'left', wrapText: true, indent: 1 };
    });
  });
}

/** Build the Provenance reference sheet. */
function writeProvenance(wb: ExcelJS.Workbook, spec: OkrBaselineSpec): void {
  const ws = wb.addWorksheet('Provenance', {
    views: [{ state: 'frozen', ySplit: 1 }],
  });
  ws.columns = [
    { header: 'Reference type', key: 'kind', width: 18 },
    { header: 'Identifier', key: 'identifier', width: 36 },
    { header: 'Used by', key: 'usedBy', width: 80 },
  ];
  const headerRow = ws.getRow(1);
  headerRow.eachCell((cell) => {
    cell.font = { bold: true, size: 11, color: { argb: HEADER_TEXT } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: HEADER_FILL } };
    cell.alignment = { vertical: 'middle', horizontal: 'left', indent: 1 };
  });
  headerRow.height = 24;

  // Aggregate unique source systems and owners.
  const systems = new Map<string, string[]>();
  const owners = new Map<string, string[]>();
  for (const m of spec.payload.metrics) {
    const sys = systems.get(m.sourceSystem) ?? [];
    sys.push(m.metricId);
    systems.set(m.sourceSystem, sys);
    const own = owners.get(m.owner) ?? [];
    own.push(m.metricId);
    owners.set(m.owner, own);
  }

  for (const [sys, ids] of systems) {
    ws.addRow({
      kind: 'source system',
      identifier: safeCell(sys),
      usedBy: safeCell(ids.join(', ')),
    });
  }
  for (const [own, ids] of owners) {
    ws.addRow({
      kind: 'owner',
      identifier: safeCell(own),
      usedBy: safeCell(ids.join(', ')),
    });
  }

  ws.eachRow((row, rowNumber) => {
    if (rowNumber === 1) return;
    row.alignment = { vertical: 'top', horizontal: 'left', wrapText: true, indent: 1 };
  });
}

/**
 * Build a populated `ExcelJS.Workbook` for an OKR baseline spec. Pure —
 * no I/O. The xlsx renderer dispatcher serializes the returned workbook
 * to a buffer.
 */
export function buildOkrBaselineWorkbook(spec: OkrBaselineSpec): ExcelJS.Workbook {
  const wb = new ExcelJS.Workbook();
  wb.creator = 'AbarVa Programs';
  wb.created = new Date();
  wb.title = spec.title;
  if (spec.subtitle !== undefined) {
    wb.description = spec.subtitle;
  }

  writeCover(wb, spec);
  writeBaseline(wb, spec);
  if (spec.payload.contradictions !== undefined && spec.payload.contradictions.length > 0) {
    writeContradictions(wb, spec.payload.contradictions);
  }
  writeProvenance(wb, spec);

  return wb;
}
