import {
  autoGenerateDiscoveryPlanOnCharterApproval,
  discoveryPlanSourceArtifactRef,
} from "../auto-generate-discovery-plan";
import type { MoveBusinessCaseInput } from "@/lib/programs/move-business-case";

const moveInput: MoveBusinessCaseInput = {
  name: "IROPS Care Recovery",
  tenant_key: "skyharbor",
  tenant_name: "SkyHarbor Air",
  function_pack_key: "AI_OPERATIONS_DECISION_SUPPORT",
  charter: {
    sponsor: "Chief Operations Officer",
    stakeholders: "Ops Control, Airport Ops, Customer Care",
    success_metrics: "Reduce recovery time and customer-care backlog",
    value_range: "$20M-$40M planning range",
    scope: "IROP recovery decision support",
  },
  baseline_metrics: [],
  governed_evidence_items: [
    {
      id: "11111111-1111-4111-8111-111111111111",
      title: "Current-state systems inventory",
      summary:
        "Legacy crew, aircraft, and customer-care systems are batch-linked.",
      evidence_type: "systems_landscape",
      confidence: "high",
      phase: 1,
      created_at: "2026-06-12T10:00:00.000Z",
    },
  ],
};

describe("autoGenerateDiscoveryPlanOnCharterApproval", () => {
  it("skips when the move id is unavailable", async () => {
    await expect(
      autoGenerateDiscoveryPlanOnCharterApproval({
        tenantKey: "skyharbor",
        moveId: null,
        renderedBy: "user_1",
      }),
    ).resolves.toEqual({
      status: "skipped",
      reason: "move id unavailable",
    });
  });

  it("does not regenerate when a discovery plan already exists", async () => {
    const latest = jest.fn().mockResolvedValue({
      id: "generated_existing",
      sourceArtifactRef: discoveryPlanSourceArtifactRef("move_1"),
    });
    const loadMoveInput = jest.fn();
    const run = jest.fn();

    await expect(
      autoGenerateDiscoveryPlanOnCharterApproval(
        {
          tenantKey: "skyharbor",
          moveId: "move_1",
          renderedBy: "user_1",
        },
        { latest, loadMoveInput, run },
      ),
    ).resolves.toMatchObject({
      status: "already_exists",
      artifactId: "generated_existing",
      sourceArtifactRef: "move:move_1:discovery_plan",
    });
    expect(loadMoveInput).not.toHaveBeenCalled();
    expect(run).not.toHaveBeenCalled();
  });

  it("generates and persists the discovery plan with lineage", async () => {
    const latest = jest.fn().mockResolvedValue(null);
    const loadMoveInput = jest.fn().mockResolvedValue(moveInput);
    const run = jest.fn().mockResolvedValue({
      ok: true,
      html: "<article>Discovery Plan</article>",
      evidenceCount: 6,
      citedInputIds: ["11111111-1111-4111-8111-111111111111"],
      quality: { blockers: [], warnings: [] },
      passTrace: [{ responseId: "resp_1" }],
    });
    const persist = jest.fn().mockResolvedValue({ id: "generated_1" });

    await expect(
      autoGenerateDiscoveryPlanOnCharterApproval(
        {
          tenantKey: "skyharbor",
          moveId: "move_1",
          renderedBy: "user_1",
          generatedOn: "2026-06-12T12:00:00.000Z",
        },
        { latest, loadMoveInput, run, persist },
      ),
    ).resolves.toMatchObject({
      status: "generated",
      artifactId: "generated_1",
      sourceArtifactRef: "move:move_1:discovery_plan",
      evidenceCount: 6,
      citedInputCount: 1,
    });

    expect(run).toHaveBeenCalledWith(
      expect.objectContaining({
        moveInput,
        moveId: "move_1",
        tenantId: "skyharbor",
        userId: "user_1",
        deliverableType: "discovery_plan",
        phaseOrStage: "P2_discovery",
        minEvidence: 1,
      }),
    );
    expect(persist).toHaveBeenCalledWith(
      expect.objectContaining({
        clientId: "skyharbor",
        moveId: "move_1",
        artifactId: "discovery_plan",
        title: "Discovery Plan",
        citedInputIds: ["11111111-1111-4111-8111-111111111111"],
        generationEgressAudit: "resp_1",
      }),
    );
  });

  it("reports a blocked result when the orchestrator refuses to author", async () => {
    const latest = jest.fn().mockResolvedValue(null);
    const loadMoveInput = jest.fn().mockResolvedValue(moveInput);
    const run = jest.fn().mockResolvedValue({
      ok: false,
      blockedReason: "move has 0 recorded evidence item(s)",
      evidenceCount: 0,
      citedInputIds: [],
    });
    const persist = jest.fn();

    await expect(
      autoGenerateDiscoveryPlanOnCharterApproval(
        {
          tenantKey: "skyharbor",
          moveId: "move_1",
          renderedBy: "user_1",
        },
        { latest, loadMoveInput, run, persist },
      ),
    ).resolves.toMatchObject({
      status: "blocked",
      reason: "move has 0 recorded evidence item(s)",
      evidenceCount: 0,
      citedInputCount: 0,
    });
    expect(persist).not.toHaveBeenCalled();
  });
});
