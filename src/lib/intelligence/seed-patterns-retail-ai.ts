function canonicalBody(def: RetailAIPatternDefinition): string {
  return [
    '## Summary',
    def.valueHypothesis,
    '',
    '## When to apply',
    def.problem,
    '',
    '## Agentic workflow',
    def.workflow,
    '',
    '## Evidence required',
    def.evidence.map((item) => `- ${item}`).join('\n'),
    '',
    '## Failure modes',
    def.failureModes.map((item) => `- ${item}`).join('\n'),
  ].join('\n');
}

