/** Best-effort: pull the vendor name from any authored d12 shortlist or
 *  d13 vendor responses body. When more than one vendor is on file,
 *  we leave the field blank rather than guessing wrong. */
function vendorNameFromContext(ctx: SourceGenerationContext): string {
  const shortlist = ctx.artifactStates.find((a) => a.artifactCode === 'd12_vendor_shortlist');
  const responses = ctx.artifactStates.find((a) => a.artifactCode === 'd13_vendor_responses');
  const body = shortlist?.body ?? responses?.body ?? null;
  if (!body) return '';
  const vendors = new Set<string>();
  for (const line of body.split('\n')) {
    const m = line.match(/^[-*]\s+\*\*([^*]+)\*\*/);
    if (m && m[1]) vendors.add(m[1].trim());
    if (vendors.size > 1) return '';
  }
  return vendors.size === 1 ? Array.from(vendors)[0]! : '';
}

/** Parse `| AI-001 | present | notes... |` rows from an authored body. */
function parseStatusOverrides(md: string): Map<string, string> {
  const out = new Map<string, string>();
  for (const line of md.split('\n')) {
    if (!/^\s*\|/.test(line)) continue;
    const cells = line
      .split('|')
      .map((c) => c.trim())
      .filter((c) => c.length > 0);
    if (cells.length < 2) continue;
    const id = cells[0] ?? '';
    if (!/^AI-\d{3}$/i.test(id)) continue;
    const status = (cells[1] ?? '').toLowerCase();
    if (['present', 'partial', 'missing', 'n/a'].includes(status)) {
      out.set(id.toUpperCase(), status);
    }
    if (cells[2]) out.set(`${id.toUpperCase()}::notes`, cells[2] ?? '');
  }
  return out;
}
