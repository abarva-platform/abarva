// Source · dx6a AI Clause Gap payload binder.
//
// Methodology §6 ships a fixed clause library — this binder loads that
// canonical library + initial status "missing" for every clause so the
// buyer's review starts from a defensible baseline (assume nothing is
// in the contract until proven otherwise). The artifact body, if
// authored, can override individual clause statuses (parsed from a
// markdown table). Vendor name is best-effort from the d12 shortlist /
// d13 vendor responses if a single vendor has been identified — else
// blank for the buyer to fill.

import 'server-only';

import type { SourceGenerationContext } from '@/lib/source/agent-generation/types';
import type {
  AiClauseGapPayload,
  AiClauseRow,
} from '../renderers/ai-clause-gap';

export function buildAiClauseGapPayloadFromContext(
  ctx: SourceGenerationContext,
  generatedAt: string,
): AiClauseGapPayload {
  const authored = ctx.artifactStates.find(
    (a) => a.artifactCode === 'dx6a_ai_clause_gap',
  );
  const overrides = authored?.body ? parseStatusOverrides(authored.body) : new Map();
  const vendorHint = vendorNameFromContext(ctx);
  const clauses = canonicalClauseLibrary().map((c) => {
    const status = overrides.get(c.id) ?? c.status;
    const notes = overrides.get(`${c.id}::notes`) ?? c.notes;
    return { ...c, status, notes };
  });

  return {
    tenantName: ctx.tenantName,
    eventCode: ctx.event.code,
    eventName: ctx.event.name,
    issuedBy: ctx.event.owner ?? undefined,
    generatedAt,
    vendorName: vendorHint,
    clauses,
  };
}

