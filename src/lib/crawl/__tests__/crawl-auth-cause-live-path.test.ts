/** A Clerk sign-in ticket is an unverified-readable JWT; only `iss` is read. */
function ticketIssuedBy(issuer: string): string {
  const b64 = (value: object) =>
    Buffer.from(JSON.stringify(value))
      .toString("base64")
      .replace(/\+/g, "-")
      .replace(/\//g, "_")
      .replace(/=+$/, "");
  return [
    b64({ alg: "RS256", typ: "JWT" }),
    b64({ iss: issuer, sid: "sit_2abcDEF" }),
    "signature-not-verified-here",
  ].join(".");
}

/** `pk_test_<base64 of "<frontend-api-host>$">`, the real publishable-key shape. */
function publishableKeyFor(host: string): string {
  return `pk_test_${Buffer.from(`${host}$`).toString("base64")}`;
}

/**
 * Drives the REAL crawl handler
 * (`signInPersona` in `src/lib/crawl/persona-switcher.ts`) with a Clerk client
 * that mints successfully and a page that refuses the ticket exactly the way
 * `clerk.browser.js` refused it in run 37150673373 — because a classifier
 * nothing calls is the vacuous control this backlog keeps finding.
 */
const mintSignInToken = jest.fn();
const getUserList = jest.fn();

jest.mock("@clerk/backend", () => ({
  createClerkClient: () => ({
    users: { getUserList: (...args: unknown[]) => getUserList(...args) },
    signInTokens: {
      createSignInToken: (...args: unknown[]) => mintSignInToken(...args),
    },
  }),
}));

jest.mock("@/lib/crawl/clerk-testing-token", () => ({
  ...jest.requireActual("@/lib/crawl/clerk-testing-token"),
  // The live run proves the testing token installs fine; it is not the subject.
  createClerkTestingTokenForCrawl: async () => null,
  installClerkTestingTokenInterceptor: async () => undefined,
}));

describe("C-639 · the crawl's own output names the cause", () => {
  const BASE_URL = "https://app.abarva.ai";
  const REDEEM_REFUSAL =
    "page.evaluate: e: This ticket is invalid. Make sure you're using a valid ticket generated by Clerk.";
  let secretKey: string | undefined;
  let publishableKey: string | undefined;
  let warnings: string[];

  function pageThatRefusesTheTicket() {
    return {
      goto: jest.fn(async () => undefined),
      waitForFunction: jest.fn(async () => undefined),
      evaluate: jest.fn(async () => {
        throw new Error(REDEEM_REFUSAL);
      }),
      context: () => ({ addCookies: jest.fn(async () => undefined) }),
    };
  }

  async function signInWithRefusedTicket(ticketIssuer: string) {
    const { signInPersona, CRAWL_PERSONAS } =
      await import("@/lib/crawl/persona-switcher");
    getUserList.mockResolvedValue({ data: [{ id: "user_2abc" }] });
    mintSignInToken.mockResolvedValue({ token: ticketIssuedBy(ticketIssuer) });
    const page = pageThatRefusesTheTicket();
    let thrown = "";
    await signInPersona(page as never, CRAWL_PERSONAS[0], {
      baseUrl: BASE_URL,
    }).catch((error: unknown) => {
      thrown = error instanceof Error ? error.message : String(error);
    });
    return { thrown, page };
  }

  beforeEach(() => {
    secretKey = process.env.CLERK_SECRET_KEY;
    publishableKey = process.env.NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY;
    process.env.CLERK_SECRET_KEY = "sk_test_not-a-real-key";
    process.env.NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY =
      publishableKeyFor("clerk.abarva.ai");
    warnings = [];
    jest.spyOn(console, "warn").mockImplementation((...args: unknown[]) => {
      warnings.push(args.map(String).join(" "));
    });
    jest.spyOn(console, "log").mockImplementation(() => undefined);
    getUserList.mockReset();
    mintSignInToken.mockReset();
  });

  afterEach(() => {
    jest.restoreAllMocks();
    if (secretKey === undefined) delete process.env.CLERK_SECRET_KEY;
    else process.env.CLERK_SECRET_KEY = secretKey;
    if (publishableKey === undefined)
      delete process.env.NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY;
    else process.env.NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY = publishableKey;
  });

  it("still fails, and the failure now says the OPERATOR owns a mismatched instance", async () => {
    const { thrown } = await signInWithRefusedTicket(
      "https://sample-app-42.clerk.accounts.dev",
    );

    // It must STILL throw: a crawl that reached no product route may not pass.
    expect(thrown).not.toBe("");
    expect(thrown).toContain("crawl_auth_cause:");
    expect(thrown).toContain("instance_mismatch");
    expect(thrown).toContain("owner=operator-secret");
    expect(thrown).toContain("mint_instance=sample-app-42.clerk.accounts.dev");
    expect(thrown).toContain("redeem_instance=clerk.abarva.ai");
    // and the same line reaches the log a human greps.
    expect(warnings.some((line) => line.includes("instance_mismatch"))).toBe(
      true,
    );
  });

  it("says THIS LANE owns it when the instances agree and the ticket is still refused", async () => {
    const { thrown } = await signInWithRefusedTicket("https://clerk.abarva.ai");

    expect(thrown).toContain("crawl_auth_cause:");
    expect(thrown).toContain("redemption_defect");
    expect(thrown).toContain("owner=this-lane");
  });

  it("stages a refused MINT upstream of the browser and never opens a page", async () => {
    const { signInPersona, CRAWL_PERSONAS } =
      await import("@/lib/crawl/persona-switcher");
    getUserList.mockResolvedValue({ data: [] });
    const page = pageThatRefusesTheTicket();
    let thrown = "";
    await signInPersona(page as never, CRAWL_PERSONAS[0], {
      baseUrl: BASE_URL,
    }).catch((error: unknown) => {
      thrown = error instanceof Error ? error.message : String(error);
    });

    expect(thrown).toContain("mint_rejected");
    expect(thrown).toContain("crawl_clerk_ticket_user_not_found");
    expect(page.goto).not.toHaveBeenCalled();
    expect(page.evaluate).not.toHaveBeenCalled();
  });
});
