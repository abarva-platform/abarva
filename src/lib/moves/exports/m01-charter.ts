// ── Public builder ────────────────────────────────────────────────────────

/**
 * Build a populated `docx.Document` for an M01 Charter spec. Pure —
 * no I/O. The caller serializes the returned document to a buffer.
 */
export function buildM01CharterDocument(spec: M01CharterSpec): Document {
  const generatedAt =
    spec.generatedAt !== undefined ? new Date(spec.generatedAt) : new Date();

  const children = [
    ...buildCoverPage(spec, generatedAt),
    ...buildRationaleSection(),
    ...buildSponsorSection(),
    ...buildScopeSection(),
    ...buildMetadataSection(),
    ...buildKillCriterionSection(),
    ...buildFooter(spec),
  ];

  return new Document({
    creator: 'AbarVa Moves',
    title: spec.documentTitle,
    styles: DOCX_HEADING_STYLES,
    sections: [{ properties: {}, children }],
  });
}

// ── Render entry point ────────────────────────────────────────────────────

/** DOCX MIME type. */
const DOCX_CONTENT_TYPE =
  'application/vnd.openxmlformats-officedocument.wordprocessingml.document';

/**
 * Render an M01 Charter spec to a binary DOCX buffer.
 *
 * Entry point for the Moves export route. Returns a fully populated
 * `M01CharterRenderResult` with buffer, filename, content type, and size.
 */
export async function renderM01Charter(
  spec: M01CharterSpec,
): Promise<M01CharterRenderResult> {
  const document = buildM01CharterDocument(spec);
  const buffer = await Packer.toBuffer(document);
  const sizeBytes = buffer.byteLength;

  const slug = spec.documentTitle
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

  const filename = `${spec.moveId.toLowerCase()}-charter-${slug}.docx`;

  return {
    buffer,
    filename,
    contentType: DOCX_CONTENT_TYPE,
    sizeBytes,
  };
}
