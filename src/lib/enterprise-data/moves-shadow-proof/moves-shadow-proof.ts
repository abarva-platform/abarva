async function readJson<T>(filePath: string): Promise<T> {
  return JSON.parse(await fs.readFile(filePath, "utf8")) as T;
}

async function readCsv<T>(filePath: string): Promise<T[]> {
  const parsed = parseCsv(await fs.readFile(filePath, "utf8"));
  return parsed.rows as unknown as T[];
}

function searchable(record: CanonicalIngestionRecord): string {
  return [
    record.sourceObjectId,
    record.objectType,
    record.domain,
    ...Object.values(record.attributes).map((value) => stringify(value.value)),
    ...record.evidenceReferences.map((reference) => reference.excerpt ?? ""),
  ]
    .join(" ")
    .toLowerCase();
}

function stringify(value: CanonicalValue["value"]): string {
  if (typeof value === "string") return value;
  if (value === null || value === undefined) return "";
  return JSON.stringify(value);
}

function splitList(input: string): string[] {
  return input
    .split(/\s*[;|]\s*/g)
    .map((part) => part.trim())
    .filter(Boolean);
}

function unique<T>(items: T[]): T[] {
  return Array.from(new Set(items.filter(Boolean)));
}

function quote(input: unknown): string {
  const value = String(input ?? "");
  return `"${value.replaceAll('"', '""')}"`;
}

function escapeHtml(input: unknown): string {
  return String(input ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}
