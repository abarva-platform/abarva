function blockersForPhase(
  phase: PhaseReadiness["phase"],
  status: PhaseStatus,
): string[] {
  const blockers = [
    "Candidate is inactive and cannot advance a live Move.",
    "Operator approval and signed-in runtime proof are required before active use.",
  ];
  if (phase === "P1" || phase === "P4") {
    blockers.push(
      "Human sponsorship, decision rights, and commercial attestation remain outside the dry-run packet.",
    );
  }
  if (phase === "P5") {
    blockers.push(
      "Tower commitments are preview-only until Outcome Ledger writeback is explicitly approved.",
    );
  }
  if (status === "blocked") {
    blockers.push(
      "Phase cannot be treated as runtime-ready from candidate evidence.",
    );
  }
  return blockers;
}

