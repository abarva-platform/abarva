function phaseMatrixCsv(phases: PhaseReadiness[]): string {
  const header = [
    "phase",
    "name",
    "status",
    "candidate_inputs",
    "evidence_refs",
    "generated_artifacts",
    "blockers",
  ].join(",");
  const rows = phases.map((phase) =>
    [
      phase.phase,
      quote(phase.name),
      phase.status,
      phase.candidateInputs,
      phase.evidenceRefs.length,
      quote(phase.generatedArtifacts.join(" | ")),
      quote(phase.blockers.join(" | ")),
    ].join(","),
  );
  return `${[header, ...rows].join("\n")}\n`;
}

