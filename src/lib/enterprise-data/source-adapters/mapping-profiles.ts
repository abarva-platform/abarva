import type {
  MappingProfile,
  MappingRule,
} from "../contracts/mapping-registry";

type OrganizationRuleSpec = {
  id: string;
  field: string;
  objectType: string;
  attribute: string;
  transform?: MappingRule["transform"];
  required?: boolean;
  targetDomain?: MappingRule["targetDomain"];
  confidence?: number;
};

function organizationRule(
  mappingProfile: string,
  spec: OrganizationRuleSpec,
): MappingRule {
  return {
    mappingRuleId: `${mappingProfile.replace(/\/v\d+$/, "").replace(/\//g, "-")}.${spec.id}`,
    mappingProfile,
    sourceClass: "organization_functions",
    sourceField: spec.field,
    targetDomain: spec.targetDomain ?? "enterprise_structure",
    targetObjectType: spec.objectType,
    targetAttribute: spec.attribute,
    transform: spec.transform ?? "trim",
    required: spec.required ?? false,
    confidenceDefault: spec.confidence ?? 0.86,
    validFrom: "2026-08-14",
  };
}

function organizationRules(
  mappingProfile: string,
  specs: OrganizationRuleSpec[],
): MappingRule[] {
  return specs.map((spec) => organizationRule(mappingProfile, spec));
}

type SourceRuleSpec = OrganizationRuleSpec;

function sourceRule(
  sourceClass: MappingRule["sourceClass"],
  mappingProfile: string,
  spec: SourceRuleSpec,
): MappingRule {
  return {
    ...organizationRule(mappingProfile, spec),
    sourceClass,
  };
}

function sourceRules(
  sourceClass: MappingRule["sourceClass"],
  mappingProfile: string,
  specs: SourceRuleSpec[],
): MappingRule[] {
  return specs.map((spec) => sourceRule(sourceClass, mappingProfile, spec));
}

