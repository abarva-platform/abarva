/** A light, board-grade PDF table — same visual language as `lightTable()`
 *  (muted uppercase header, hairline row dividers, no navy fill), since
 *  `PDF_STYLES.table`'s default header is a solid navy fill built for
 *  Source's house style, not this orchestrator's. */
function pdfLightTable(
  columns: string[],
  rows: string[][],
  statusColumn?: number,
): ReactElement {
  const statusCol =
    typeof statusColumn === "number" &&
    statusColumn >= 0 &&
    statusColumn < columns.length
      ? statusColumn
      : null;
  return (
    <PdfView style={{ marginVertical: 8 }}>
      <PdfView
        style={{
          flexDirection: "row",
          borderBottomColor: PDF_COLORS.RULE,
          borderBottomWidth: 1,
        }}
      >
        {columns.map((c, i) => (
          <PdfView
            key={i}
            style={{ flex: 1, paddingHorizontal: 6, paddingVertical: 4 }}
          >
            <PdfText
              style={{
                fontSize: 7,
                fontFamily: PDF_FONTS.BODY_BOLD,
                color: PDF_COLORS.MUTED,
                textTransform: "uppercase",
                letterSpacing: 0.5,
              }}
            >
              {c}
            </PdfText>
          </PdfView>
        ))}
      </PdfView>
      {rows.map((row, ri) => (
        <PdfView
          key={ri}
          wrap={false}
          style={{
            flexDirection: "row",
            borderBottomColor:
              ri === rows.length - 1 ? "transparent" : "#EFECE5",
            borderBottomWidth: ri === rows.length - 1 ? 0 : 0.5,
          }}
        >
          {columns.map((_, i) => {
            const tone =
              statusCol !== null && i === statusCol
                ? CELL_TONE_HEX[cellTone(row[i] ?? "")]
                : null;
            const shaded = tone && tone.fill ? tone : null;
            return (
              <PdfView
                key={i}
                style={{
                  flex: 1,
                  paddingHorizontal: 6,
                  paddingVertical: 4,
                  ...(shaded ? { backgroundColor: `#${shaded.fill}` } : {}),
                }}
              >
                <PdfText
                  style={{
                    fontSize: 9,
                    color: shaded ? `#${shaded.text}` : PDF_COLORS.HEADER,
                    ...(shaded ? { fontFamily: PDF_FONTS.BODY_BOLD } : {}),
                  }}
                >
                  {row[i] ?? ""}
                </PdfText>
              </PdfView>
            );
          })}
        </PdfView>
      ))}
    </PdfView>
  );
}

function tableToPdf(table: RenderableTable): ReactElement {
  if (table.rows.length === 0) {
    return (
      <PdfText
        style={{
          ...PDF_STYLES.body,
          fontFamily: PDF_FONTS.BODY_ITALIC,
          color: PDF_COLORS.MUTED,
        }}
      >
        ({table.title}: see Excel companion exhibit)
      </PdfText>
    );
  }
  return pdfLightTable(table.columns, table.rows, table.statusColumn);
}

/** Rasterise one declared exhibit into the PDF; missing visuals fail closed. */
function exhibitToPdfBlock(
  exhibit: RenderableExhibit,
  index: number,
): ReactElement | null {
  const rawSvg = exhibitSvg(exhibit, index);
  if (!rawSvg) return null;
  const svg = withXmlns(resolveSvgTokens(rawSvg));
  let imageNode: ReactElement;
  try {
    const { png, aspect } = rasteriseSvg(svg, 3);
    const width = 468; // LETTER page width (612pt) minus 2×48pt margin, minus a little breathing room
    const height = Math.round(width / aspect);
    imageNode = (
      <PdfImage
        src={{ data: png, format: "png" }}
        style={{ width, height, marginTop: 6, marginBottom: 4 }}
      />
    );
  } catch (err) {
    throw new Error(`pdf_exhibit_rasterisation_failed:${exhibit.key}`, {
      cause: err,
    });
  }
  return (
    <PdfView key={exhibit.key} wrap={false} style={{ marginBottom: 10 }}>
      <PdfText style={PDF_STYLES.h3}>{exhibit.title}</PdfText>
      {imageNode}
      <PdfText
        style={{
          ...PDF_STYLES.body,
          fontFamily: PDF_FONTS.BODY_ITALIC,
          color: PDF_COLORS.MUTED,
          fontSize: 8,
        }}
      >
        {exhibit.description}
      </PdfText>
    </PdfView>
  );
}

