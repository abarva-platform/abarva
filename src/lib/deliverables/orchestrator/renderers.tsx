type PptxExhibitRef = { exhibit: RenderableExhibit; index: number };
type PptxStoryPage =
  | { kind: "narrative"; slide: RenderableDeckSlide; exhibit?: PptxExhibitRef }
  | { kind: "paired-narrative"; slides: [RenderableDeckSlide, RenderableDeckSlide] }
  | { kind: "exhibit"; exhibit: PptxExhibitRef };

function compactArchitectureStory(
  pages: PptxStoryPage[],
  maxPages: number,
): PptxStoryPage[] {
  const compact = [...pages];
  const sourceNotes = (slide: RenderableDeckSlide) =>
    slide.speakerNotes?.startsWith("Architecture source statements:")
      ? slide.speakerNotes
      : [
          "Architecture source statements:",
          slide.title,
          slide.governingMessage,
          ...(slide.points ?? []),
          slide.speakerNotes,
          slide.citationsUsed?.length
            ? `Citations: [${slide.citationsUsed.join(", ")}]`
            : undefined,
        ]
          .filter(Boolean)
          .join("\n");
  const mergeAt = (index: number) => {
    const left = compact[index] as Extract<PptxStoryPage, { kind: "narrative" }>;
    const right = compact[index + 1] as Extract<PptxStoryPage, { kind: "narrative" }>;
    const candidates = [
      ...(left.slide.points ?? []),
      right.slide.governingMessage,
      ...(right.slide.points ?? []),
    ].filter((point) => point !== left.slide.governingMessage);
    compact.splice(index, 2, {
      kind: "narrative",
      slide: {
        ...left.slide,
        points: [...new Set(candidates)].slice(0, 3),
        speakerNotes: `${sourceNotes(left.slide)}\n\n${sourceNotes(right.slide)}`,
        citationsUsed: [
          ...new Set([
            ...(left.slide.citationsUsed ?? []),
            ...(right.slide.citationsUsed ?? []),
          ]),
        ],
      },
    });
  };
  while (compact.length > maxPages) {
    let index = -1;
    let smallestPair = Number.POSITIVE_INFINITY;
    for (let i = 0; i < compact.length - 1; i += 1) {
      const left = compact[i];
      const right = compact[i + 1];
      if (
        left.kind !== "narrative" ||
        right.kind !== "narrative" ||
        left.exhibit ||
        right.exhibit
      ) continue;
      const size = sourceNotes(left.slide).length + sourceNotes(right.slide).length;
      if (size < smallestPair) {
        smallestPair = size;
        index = i;
      }
    }
    if (index < 0) break; // refuse rather than drop an exhibit
    mergeAt(index);
  }
  // Thin beats merge up even when the numerical ceiling has already cleared.
  // Leave image pages alone: an exhibit is substance in its own right.
  const plain = (page: PptxStoryPage): page is Extract<PptxStoryPage, { kind: "narrative" }> =>
    page.kind === "narrative" && !page.exhibit;
  const thin = (page: PptxStoryPage) =>
    plain(page) && (page.slide.points?.length ?? 0) < 2;
  while (compact.length > 1) {
    let index = compact.findIndex(
      (page, i) => i < compact.length - 1 &&
        thin(page) && thin(compact[i + 1]),
    );
    if (index < 0) {
      const weak = compact.findIndex(thin);
      if (weak < 0) break;
      if (weak > 0 && plain(compact[weak - 1])) index = weak - 1;
      else if (weak + 1 < compact.length && plain(compact[weak + 1])) index = weak;
      else break;
    }
    mergeAt(index);
  }
  return compact;
}

function composePptxStory(
  doc: RenderableDeliverable,
  renderableExhibits: PptxExhibitRef[],
): PptxStoryPage[] {
  const pages: PptxStoryPage[] = [];
  const exhibitByKey = new Map(
    renderableExhibits.map((entry) => [entry.exhibit.key, entry]),
  );
  const pairedKeys = new Set<string>();
  const authored = (doc.deckSlides ?? []).filter(
    (slide) => slide.governingMessage.trim().length > 0,
  );
  const story: RenderableDeckSlide[] = authored.length
    ? authored
    : doc.generatedSections.map((section) => {
        const source = sectionSlideText(
          normalizeSectionMarkdown(section.bodyMarkdown, section.title),
          section.title,
          Number.MAX_SAFE_INTEGER,
        );
        return {
          title: source.governingIsTitle ? undefined : section.title,
          governingMessage: source.governing,
          points: source.bullets,
          speakerNotes: [
            section.citationsUsed.length
              ? `Grounding: ${section.groundingMode}; citations [${section.citationsUsed.join(", ")}]`
              : undefined,
            source.heldOffFace.length
              ? `In full (too long for the slide face):\n${source.heldOffFace.join("\n")}`
              : undefined,
          ]
            .filter(Boolean)
            .join("\n"),
        } satisfies RenderableDeckSlide;
      });

  for (const slide of story) {
    const points = slide.points ?? [];
    const chunks: string[][] = [];
    for (let i = 0; i < points.length; i += 3) {
      chunks.push(points.slice(i, i + 3));
    }
    if (chunks.length === 0) chunks.push([]);
    chunks.forEach((chunk, index) => {
      const linked =
        index === 0 && slide.exhibitKey
          ? exhibitByKey.get(slide.exhibitKey)
          : undefined;
      if (linked) pairedKeys.add(linked.exhibit.key);
      pages.push({
        kind: "narrative",
        slide: {
          ...slide,
          title:
            index > 0 && slide.title
              ? `${slide.title} — continued`
              : slide.title,
          points: chunk,
          exhibitKey: linked?.exhibit.key,
        },
        ...(linked ? { exhibit: linked } : {}),
      });
    });
  }
  for (const exhibit of renderableExhibits) {
    if (!pairedKeys.has(exhibit.exhibit.key)) {
      pages.push({ kind: "exhibit", exhibit });
    }
  }
  return pages;
}

function addPptxTableLayout(
  pptx: PptxGenJSInstance,
  table: RenderableTable,
  doc: RenderableDeliverable,
  slideNumber: number,
  totalSlides: number,
): void {
  const slide = pptx.addSlide();
  slide.background = { color: PPTX_COLOR.cream };
  addPptxChrome(slide, doc, slideNumber, totalSlides);
  slide.addText(safePptxText(table.title), {
    x: PPTX_GRID.x(0),
    y: 0.85,
    w: PPTX_GRID.w(12),
    h: 0.6,
    fontFace: PPTX_FONT.display,
    fontSize: 20,
    color: PPTX_COLOR.ink,
    fit: "shrink",
  });
  if (table.rows.length === 0) {
    slide.addText(`(${table.title}: see Excel companion exhibit)`, {
      x: PPTX_GRID.x(0),
      y: 2,
      w: PPTX_GRID.w(12),
      h: 0.5,
      fontFace: PPTX_FONT.body,
      fontSize: 12,
      italic: true,
      color: PPTX_COLOR.muted,
    });
    return;
  }
  // A dark header row reads as a board table rather than a spreadsheet dump —
  // it is the single change that most distinguishes an executive exhibit from a
  // printed grid (the gold-standard decks use a dark header band on every table).
  const header = table.columns.map((c) => ({
    text: c,
    options: {
      bold: true,
      color: PPTX_COLOR.white,
      fontFace: PPTX_FONT.body,
      fontSize: 9,
      fill: { color: PPTX_COLOR.ink },
    },
  }));
  const statusCol =
    typeof table.statusColumn === "number" &&
    table.statusColumn >= 0 &&
    table.statusColumn < table.columns.length
      ? table.statusColumn
      : null;
  const bodyRows = table.rows.slice(0, 14).map((row) =>
    row.map((cell, colIndex) => {
      // Colour the declared status/RAG/ownership column by its value so the
      // table reads at a glance; every other cell renders plain.
      if (statusCol !== null && colIndex === statusCol) {
        const tone = CELL_TONE_HEX[cellTone(cell)];
        return {
          text: cell,
          options: {
            color: tone.text,
            bold: tone.fill !== null,
            fontFace: PPTX_FONT.body,
            fontSize: 10,
            ...(tone.fill ? { fill: { color: tone.fill } } : {}),
          },
        };
      }
      return {
        text: cell,
        options: {
          color: PPTX_COLOR.ink,
          fontFace: PPTX_FONT.body,
          fontSize: 10,
        },
      };
    }),
  );
  slide.addTable([header, ...bodyRows], {
    x: PPTX_GRID.x(0),
    y: SLIDE_DESIGN.masters.table.tableTopIn,
    w: PPTX_GRID.w(12),
    border: { type: "solid", color: PPTX_COLOR.line, pt: 0.5 },
    autoPage: false,
  });
  if (table.rows.length > 14) {
    slide.addText(
      `+ ${table.rows.length - 14} more rows — see Excel companion exhibit`,
      {
        x: PPTX_GRID.x(0),
        y: 6.9,
        w: PPTX_GRID.w(12),
        h: 0.3,
        fontFace: PPTX_FONT.body,
        fontSize: 9,
        italic: true,
        color: PPTX_COLOR.muted,
      },
    );
  }
}

