function designedHeading(
  text: string,
  level: 1 | 2,
  pageBreakBefore = false,
): Paragraph {
  const first = level === 1;
  return new Paragraph({
    heading: first ? HeadingLevel.HEADING_1 : HeadingLevel.HEADING_2,
    keepNext: true,
    pageBreakBefore,
    spacing: {
      before:
        (first
          ? PAGE_DESIGN.space.sectionBeforePt
          : PAGE_DESIGN.space.sectionAfterPt) * 20,
      after: PAGE_DESIGN.space.sectionAfterPt * 20,
    },
    border: first
      ? {
          bottom: {
            style: BorderStyle.SINGLE,
            size: 4,
            color: TOKENS.LINE,
            space: 6,
          },
        }
      : undefined,
    children: [
      new TextRun({
        text,
        font: first ? SOURCE_DOCX.DISPLAY_FONT : SOURCE_DOCX.BODY_FONT,
        size:
          (first ? PAGE_DESIGN.type.heading1Pt : PAGE_DESIGN.type.heading2Pt) *
          2,
        bold: !first,
        color: TOKENS.INK,
      }),
    ],
  });
}

const SOURCE_REGISTER_APPENDIX_THRESHOLD = 10;

/** A light, board-grade table: muted uppercase header (bottom border only),
 *  hairline row dividers, no per-cell boxes, no navy fill. */
function lightTable(
  columns: string[],
  rows: string[][],
  statusColumn?: number,
): Table {
  const statusCol =
    typeof statusColumn === "number" &&
    statusColumn >= 0 &&
    statusColumn < columns.length
      ? statusColumn
      : null;
  const bodyFontSize = columns.length >= 5 ? 18 : 20;
  const columnWeights = columns.map((column) => {
    const label = column.trim().toLowerCase();
    if (/^(?:#|\[n\]|id|no\.?|number|citation(?: number)?)$/.test(label)) {
      return 0.45;
    }
    if (label === "evidence position") {
      return 0.9;
    }
    if (label === "type") {
      return 1.1;
    }
    if (label === "group") {
      return 0.8;
    }
    if (/^requirements?$/.test(label)) {
      return 3;
    }
    if (/\b(status|confidence|rating|family|date)\b/.test(label)) {
      return 0.85;
    }
    if (/\b(owner|role|responsible)\b/.test(label)) return 1.2;
    if (
      /\b(description|mitigation|resolution|path|action|rationale|comment|scope|condition|input|source|impact|dependency|risk|issue|detail|notes)\b/.test(
        label,
      )
    ) {
      return 2.2;
    }
    return 1.1;
  });
  const totalWeight = columnWeights.reduce((sum, weight) => sum + weight, 0);
  const columnWidths = columnWeights.map((weight) =>
    Math.floor((weight / totalWeight) * 100),
  );
  if (columnWidths.length > 0) {
    columnWidths[columnWidths.length - 1] =
      (columnWidths[columnWidths.length - 1] ?? 0) +
      (100 - columnWidths.reduce((sum, width) => sum + width, 0));
  }
  const width = (i: number): number => columnWidths[i] ?? 0;

  const headerRow = new TableRow({
    tableHeader: true,
    cantSplit: true,
    children: columns.map(
      (c, i) =>
        new TableCell({
          width: { size: width(i), type: WidthType.PERCENTAGE },
          borders: {
            top: { style: BorderStyle.NONE, size: 0, color: "auto" },
            left: { style: BorderStyle.NONE, size: 0, color: "auto" },
            right: { style: BorderStyle.NONE, size: 0, color: "auto" },
            bottom: { style: BorderStyle.SINGLE, size: 4, color: TOKENS.LINE },
          },
          children: [
            new Paragraph({
              spacing: { before: 40, after: 40 },
              children: [
                new TextRun({
                  text: c.toUpperCase(),
                  font: SOURCE_DOCX.BODY_FONT,
                  size: 16, // ~8pt — the header recedes
                  color: TOKENS.MUTED,
                  characterSpacing: 6,
                }),
              ],
            }),
          ],
        }),
    ),
  });

  const dataRows = rows.map(
    (row, ri) =>
      new TableRow({
        cantSplit: true,
        children: columns.map((_, i) => {
          // Colour the declared status column by value (see shared/cell-tone.ts),
          // matching the deck; every other cell renders plain.
          const tone =
            statusCol !== null && i === statusCol
              ? CELL_TONE_HEX[cellTone(row[i] ?? "")]
              : null;
          const shaded = tone && tone.fill ? tone : null;
          return new TableCell({
            width: { size: width(i), type: WidthType.PERCENTAGE },
            ...(shaded ? { shading: { fill: shaded.fill ?? undefined } } : {}),
            borders: {
              top: { style: BorderStyle.NONE, size: 0, color: "auto" },
              left: { style: BorderStyle.NONE, size: 0, color: "auto" },
              right: { style: BorderStyle.NONE, size: 0, color: "auto" },
              // hairline divider on every row except the last (last row no border)
              bottom:
                ri === rows.length - 1
                  ? { style: BorderStyle.NONE, size: 0, color: "auto" }
                  : {
                      style: BorderStyle.SINGLE,
                      size: 2,
                      color: TOKENS.LINE2,
                    },
            },
            children: [
              new Paragraph({
                spacing: { before: 40, after: 40 },
                children: [
                  new TextRun({
                    text: row[i] ?? "",
                    font: SOURCE_DOCX.BODY_FONT,
                    size: bodyFontSize,
                    color: shaded ? shaded.text : TOKENS.INK,
                    ...(shaded ? { bold: true } : {}),
                  }),
                ],
              }),
            ],
          });
        }),
      }),
  );

  return new Table({
    rows: [headerRow, ...dataRows],
    columnWidths: columnWidths.map((width) => width * 100),
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: { style: BorderStyle.NONE, size: 0, color: "auto" },
      bottom: { style: BorderStyle.NONE, size: 0, color: "auto" },
      left: { style: BorderStyle.NONE, size: 0, color: "auto" },
      right: { style: BorderStyle.NONE, size: 0, color: "auto" },
      insideHorizontal: { style: BorderStyle.NONE, size: 0, color: "auto" },
      insideVertical: { style: BorderStyle.NONE, size: 0, color: "auto" },
    },
  });
}

function tableToDocx(table: RenderableTable): Paragraph | Table {
  if (table.rows.length === 0) {
    return bodyParagraph([
      bodyRun(`(${table.title}: see Excel companion exhibit)`, {
        italics: true,
        color: SOURCE_DOCX.MUTED_COLOR,
      }),
    ]);
  }
  return lightTable(table.columns, table.rows, table.statusColumn);
}

function normalizeHeadingText(value: string): string {
  return value
    .replace(/^\d+(?:\.\d+)+[.):]?\s+|^\d+[.):]\s+/, "")
    .replace(/[*_`]/g, "")
    .replace(/&amp;/gi, "&")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

/** The renderer owns the section heading. Models occasionally repeat that same
 * heading as the first Markdown line, producing a visibly duplicated title in
 * HTML, DOCX, and PDF. Remove only an exact normalized duplicate. */
function withoutDuplicateSectionHeading(
  markdown: string,
  title: string,
): string {
  const lines = markdown.split(/\r?\n/);
  const firstContent = lines.findIndex((line) => line.trim().length > 0);
  if (firstContent < 0) return markdown;
  const heading = lines[firstContent]?.match(/^#{1,6}\s+(.+?)\s*#*\s*$/);
  if (
    !heading ||
    normalizeHeadingText(heading[1] ?? "") !== normalizeHeadingText(title)
  ) {
    return markdown;
  }
  lines.splice(firstContent, 1);
  return lines.join("\n").replace(/^\s+/, "");
}

function sectionBodyFromJson(value: unknown): string | null {
  if (!value || typeof value !== "object" || Array.isArray(value)) return null;
  const record = value as Record<string, unknown>;
  const body = record.bodyMarkdown;
  return typeof body === "string" && body.trim().length > 0 ? body : null;
}

function sectionBodyFromJsonText(text: string): string | null {
  try {
    return sectionBodyFromJson(JSON.parse(text));
  } catch {
    // Fall through to a conservative loose extractor. Older persisted artifacts
    // can contain section-object shaped text inside malformed Markdown fences,
    // so strict JSON parsing is not always available at render time.
  }
  const match = text.match(
    /"bodyMarkdown"\s*:\s*"([\s\S]*?)"\s*,\s*"(?:rawBodyMarkdown|groundingMode|citationsUsed)"/,
  );
  if (!match?.[1]) return null;
  try {
    return JSON.parse(`"${match[1]}"`) as string;
  } catch {
    return match[1]
      .replace(/\\n/g, "\n")
      .replace(/\\"/g, '"')
      .replace(/\\\\/g, "\\");
  }
}

function findJsonObjectEnd(text: string, start: number): number | null {
  let depth = 0;
  let inString = false;
  let escaped = false;
  for (let i = start; i < text.length; i += 1) {
    const char = text[i];
    if (inString) {
      if (escaped) escaped = false;
      else if (char === "\\") escaped = true;
      else if (char === '"') inString = false;
      continue;
    }
    if (char === '"') inString = true;
    else if (char === "{") depth += 1;
    else if (char === "}") {
      depth -= 1;
      if (depth === 0) return i + 1;
    }
  }
  return null;
}

function replaceSectionJsonObjects(markdown: string): string {
  const withoutJsonFences = markdown.replace(
    /```json\s*\n([\s\S]*?)\n```/gi,
    (match, inner) => {
      return sectionBodyFromJsonText(inner) ?? match;
    },
  );
  let out = "";
  let cursor = 0;
  while (cursor < withoutJsonFences.length) {
    const start = withoutJsonFences.indexOf("{", cursor);
    if (start < 0) {
      out += withoutJsonFences.slice(cursor);
      break;
    }
    const end = findJsonObjectEnd(withoutJsonFences, start);
    if (end === null) {
      out += withoutJsonFences.slice(cursor);
      break;
    }
    const candidate = withoutJsonFences.slice(start, end);
    const replacement = sectionBodyFromJsonText(candidate);
    out += withoutJsonFences.slice(cursor, start);
    out += replacement ?? candidate;
    cursor = end;
  }
  return out;
}

function normalizeSectionMarkdown(markdown: string, title: string): string {
  return stripStructuralScaffolding(
    withoutDuplicateSectionHeading(replaceSectionJsonObjects(markdown), title),
  );
}

// ── DOCX ──

export function renderDeliverableDocx(
  doc: RenderableDeliverable,
  architectureModel?: ArchitectureModel,
): Document {
  const children: (Paragraph | Table)[] = [];

  // Cover
  children.push(eyebrowParagraph(DOC_COVER_EYEBROW));
  children.push(
    new Paragraph({
      spacing: { before: 180, after: 180 },
      children: [
        new TextRun({
          text: doc.title,
          font: SOURCE_DOCX.DISPLAY_FONT,
          size: PAGE_DESIGN.type.titlePt * 2,
          color: TOKENS.INK,
        }),
      ],
    }),
  );
  if (doc.subtitle) children.push(coverSubtitleParagraph(doc.subtitle));
  children.push(
    coverSubtitleParagraph(
      `${doc.clientDisplayName} — ${doc.initiativeDisplayName}`,
    ),
  );
  // Required document-status block — every generated artifact carries this
  // until a real, named human-approval record exists for it.
  children.push(
    bodyParagraph([boldRun("Document status: "), bodyRun(DOC_STATUS_LABEL)]),
  );
  children.push(bodyParagraph([bodyRun(DOC_STATUS_BODY)]));

  // Sections — render the authored markdown body PROPERLY (headings, bold,
  // ordered/unordered + nested lists, inline GFM tables) via the shared
  // mdast walker, instead of flattening every line to a paragraph.
  for (const section of doc.generatedSections) {
    children.push(designedHeading(section.title, 1));
    children.push(
      ...markdownToDocxBlocks(
        normalizeSectionMarkdown(section.bodyMarkdown, section.title),
      ),
    );
  }

  // In-document tables (those NOT routed to the Excel companion)
  const inDocTables = doc.tables.filter((t) => t.targetFormat !== "xlsx");
  if (inDocTables.length) {
    children.push(designedHeading("Tables & Exhibits", 1));
    for (const t of inDocTables) {
      children.push(designedHeading(t.title, 2));
      children.push(tableToDocx(t));
    }
  }

  // Visual exhibits — rasterised from the same SVG the HTML renderer inlines.
  // Missing structured exhibit data intentionally produces no block; the
  // quality contract surfaces the missing visual instead of shipping a fake one.
  const exhibitBlocks = doc.exhibits.flatMap((exhibit, index) =>
    exhibitToDocxBlocks(exhibit, index),
  );
  const architectureBlocks = architectureModel
    ? renderArchitectureVisualExhibits(architectureModel)
        .flatMap(architectureVisualPanels)
        .flatMap((visual, index) =>
          svgToDocxBlocks(
            {
              key: `architecture-exhibit:${visual.id}:${architectureVisualDigest(visual.svg)}`,
              title: visual.title,
              description: `${visual.soWhat} Decision implication: ${visual.decisionImplication}`,
              accessibleDescription: [
                visual.soWhat,
                ...architecturePanelRecordedFlows(visual.svg),
              ].join("\n"),
              svg: visual.svg,
            },
            doc.exhibits.length + index,
          ),
        )
    : [];
  if (exhibitBlocks.length || architectureBlocks.length) {
    children.push(designedHeading("Visual Exhibits", 1));
    children.push(...exhibitBlocks);
    children.push(...architectureBlocks);
  }

  // Recommendation + next actions
  children.push(designedHeading("Recommendation", 1));
  children.push(bodyParagraph([bodyRun(doc.recommendation)]));
  if (doc.nextActions.length) {
    children.push(designedHeading("Next Actions", 2));
    for (const a of doc.nextActions)
      children.push(bodyParagraph([bodyRun(`• ${a}`)]));
  }

  // Client-to-complete checklist
  if (doc.clientCompleteChecklist.length) {
    children.push(designedHeading("Client-to-Complete Checklist", 1));
    for (const c of doc.clientCompleteChecklist) {
      children.push(
        bodyParagraph([
          boldRun(`☐ ${c.label} `),
          bodyRun(
            `— owner: ${c.owner} (${clientCompleteReasonLabel(c.reason)})`,
          ),
        ]),
      );
    }
  }

  // Assumptions
  if (doc.assumptions.length) {
    children.push(designedHeading("Assumptions", 1));
    for (const a of doc.assumptions) {
      children.push(
        bodyParagraph([
          bodyRun(
            `• ${a.statement}${a.mustValidate ? " [VALIDATE]" : ""} — ${a.basis}`,
          ),
        ]),
      );
    }
  }

  // Source register
  if (doc.sourceRegister.length) {
    children.push(
      designedHeading(
        "Source Register",
        1,
        doc.sourceRegister.length >= SOURCE_REGISTER_APPENDIX_THRESHOLD,
      ),
    );
    children.push(
      lightTable(
        ["[n]", "Source", "Family", "Confidence"],
        doc.sourceRegister.map((r) => [
          String(r.citationNumber),
          r.label,
          humanizeSourceFamily(r.evidenceFamily),
          `${r.confidence}${r.asOf ? ` · ${r.asOf}` : ""}`,
        ]),
      ),
    );
  }

  return new Document({
    creator: "AbarVa",
    title: doc.title,
    description: `${doc.clientDisplayName} — ${doc.initiativeDisplayName}`,
    // Required so ordered lists emitted by markdownToDocxBlocks render as 1./2./a.
    numbering: ORDERED_NUMBERING_CONFIG,
    sections: [
      {
        properties: {
          page: {
            margin: {
              top: PAGE_DESIGN.marginIn * 1440,
              right: PAGE_DESIGN.marginIn * 1440,
              bottom: PAGE_DESIGN.marginIn * 1440,
              left: PAGE_DESIGN.marginIn * 1440,
            },
          },
        },
        footers: {
          default: new Footer({
            children: [
              new Paragraph({
                children: [
                  new TextRun({
                    text: `Confidential — ${doc.clientDisplayName} · ${DOC_STATUS_FOOTER}`,
                    font: SOURCE_DOCX.BODY_FONT,
                    size: 16,
                    color: SOURCE_DOCX.MUTED_COLOR,
                  }),
                ],
              }),
            ],
          }),
        },
        children,
      },
    ],
  });
}

// ── XLSX companion (wide tables) ──

type ExcelCompanionOptions = {
  /**
   * Route downloads for an xlsx-prescribed artifact must produce a real workbook
   * even when the model forgot to flag a table as xlsx. Normal companion mode
   * stays strict so wide-data intent remains visible to authors and tests.
   */
  includeAllTablesWhenNoXlsxTables?: boolean;
  /**
   * Last-resort workbook for xlsx-prescribed artifacts with no tables at all.
   * It preserves the structured document as auditable sheets instead of falling
   * through to a mislabeled DOCX.
   */
  includeDocumentSheetsWhenNoTables?: boolean;
};

/** Build the Excel companion for every table flagged targetFormat 'xlsx'. Returns null if none. */
export function renderDeliverableExcelCompanion(
  doc: RenderableDeliverable,
  options: ExcelCompanionOptions = {},
): ExcelJS.Workbook | null {
  let xlsxTables = doc.tables.filter((t) => t.targetFormat === "xlsx");
  if (xlsxTables.length === 0 && options.includeAllTablesWhenNoXlsxTables) {
    xlsxTables = doc.tables;
  }
  if (
    xlsxTables.length === 0 &&
    !options.includeDocumentSheetsWhenNoTables &&
    !doc.exhibits.some((exhibit) => exhibit.data)
  ) {
    return null;
  }
  const wb = new ExcelJS.Workbook();
  wb.creator = "AbarVa";
  wb.created = new Date(0); // deterministic
  addExcelCover(wb, doc);
  for (const t of xlsxTables) {
    const sheet = wb.addWorksheet(uniqueSheetName(wb, t.title));
    const header = sheet.addRow(t.columns.map((c) => c.toUpperCase()));
    for (const row of t.rows) sheet.addRow(row);
    styleExcelDataSheet(sheet, header);
  }
  if (xlsxTables.length === 0 && options.includeDocumentSheetsWhenNoTables) {
    addDocumentSummarySheets(wb, doc);
  }
  const expectedFigures = addExcelExhibits(wb, doc);
  const sheetVerdict = judgeSheetQuality(wb, expectedFigures);
  if (!sheetVerdict.ok) {
    throw new Error(
      `generated_xlsx_failed_quality:${sheetVerdict.findings.join(";")}`,
    );
  }
  return wb;
}

function addExcelExhibits(
  wb: ExcelJS.Workbook,
  doc: RenderableDeliverable,
): number {
  let rendered = 0;
  doc.exhibits.forEach((exhibit, index) => {
    if (!exhibit.data) return;
    const rawSvg = exhibitSvg(exhibit, index);
    if (!rawSvg) throw new Error(`xlsx_exhibit_not_renderable:${exhibit.key}`);
    const { png, aspect } = rasteriseSvg(
      withXmlns(resolveSvgTokens(rawSvg)),
      2,
    );
    const sheet = wb.addWorksheet(
      uniqueSheetName(wb, `Exhibit ${index + 1} ${exhibit.title}`),
    );
    sheet.columns = [{ width: 30 }, { width: 70 }];
    const title = sheet.addRow([`FIGURE ${index + 1}`, exhibit.title]);
    sheet.addRow(["Description", exhibit.description]);
    styleExcelDataSheet(sheet, title);
    const width = Math.min(960, 640 * aspect);
    const height = width / aspect;
    const imageId = wb.addImage({
      buffer: png as unknown as Parameters<
        ExcelJS.Workbook["addImage"]
      >[0]["buffer"],
      extension: "png",
    });
    sheet.addImage(imageId, { tl: { col: 0, row: 4 }, ext: { width, height } });
    rendered += 1;
  });
  return rendered;
}

function uniqueSheetName(wb: ExcelJS.Workbook, title: string): string {
  const stem =
    title
      .replace(/[\\/?*[\]:]/g, " ")
      .trim()
      .slice(0, 27) || "Data";
  let name = stem;
  let suffix = 2;
  while (wb.getWorksheet(name)) name = `${stem.slice(0, 27)} ${suffix++}`;
  return name.slice(0, 31);
}

