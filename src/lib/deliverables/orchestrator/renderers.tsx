        <PdfText style={PDF_STYLES.title}>{doc.title}</PdfText>
        {doc.subtitle ? (
          <PdfText style={{ ...PDF_STYLES.meta, fontSize: 12 }}>
            {doc.subtitle}
          </PdfText>
        ) : null}
        <PdfText style={PDF_STYLES.meta}>
          {doc.clientDisplayName} — {doc.initiativeDisplayName}
        </PdfText>

        {/* Required document-status block — every generated artifact carries
            this until a real, named human-approval record exists for it. */}
