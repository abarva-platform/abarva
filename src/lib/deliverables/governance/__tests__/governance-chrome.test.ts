import { checkGovernanceChrome, DEFAULT_CHROME } from '../governance-chrome';

const complete = 'AbarVa · AI-generated working draft — not approved · synthetic planning-grade data';

describe('governance chrome on the rendered file', () => {
  it('passes a deck carrying all three markers', () => {
    const v = checkGovernanceChrome({ visibleText: complete });
    expect(v.findings).toEqual([]);
    expect(v.present.sort()).toEqual(['data_basis', 'producer', 'provenance']);
  });

  // Each marker removed independently must fail its own assertion, so a deck
  // that drops one cannot be rescued by the presence of the other two.
  it.each(DEFAULT_CHROME.map((r) => r.marker))('FAILS when the %s marker is removed', (marker) => {
    const stripped: Record<string, string> = {
      provenance: 'AbarVa · synthetic planning-grade data',
      data_basis: 'AbarVa · AI-generated working draft — not approved',
      producer: 'AI-generated working draft — not approved · synthetic planning-grade data',
    };
    const v = checkGovernanceChrome({ visibleText: stripped[marker] });
    expect(v.ok).toBe(false);
    expect(v.findings.map((f) => f.marker)).toContain(marker);
  });

  it('reproduces the defect the blind review found', () => {
    // The composed deck dropped the provenance banner while every other gate
    // passed. This is the assertion that would have caught it.
    const composed = 'AbarVa · Contact Center Platform — Discovery Readout · planning-grade, PHI-free';
    const v = checkGovernanceChrome({ visibleText: composed });
    expect(v.ok).toBe(false);
    expect(v.findings[0].marker).toBe('provenance');
  });

  it('does not count a marker that appears only in speaker notes', () => {
    // The check is what the reader sees. Notes are not a slide face, so the
    // caller passes visible text only and an absent marker stays absent.
    const v = checkGovernanceChrome({ visibleText: 'AbarVa · synthetic planning-grade' });
    expect(v.findings.map((f) => f.marker)).toEqual(['provenance']);
  });

  it('flags an internal agent name on a client surface', () => {
    const v = checkGovernanceChrome({ visibleText: `${complete} · generated by Nexus` });
    expect(v.ok).toBe(false);
    expect(v.findings[0].message).toContain('Nexus');
  });

  it('does not demand a synthetic label when the corpus is not synthetic', () => {
    const v = checkGovernanceChrome({
      visibleText: 'AbarVa · AI-generated working draft — not approved',
      requireDataBasis: false,
    });
    expect(v.ok).toBe(true);
  });
});
