/**
 * Deterministic assembly of the composer module from per-slide functions.
 *
 * The composer does not write the program; it writes the slides. The header, the
 * call order and the save are written here, in code nobody prompts, for three
 * reasons:
 *
 *   - One 18-slide program does not fit in an output budget. Batched per-slide
 *     functions do, and each batch is independently retryable.
 *   - A revision that has to touch three weak slides should regenerate three
 *     functions, not re-emit two thousand lines and risk changing the other
 *     fifteen by accident.
 *   - Slide ORDER is the argument. Leaving it to the model to re-state on every
 *     revision is leaving the argument itself to drift.
 *
 * The assembled module still passes the AST gate in full — assembly is not a
 * trust boundary, it is a structure.
 */

import type { SlideStoryPlanEntry } from './presentation-packet';

export interface SlideFunction {
  slideId: string;
  /** A complete `def slide_<id>(deck, theme):` definition. */
  code: string;
}

export interface AssemblyResult {
  source: string;
  missing: string[];
  extra: string[];
  malformed: string[];
}

const DEF = /^def\s+(slide_[A-Za-z0-9_]+)\s*\(/m;

function functionName(slideId: string): string {
  return `slide_${slideId.replace(/[^A-Za-z0-9_]/g, '_')}`;
}

function dedent(code: string): string {
  const lines = code.replace(/\t/g, '    ').split('\n');
  const indents = lines
    .filter((l) => l.trim())
    .map((l) => l.length - l.trimStart().length);
  const shift = indents.length ? Math.min(...indents) : 0;
  return lines.map((l) => l.slice(shift)).join('\n').replace(/\s+$/, '');
}

export function assembleComposerModule(
  plan: SlideStoryPlanEntry[],
  functions: SlideFunction[],
  themeVersion: string,
): AssemblyResult {
  const byId = new Map(functions.map((f) => [f.slideId, f]));
  const planIds = new Set(plan.map((s) => s.slideId));

  const missing: string[] = [];
  const malformed: string[] = [];
  const extra = functions.filter((f) => !planIds.has(f.slideId)).map((f) => f.slideId);

  const bodies: string[] = [];
  const calls: string[] = [];

  for (const slide of plan) {
    const fn = byId.get(slide.slideId);
    if (!fn) {
      missing.push(slide.slideId);
      continue;
    }
    const code = dedent(fn.code);
    const match = code.match(DEF);
    if (!match) {
      malformed.push(slide.slideId);
      continue;
    }
    // The model is asked for slide_<id>, but a renamed function would silently
    // never be called — the slide would vanish from a deck that still looked
    // plausible. Call what was actually defined, and let the plan-order loop
    // below be the only thing that decides sequence.
    bodies.push(code);
    calls.push(`    ${match[1]}(deck, theme)  # ${slide.slideId}: ${slide.title.replace(/\s+/g, ' ').slice(0, 88)}`);
  }

  const source = [
    '# Generated by the Presentation Composer.',
    `# Theme version: ${themeVersion}. Slide order is fixed by the accepted SlideStoryPlan.`,
    '# Per-slide functions are model-authored; this header, the call order and the',
    '# save are assembled deterministically.',
    'import sdk',
    '',
    '',
    ...bodies.flatMap((b) => [b, '', '']),
    'def build():',
    '    deck = sdk.Deck()',
    '    theme = deck.theme',
    ...calls,
    '    deck.save("deck.pptx")',
    '',
    '',
    'build()',
    '',
  ].join('\n');

  return { source, missing, extra, malformed };
}

export { functionName };
