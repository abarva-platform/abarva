import { ingestRssFeed } from '../ingest/rss_ingest';
import type { SourceDeclaration } from '../pipeline';

function rssSource(decl: Omit<SourceDeclaration, 'ingest' | 'attribution'> & { attribution: string; feedUrl: string }): SourceDeclaration {
  return {
    ...decl,
    ingest: () =>
      ingestRssFeed(decl.feedUrl, {
        attribution: decl.attribution,
        maxItems: 50,
      }),
  };
}

