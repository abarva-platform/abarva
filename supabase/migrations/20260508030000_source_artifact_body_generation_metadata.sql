-- Source canvas · artifact body generation provenance
--
-- When the agent generates an artifact body via Claude, we need to
-- carry the receipt: which model, which prompt template version,
-- which upstream artifact codes were bound into the prompt context.
-- Without provenance, "Sentinel drafted this" is an unverifiable
-- claim. Trust scales with traceability — see EASE_OF_USE_BACKLOG · C.6.
--
-- Adds one JSONB column on source_event_artifact_states:
--   - body_generation_metadata · audit receipt for the last generation
--
-- Shape (typed in TS via SourceArtifactBodyGenerationMetadata):
--   {
--     "model": "claude-sonnet-4-6",
--     "promptTemplateId": "d09_rfp_pack",
--     "promptTemplateVersion": 1,
--     "upstreamBoundCodes": ["d01_strategy_memo", "d05_scope_memo"],
--     "generatedAt": "2026-05-08T02:30:00Z",
--     "generatedByUserId": "user_clerk_xxx",
--     "tokensIn": 4321,
--     "tokensOut": 2156,
--     "stopReason": "end_turn"
--   }
--
-- NULL means the body was authored by hand (or is still the canonical
-- template). Non-null means the body came from a Claude generation.

BEGIN;

ALTER TABLE source_event_artifact_states
  ADD COLUMN IF NOT EXISTS body_generation_metadata JSONB;

COMMENT ON COLUMN source_event_artifact_states.body_generation_metadata IS
  'Provenance receipt when the body was generated by an agent. NULL '
  'when authored by hand. Includes model, prompt template id + version, '
  'upstream artifact codes bound into the context, and token counts. '
  'See SourceArtifactBodyGenerationMetadata in TypeScript for the shape.';

COMMIT;
