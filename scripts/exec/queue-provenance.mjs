#!/usr/bin/env node
/**
 * Which generator wrote the queue an item was taken from (item T-720).
 *
 * T-507 moved this toolchain into the repository and left the superseded copies
 * standing in the operator root. T-711 shipped a guard for the MIXED case: the
 * repo-owned queue refuses a board summary that the repo-owned board did not
 * write. Its own closure recorded what it did not close:
 *
 *   > the superseded generators in the operator root still exist and are still
 *   > what regenerates the live queue [...] Removing them is operator-side work
 *   > outside this repository and is **owed**. Until then, a queue file without
 *   > the `Generated by ...` line is stale on sight.
 *
 * "Stale on sight" is a reader's obligation, and it has now been missed twice.
 * Measured on 2026-09-23: the live queue was stamped 00:49Z, carried no
 * repo-owned line, offered 61 claimable rows and reported "None held. Every
 * claim in the log is released or expired." while three claims were live. The
 * repo-owned pair, on byte-identical inputs, offered 1 row, found all three
 * claims, and classified 110 signed-in-acceptance rows as blocked rather than
 * claimable. The superseded pair is self-consistent — its board writes an
 * unstamped summary and its queue never asks — so T-711's guard never fires on
 * it, and the regenerate block printed inside the stale file names the
 * generators by bare filename, which resolves to the superseded copies. A run
 * following that instruction re-verified items 1, 15 and 18 as long closed
 * before noticing; those are the same three ids T-711 named as its evidence.
 *
 * So the obligation moves off the reader and onto a check.
 *
 * Hash, not path, and the reason is T-711's. The same generator legitimately
 * runs from a worktree, from the fixture directory a suite copies it into, and
 * from a CI checkout; a path comparison would refuse all three. The path is
 * carried in the stamp anyway, because it is the evidence that names the copy.
 *
 * Hash of the generator's own file, read at run time, which is why a superseded
 * copy cannot forge it: to write this stamp it would have to be byte-identical
 * to the repo-owned generator, and then it is not superseded.
 *
 * Every verdict other than `repo_owned` fails closed, including the ones that
 * mean "I could not tell". A guard whose unknown case passes is opt-in, and the
 * first file to reach it is by definition the one that predates it.
 */

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const REPO_OWNED = "repo_owned";
export const SUPERSEDED = "superseded";
export const UNSTAMPED = "unstamped";
export const ABSENT = "absent";
export const UNREADABLE = "unreadable";
export const GENERATOR_MISSING = "generator_missing";

/**
 * The stamp grammar, versioned so a later change to it is detectable rather
 * than silently unreadable. An HTML comment keeps it out of the rendered
 * document without hiding it from `grep`.
 *
 * `sha256` is matched as exactly 64 hex characters, so no amount of prose
 * mentioning this control can satisfy the reader — the failure mode where a
 * gate was answered by its own name appearing in a file is the reason this
 * whole directory exists.
 */
export const PROVENANCE_VERSION = "v1";
const STAMP_PATTERN =
  /<!--\s*queue-provenance\s+v1\s+sha256=([0-9a-f]{64})\s+script=(.*?)\s*-->/;

export const QUEUE_FILENAME = "EXECUTION_QUEUE.md";

/** sha256 of a generator's own source, which is what the stamp records. */
export function hashGenerator(generatorPath) {
  return crypto
    .createHash("sha256")
    .update(fs.readFileSync(generatorPath))
    .digest("hex");
}

export function queueProvenanceStamp(generatorPath) {
  return { sha256: hashGenerator(generatorPath), script: generatorPath };
}

export function formatQueueProvenance({ sha256, script }) {
  return `<!-- queue-provenance ${PROVENANCE_VERSION} sha256=${sha256} script=${script} -->`;
}

/** The stamp a queue file carries, or null when it carries none. */
export function readQueueProvenance(text) {
  const m = STAMP_PATTERN.exec(text);
  return m ? { sha256: m[1], script: m[2] } : null;
}

/** The queue that sits beside a register, which is the pair an agent reads. */
export function queuePathBesideRegister(registerPath) {
  return path.join(path.dirname(path.resolve(registerPath)), QUEUE_FILENAME);
}

/**
 * Compare the stamp in `queuePath` against the generator at `generatorPath`.
 *
 * Returns `{ verdict, queuePath, generatorPath, expected, found }`. `found` is
 * the stamp read from the file when there was one, so a refusal can quote the
 * copy that wrote it rather than only asserting a mismatch.
 */
export function evaluateQueueProvenance({ queuePath, generatorPath }) {
  const base = { queuePath, generatorPath, expected: null, found: null };

  if (!fs.existsSync(generatorPath)) {
    return { ...base, verdict: GENERATOR_MISSING };
  }

  let expected;
  try {
    expected = hashGenerator(generatorPath);
  } catch {
    return { ...base, verdict: GENERATOR_MISSING };
  }

  if (!fs.existsSync(queuePath)) {
    return { ...base, expected, verdict: ABSENT };
  }

  let text;
  try {
    text = fs.readFileSync(queuePath, "utf8");
  } catch {
    return { ...base, expected, verdict: UNREADABLE };
  }

  const found = readQueueProvenance(text);
  if (!found) return { ...base, expected, verdict: UNSTAMPED };

  return {
    ...base,
    expected,
    found,
    verdict: found.sha256 === expected ? REPO_OWNED : SUPERSEDED,
  };
}

export function isRepoOwned(result) {
  return result.verdict === REPO_OWNED;
}

/**
 * The one-line fix, printed with every refusal. A refusal that does not carry
 * the command is a refusal the next run has to go and look up, and this control
 * is deliberately cheap to satisfy.
 */
export function regenerateCommand(operatorRoot) {
  const home = operatorRoot ? `SOURCE_EXECUTION_HOME=${operatorRoot} ` : "";
  return (
    `${home}node scripts/exec/build-source-board.mjs --json && \\\n` +
    `  ${home}node scripts/exec/build-execution-queue.mjs`
  );
}

export function describeQueueProvenance(result) {
  const { verdict, queuePath, generatorPath, expected, found } = result;
  const root = path.dirname(queuePath);
  const fix = `Regenerate it:\n  ${regenerateCommand(root)}`;

  switch (verdict) {
    case REPO_OWNED:
      return `${queuePath} was written by the generator beside this script (sha256 ${expected.slice(0, 12)}).`;
    case SUPERSEDED:
      return (
        `${queuePath} was written by a DIFFERENT build-execution-queue.mjs than the one beside this\n` +
        `script, so it does not describe the work this toolchain now offers.\n` +
        `  queue written by  ${found.script}  (sha256 ${found.sha256.slice(0, 12)})\n` +
        `  checked against   ${generatorPath}  (sha256 ${expected.slice(0, 12)})\n${fix}`
      );
    case UNSTAMPED:
      return (
        `${queuePath} carries no record of which generator wrote it, so it predates this stamp or came\n` +
        "from a superseded copy in the operator root. Those copies have drifted: on identical inputs\n" +
        "they have offered work the backlog no longer holds and reported no live claims while claims\n" +
        `were live.\n${fix}`
      );
    case ABSENT:
      return (
        `there is no ${QUEUE_FILENAME} at ${queuePath}, so there is no generated queue to have taken a\n` +
        `row from. Build one rather than choosing an item unaided.\n${fix}`
      );
    case UNREADABLE:
      return `${queuePath} exists and could not be read, so its provenance is unknown.\n${fix}`;
    case GENERATOR_MISSING:
      return (
        `build-execution-queue.mjs is not at ${generatorPath}, so the queue's provenance cannot be\n` +
        "checked against the generator that should have written it."
      );
    default:
      return `unrecognised verdict ${verdict} for ${queuePath}.`;
  }
}

/* ------------------------------------------------------------------------- */
/* CLI                                                                        */
/* ------------------------------------------------------------------------- */

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_GENERATOR = path.join(HERE, "build-execution-queue.mjs");

const USAGE =
  "usage: --queue <EXECUTION_QUEUE.md> | --register <EXECUTION_CLAIMS.md>\n" +
  "       [--generator <build-execution-queue.mjs>] [--json]\n" +
  "exit 0 when the queue was written by the repo-owned generator, 1 otherwise.";

function cli(argv) {
  const flag = (name) => {
    const i = argv.indexOf(name);
    return i >= 0 ? argv[i + 1] : undefined;
  };

  const register = flag("--register");
  const queuePath = flag("--queue") ?? (register ? queuePathBesideRegister(register) : undefined);
  if (!queuePath) {
    console.error(USAGE);
    process.exit(2);
  }

  const result = evaluateQueueProvenance({
    queuePath: path.resolve(queuePath),
    generatorPath: path.resolve(flag("--generator") ?? DEFAULT_GENERATOR),
  });

  if (argv.includes("--json")) {
    console.log(JSON.stringify(result, null, 2));
  } else if (isRepoOwned(result)) {
    console.log(describeQueueProvenance(result));
  } else {
    console.error(`queue provenance: ${result.verdict}`);
    console.error(describeQueueProvenance(result));
  }

  process.exit(isRepoOwned(result) ? 0 : 1);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
  cli(process.argv.slice(2));
}
