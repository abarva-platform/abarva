const csvEscape = (value) => {
  const s = String(value ?? '');
  if (/[",\n\r]/.test(s)) return `"${s.replace(/"/g, '""')}"`;
  return s;
};

const writeCsv = (file, headers, rows) => {
  const body = [
    headers.join(','),
    ...rows.map((row) => headers.map((h) => csvEscape(row[h])).join(',')),
  ].join('\n') + '\n';
  fs.writeFileSync(path.join(baseDir, file), body);
};

