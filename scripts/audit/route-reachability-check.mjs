#!/usr/bin/env node
/**
 * Report components that no route can reach.
 *
 * A component can pass every test, clear CI and deploy successfully while
 * being mounted by nothing. That happened: a 425-line change landed in
 * `workspace-tabs/EvidenceTab.tsx`, whose only importer is
 * `UniversalCanvasShell.tsx`, which the event route stopped mounting. The work
 * was correct, tested and deployed, and no user could reach it.
 *
 * It kept happening outside Source, where this watched nothing. Three surfaces
 * in the AI control catalog turned out to be components no route imports — one
 * of them carrying five declared controls, with a QA inventory still naming it
 * as what the Tower route renders. The watch now covers src/components, and
 * this runs in CI, which it previously did not.
 *
 * This walks the import graph from the app routes and reports which files
 * under the watched directories are never reached. Existing orphans are
 * recorded in a baseline so the check fails only when a NEW one appears, or
 * when a known orphan is removed and the baseline is stale.
 *
 * It then asks the same question at the grain the file walk cannot see. Two
 * Source surfaces went dead inside `src/app`, which this did not watch, and
 * one of them is an exported component sitting in a file every Source route
 * reaches — so even under the widened watch the file reads as reached while
 * nothing mounts the symbol. The export pass reports exported symbols that no
 * route-reachable file imports, against a baseline of its own: one defect, one
 * finding, and a file-level orphan is never billed twice.
 *
 * Usage:
 *   node scripts/audit/route-reachability-check.mjs            # check against baseline
 *   node scripts/audit/route-reachability-check.mjs --update   # rewrite baseline
 *   node scripts/audit/route-reachability-check.mjs --json     # machine-readable
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// The graph walk is shared with the AI surface control catalog, which asks the
// same question of its declared surfaces. One implementation so the two audits
// cannot disagree about what a user can reach.
import {
  computeExportReachability,
  computeRouteReachability,
  isExcluded,
  walk,
} from './lib/route-reachability.mjs';

const REPO_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
  '..',
);
const BASELINE = path.join(
  REPO_ROOT,
  'docs',
  'architecture',
  'unreachable-components.json',
);
const EXPORT_BASELINE = path.join(
  REPO_ROOT,
  'docs',
  'architecture',
  'unreachable-exports.json',
);

/**
 * Directories whose components must be reachable from a route.
 *
 * This was `src/components/source` alone, which is why 294 unreachable files
 * outside Source were never reported by anything. It was then `src/components`
 * alone, which is why the whole of `src/app` — every route group's colocated
 * component, including the Source preview workspace where two surfaces went
 * dead — was examined by nothing. The widening drew 18 files, not the hundreds
 * the previous one did.
 */
const WATCHED = ['src/components', 'src/app'];

function isWatched(relative) {
  return WATCHED.some((dir) => relative.startsWith(`${dir}/`));
}

function main() {
  const args = process.argv.slice(2);
  const update = args.includes('--update');
  const asJson = args.includes('--json');

  const { roots, reachable } = computeRouteReachability(REPO_ROOT);

  const orphans = [];
  for (const dir of WATCHED) {
    const abs = path.join(REPO_ROOT, dir);
    if (!fs.existsSync(abs)) continue;
    for (const file of walk(abs)) {
      const relative = path.relative(REPO_ROOT, file);
      if (isExcluded(relative)) continue;
      if (!isWatched(relative)) continue;
      if (!reachable.has(file)) orphans.push(relative);
    }
  }
  orphans.sort();

  const { orphanExports, scannedFiles } = computeExportReachability(
    REPO_ROOT,
    WATCHED,
  );

  if (update) {
    fs.writeFileSync(
      BASELINE,
      `${JSON.stringify(
        {
          note: 'Components no route can reach. Generated by scripts/audit/route-reachability-check.mjs. A new entry here means work has landed somewhere no user can see; remove the component or mount it, do not just extend this list. This list is debt, not a permission slip: three entries were AI control surfaces the control catalog counted as controls the product has.',
          generatedFrom: 'src/app route graph',
          watched: WATCHED,
          orphans,
        },
        null,
        2,
      )}\n`,
    );
    fs.writeFileSync(
      EXPORT_BASELINE,
      `${JSON.stringify(
        {
          note: 'Exported symbols in the watched trees that no route-reachable file imports. Generated by scripts/audit/route-reachability-check.mjs. The file holding one of these IS reachable — that is the point: the file-level baseline cannot see a dead component inside a live file. A test importing the symbol does not count; a test is not an entry point. Mount it or delete it; extending this list instead is how an exported component with no caller comes to look live.',
          generatedFrom: 'src/app route graph, export grain',
          watched: WATCHED,
          scannedFiles,
          orphanExports,
        },
        null,
        2,
      )}\n`,
    );
    console.log(
      `Baseline written: ${orphans.length} orphaned file(s), ${orphanExports.length} orphaned export(s).`,
    );
    return;
  }

  let baseline = { orphans: [] };
  if (fs.existsSync(BASELINE)) {
    baseline = JSON.parse(fs.readFileSync(BASELINE, 'utf8'));
  }
  const known = new Set(baseline.orphans ?? []);
  const added = orphans.filter((file) => !known.has(file));
  const removed = [...known].filter((file) => !orphans.includes(file));

  let exportBaseline = { orphanExports: [] };
  if (fs.existsSync(EXPORT_BASELINE)) {
    exportBaseline = JSON.parse(fs.readFileSync(EXPORT_BASELINE, 'utf8'));
  }
  const knownExports = new Set(exportBaseline.orphanExports ?? []);
  const exportsAdded = orphanExports.filter((entry) => !knownExports.has(entry));
  const exportsRemoved = [...knownExports].filter(
    (entry) => !orphanExports.includes(entry),
  );

  if (asJson) {
    console.log(
      JSON.stringify(
        {
          watched: WATCHED,
          orphans,
          added,
          removed,
          orphanExports,
          exportsAdded,
          exportsRemoved,
          scannedFiles,
          roots: roots.length,
        },
        null,
        2,
      ),
    );
  } else {
    console.log(
      `Route reachability: ${roots.length} route entry points, ${orphans.length} unreachable file(s) under ${WATCHED.join(', ')}.`,
    );
    if (added.length > 0) {
      console.error('\nNEW unreachable file(s) — no route can reach these:');
      for (const file of added) console.error(`  + ${file}`);
      console.error(
        '\nWork landing here ships and passes CI but no user can see it.',
      );
      console.error(
        'Mount it from a route, or remove it. Do not extend the baseline to silence this.',
      );
    }
    if (removed.length > 0) {
      console.error('\nBaseline is stale — these are reachable again:');
      for (const file of removed) console.error(`  - ${file}`);
      console.error(
        '\nRefresh with: npm run audit:route-reachability -- --update',
      );
    }
    console.log(
      `Export reachability: ${orphanExports.length} unreachable export(s) across ${scannedFiles} reachable file(s).`,
    );
    if (exportsAdded.length > 0) {
      console.error(
        '\nNEW unreachable export(s) — the file is reached, the symbol is not:',
      );
      for (const entry of exportsAdded) console.error(`  + ${entry}`);
      console.error(
        '\nAn exported component nothing imports renders nowhere, and its file being live hides that.',
      );
      console.error(
        'Mount it from something a route reaches, or delete it. A test importer is not a mount.',
      );
    }
    if (exportsRemoved.length > 0) {
      console.error('\nExport baseline is stale — these are imported again:');
      for (const entry of exportsRemoved) console.error(`  - ${entry}`);
      console.error(
        '\nRefresh with: npm run audit:route-reachability -- --update',
      );
    }
    if (
      added.length === 0 &&
      removed.length === 0 &&
      exportsAdded.length === 0 &&
      exportsRemoved.length === 0
    ) {
      console.log('No new unreachable components or exports.');
    }
  }

  process.exit(
    added.length > 0 ||
      removed.length > 0 ||
      exportsAdded.length > 0 ||
      exportsRemoved.length > 0
      ? 1
      : 0,
  );
}

main();
