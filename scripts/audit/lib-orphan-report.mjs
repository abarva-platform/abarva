#!/usr/bin/env node
/**
 * Report modules under `src/lib` that no product or operator entry point
 * reaches.
 *
 * `audit:route-reachability` watches `src/components`, and that is why eight
 * modules under `src/lib` sat in the tree for ten weeks after a sunset removed
 * their only consumer — with nothing but their own tests pointing at them, and
 * "the suite is green" nearly accepted as "the code is reached".
 *
 * This is a separate report rather than another entry in that audit's WATCHED
 * list, because under `src/lib` the question is different. A component a route
 * cannot reach is invisible to every user. A lib module a route cannot reach
 * may be perfectly alive in an operator script or an ACA job. Measured on this
 * tree, route-only reachability calls 799 modules dead and most are not; "is
 * it imported anywhere" calls all the real orphans live, because each one's own
 * test imports it. So the report classifies by WHICH entry class reaches a
 * module, and treats a test as not an entry point.
 *
 * Two of the four states are the finding, and they carry different work:
 *
 *   test-only     dead product code with a live test attached. Removing it
 *                 means removing the suite too, so check first whether the
 *                 suite's assertions cover anything a product caller needs.
 *   unreferenced  dead code with nothing attached. Remove it.
 *
 * The baseline records today's population so the check fails only on a CHANGE,
 * and it fails in BOTH directions. A one-way ratchet — fail on new entries,
 * silently tolerate stale ones — is how three other lists in this repository
 * went stale without a single red build, and the fix each time was the same.
 *
 * Usage:
 *   node scripts/audit/lib-orphan-report.mjs            # check against baseline
 *   node scripts/audit/lib-orphan-report.mjs --update   # rewrite baseline
 *   node scripts/audit/lib-orphan-report.mjs --json     # machine-readable
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { classifyModuleReferrers } from './lib/module-referrers.mjs';

const REPO_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
  '..',
);
const BASELINE = path.join(
  REPO_ROOT,
  'docs',
  'architecture',
  'orphaned-lib-modules.json',
);
const WATCHED = 'src/lib';

const NOTE = [
  'Modules under src/lib that no product or operator entry point reaches.',
  'Generated by scripts/audit/lib-orphan-report.mjs.',
  'testOnly: the only path to the module starts at a test — dead product code with a live test attached.',
  'Removing one means removing its suite, so check first whether those assertions cover anything a product caller needs; a suite repaired in place manufactures coverage for code nothing calls.',
  'unreferenced: nothing imports it at all. Remove it.',
  'This list is debt, not a permission slip. A new entry means work landed where no entry point reaches it.',
  'The check fails in both directions: a new orphan fails, and so does a stale entry that is reachable again — a list that can only grow stops being read.',
].join(' ');

function readBaseline() {
  if (!fs.existsSync(BASELINE)) return { testOnly: [], unreferenced: [] };
  const parsed = JSON.parse(fs.readFileSync(BASELINE, 'utf8'));
  return {
    testOnly: parsed.testOnly ?? [],
    unreferenced: parsed.unreferenced ?? [],
  };
}

/**
 * Compare one bucket in both directions.
 *
 * `moved` is kept apart from `added` and `removed` because a module that
 * changed state has changed meaning: test-only becoming unreferenced means its
 * suite was deleted, and unreferenced becoming test-only means a test was
 * written for code nothing calls. Folding either into "added" would report the
 * wrong repair.
 */
function diff(baseline, current) {
  const baseState = new Map();
  for (const file of baseline.testOnly) baseState.set(file, 'testOnly');
  for (const file of baseline.unreferenced) baseState.set(file, 'unreferenced');

  const nowState = new Map();
  for (const file of current.testOnly) nowState.set(file, 'testOnly');
  for (const file of current.unreferenced) nowState.set(file, 'unreferenced');

  const added = [];
  const removed = [];
  const moved = [];
  for (const [file, state] of nowState) {
    const was = baseState.get(file);
    if (was === undefined) added.push({ file, state });
    else if (was !== state) moved.push({ file, from: was, to: state });
  }
  for (const [file, state] of baseState) {
    if (!nowState.has(file)) removed.push({ file, state });
  }
  added.sort((a, b) => a.file.localeCompare(b.file));
  removed.sort((a, b) => a.file.localeCompare(b.file));
  moved.sort((a, b) => a.file.localeCompare(b.file));
  return { added, removed, moved };
}

function main() {
  const args = process.argv.slice(2);
  const update = args.includes('--update');
  const asJson = args.includes('--json');

  const result = classifyModuleReferrers(REPO_ROOT, WATCHED);

  // A walk that found no entry points would classify the whole directory as
  // dead. That is a tooling failure, and reporting it as 2,924 findings would
  // be the most confident wrong answer this script could give.
  if (result.entryPointCounts.product === 0) {
    console.error(
      'No product entry points were found. This is a tooling failure, not a finding — refusing to report every module as an orphan.',
    );
    process.exit(2);
  }

  if (update) {
    fs.writeFileSync(
      BASELINE,
      `${JSON.stringify(
        {
          note: NOTE,
          watched: WATCHED,
          entryPointCounts: result.entryPointCounts,
          counts: {
            scanned: result.scanned,
            product: result.product.length,
            tooling: result.tooling.length,
            testOnly: result.testOnly.length,
            unreferenced: result.unreferenced.length,
          },
          testOnly: result.testOnly,
          unreferenced: result.unreferenced,
        },
        null,
        2,
      )}\n`,
    );
    console.log(
      `Baseline written: ${result.testOnly.length} test-only, ${result.unreferenced.length} unreferenced of ${result.scanned} scanned.`,
    );
    return;
  }

  const baseline = readBaseline();
  const { added, removed, moved } = diff(baseline, result);

  if (asJson) {
    console.log(
      JSON.stringify(
        {
          watched: WATCHED,
          counts: {
            scanned: result.scanned,
            product: result.product.length,
            tooling: result.tooling.length,
            testOnly: result.testOnly.length,
            unreferenced: result.unreferenced.length,
          },
          entryPointCounts: result.entryPointCounts,
          added,
          removed,
          moved,
        },
        null,
        2,
      ),
    );
  } else {
    console.log(
      `src/lib referrers: ${result.scanned} modules — ${result.product.length} reached by product, ${result.tooling.length} by operator tooling only, ${result.testOnly.length} by a test only, ${result.unreferenced.length} by nothing.`,
    );
    console.log(
      `Entry points walked: ${result.entryPointCounts.product} product, ${result.entryPointCounts.tooling} tooling, ${result.entryPointCounts.test} test.`,
    );
    if (added.length > 0) {
      console.error('\nNEW orphaned module(s) — no entry point reaches these:');
      for (const { file, state } of added) console.error(`  + ${file} (${state})`);
      console.error(
        '\nA green suite over one of these is not evidence the code is reached.',
      );
      console.error(
        'Reach it from product code, or remove it — with its suite if the suite covers nothing else.',
      );
    }
    if (removed.length > 0) {
      console.error('\nBaseline is stale — these are reached again:');
      for (const { file, state } of removed) console.error(`  - ${file} (was ${state})`);
      console.error('\nRefresh with: npm run audit:lib-orphans -- --update');
    }
    if (moved.length > 0) {
      console.error('\nState changed — the repair is different than recorded:');
      for (const { file, from, to } of moved) {
        console.error(`  ~ ${file}: ${from} -> ${to}`);
      }
      console.error(
        '\ntestOnly -> unreferenced means a suite was deleted; unreferenced -> testOnly means a test was written for code nothing calls.',
      );
    }
    if (added.length === 0 && removed.length === 0 && moved.length === 0) {
      console.log('No change against the baseline.');
    }
  }

  process.exit(
    added.length > 0 || removed.length > 0 || moved.length > 0 ? 1 : 0,
  );
}

main();
