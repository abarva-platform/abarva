#!/usr/bin/env node
/**
 * Emits an idempotent SQL baseline for the ECL substrate from the live database catalog.
 *
 * This script is read-only. It asks Postgres for its own canonical definitions wherever Postgres
 * has a renderer, and only assembles the column list for tables.
 */

import { spawnSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs/promises";
import fsSync from "node:fs";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

export const DEFAULT_ECL_SCHEMAS = [
  "ecl_source",
  "ecl_context",
  "ecl_commercial",
  "ecl_review",
  "ecl_projection",
  "serving",
  "tower",
];

export const PROOF_BEGIN_MARKER = "__ECL_SUBSTRATE_BASELINE_TGZ_BEGIN__";
export const PROOF_END_MARKER = "__ECL_SUBSTRATE_BASELINE_TGZ_END__";

function usage() {
  return `Usage:
  node scripts/ops/emit-ecl-substrate-baseline.mjs [options]

Options:
  --schemas <csv>          Schema names to baseline. Default: ${DEFAULT_ECL_SCHEMAS.join(",")}
  --out-file <path>        Write emitted SQL to this path.
  --out-dir <path>         Write proof files to this folder.
  --emit-proof-bundle      Emit a base64 tar.gz proof bundle between stable log markers.
  --self-test              Run local renderer tests; no database connection.
  --help                   Show this help.

DATABASE_URL is required unless --self-test is used.
`;
}

function parseArgs(argv) {
  const parsed = {
    schemas: [...DEFAULT_ECL_SCHEMAS],
    outFile: "",
    outDir: "",
    emitProofBundle: process.env.ECL_SUBSTRATE_BASELINE_EMIT_PROOF_BUNDLE === "true",
    selfTest: false,
    help: false,
  };

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    const next = () => {
      i += 1;
      if (i >= argv.length) throw new Error(`${arg} requires a value`);
      return argv[i];
    };

    if (arg === "--help" || arg === "-h") parsed.help = true;
    else if (arg === "--self-test") parsed.selfTest = true;
    else if (arg === "--emit-proof-bundle") parsed.emitProofBundle = true;
    else if (arg === "--schemas") parsed.schemas = next().split(",").map((s) => s.trim()).filter(Boolean);
    else if (arg === "--out-file") parsed.outFile = next();
    else if (arg === "--out-dir") parsed.outDir = next();
    else throw new Error(`Unknown argument: ${arg}`);
  }

  if (parsed.schemas.length === 0) throw new Error("--schemas must name at least one schema");
  for (const schema of parsed.schemas) {
    if (!/^[a-z][a-z0-9_]*$/.test(schema)) throw new Error(`Refusing suspicious schema name: ${schema}`);
  }
  if (!parsed.outDir) {
    parsed.outDir = path.join(os.tmpdir(), `ecl-substrate-baseline-${stamp()}`);
  }
  return parsed;
}

function stamp() {
  return new Date().toISOString().replace(/[-:]/g, "").replace(/\.\d{3}Z$/, "Z");
}

function sha256(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}

export function quoteIdent(value) {
  const s = String(value);
  return `"${s.replace(/"/g, '""')}"`;
}

export function quoteLiteral(value) {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function qualified(schema, name) {
  return `${quoteIdent(schema)}.${quoteIdent(name)}`;
}

function constraintExistsSql(schema, table, constraintName) {
  return [
    "select 1",
    "from pg_constraint k",
    "join pg_class c on c.oid = k.conrelid",
    "join pg_namespace n on n.oid = c.relnamespace",
    `where n.nspname = ${quoteLiteral(schema)}`,
    `and c.relname = ${quoteLiteral(table)}`,
    `and k.conname = ${quoteLiteral(constraintName)}`,
  ].join(" ");
}

function policyExistsSql(schema, table, policyName) {
  return [
    "select 1",
    "from pg_policies",
    `where schemaname = ${quoteLiteral(schema)}`,
    `and tablename = ${quoteLiteral(table)}`,
    `and policyname = ${quoteLiteral(policyName)}`,
  ].join(" ");
}

function createSchemaSql(schema) {
  return `create schema if not exists ${quoteIdent(schema)};`;
}

export function renderColumnDefinition(column) {
  const parts = [quoteIdent(column.column_name), column.data_type];
  if (column.attidentity === "a") parts.push("generated always as identity");
  else if (column.attidentity === "d") parts.push("generated by default as identity");
  else if (column.attgenerated === "s" && column.generated_expr) {
    parts.push(`generated always as (${column.generated_expr}) stored`);
  } else if (column.default_expr) {
    parts.push(`default ${column.default_expr}`);
  }
  if (column.attnotnull) parts.push("not null");
  return parts.join(" ");
}

export function renderCreateTable(table, columns) {
  if (!columns.length) throw new Error(`No columns found for ${table.schema_name}.${table.table_name}`);
  const persistence = table.relpersistence === "u" ? "unlogged " : "";
  const columnSql = columns.map((column) => `  ${renderColumnDefinition(column)}`).join(",\n");
  return `create ${persistence}table if not exists ${qualified(table.schema_name, table.table_name)} (\n${columnSql}\n);`;
}

export function renderConstraint(constraint) {
  const sql = [
    "do $$",
    "begin",
    `  if not exists (${constraintExistsSql(
      constraint.schema_name,
      constraint.table_name,
      constraint.constraint_name,
    )}) then`,
    `    alter table ${qualified(constraint.schema_name, constraint.table_name)} add constraint ${quoteIdent(
      constraint.constraint_name,
    )} ${constraint.definition};`,
    "  end if;",
    "end",
    "$$;",
  ];
  return sql.join("\n");
}

export function addIfNotExistsToIndexDef(indexDef) {
  return String(indexDef).replace(
    /^CREATE\s+(UNIQUE\s+)?INDEX\s+(?!IF\s+NOT\s+EXISTS\b)/i,
    (_match, unique = "") => `CREATE ${unique ?? ""}INDEX IF NOT EXISTS `,
  );
}

export function renderFunction(functionDef) {
  return `${functionDef.definition
    .trim()
    .replace(/;+\s*$/, "")
    .replace(/^CREATE FUNCTION\b/i, "CREATE OR REPLACE FUNCTION")};`;
}

export function orderViewsByDependency(views, dependencies) {
  const byKey = new Map(views.map((view) => [view.view_key, { ...view, depth: 0 }]));
  const outgoing = new Map();
  for (const dep of dependencies) {
    if (!byKey.has(dep.view_key) || !byKey.has(dep.depends_on_key)) continue;
    if (!outgoing.has(dep.view_key)) outgoing.set(dep.view_key, new Set());
    outgoing.get(dep.view_key).add(dep.depends_on_key);
  }

  const visiting = new Set();
  const visited = new Set();
  const depthOf = (key) => {
    if (visited.has(key)) return byKey.get(key).depth;
    if (visiting.has(key)) throw new Error(`View dependency cycle detected at ${key}`);
    visiting.add(key);
    const deps = [...(outgoing.get(key) ?? [])];
    const depth = deps.length ? 1 + Math.max(...deps.map(depthOf)) : 0;
    byKey.get(key).depth = depth;
    visiting.delete(key);
    visited.add(key);
    return depth;
  };

  for (const key of byKey.keys()) depthOf(key);
  return [...byKey.values()].sort(
    (a, b) =>
      a.depth - b.depth ||
      a.schema_name.localeCompare(b.schema_name) ||
      a.view_name.localeCompare(b.view_name),
  );
}

export function renderView(view) {
  const definition = view.definition.trim().replace(/;$/, "");
  if (view.relkind === "m") {
    return `create materialized view if not exists ${qualified(view.schema_name, view.view_name)} as\n${definition}\nwith no data;`;
  }
  return `create or replace view ${qualified(view.schema_name, view.view_name)} as\n${definition};`;
}

function roleSql(role) {
  return String(role).toLowerCase() === "public" ? "public" : quoteIdent(role);
}

export function renderPolicy(policy) {
  const roles = Array.isArray(policy.roles) && policy.roles.length ? policy.roles.map(roleSql).join(", ") : "public";
  const clauses = [
    `create policy ${quoteIdent(policy.policyname)} on ${qualified(policy.schemaname, policy.tablename)}`,
    `as ${String(policy.permissive).toLowerCase()}`,
    `for ${String(policy.cmd).toLowerCase()}`,
    `to ${roles}`,
  ];
  if (policy.qual) clauses.push(`using (${policy.qual})`);
  if (policy.with_check) clauses.push(`with check (${policy.with_check})`);
  return [
    "do $$",
    "begin",
    `  if not exists (${policyExistsSql(policy.schemaname, policy.tablename, policy.policyname)}) then`,
    `    ${clauses.join("\n      ")};`,
    "  end if;",
    "end",
    "$$;",
  ].join("\n");
}

function renderRls(table) {
  const statements = [];
  if (table.relrowsecurity) statements.push(`alter table ${qualified(table.schema_name, table.table_name)} enable row level security;`);
  if (table.relforcerowsecurity) statements.push(`alter table ${qualified(table.schema_name, table.table_name)} force row level security;`);
  return statements.join("\n");
}

function section(title, statements) {
  const body = statements.filter(Boolean).join("\n\n");
  return `-- ${title}\n${body || "-- none"}`;
}

export function renderBaselineSql(catalog) {
  const tablesByKey = new Map(catalog.tables.map((table) => [table.table_key, table]));
  const columnsByTable = new Map();
  for (const column of catalog.columns) {
    if (!columnsByTable.has(column.table_key)) columnsByTable.set(column.table_key, []);
    columnsByTable.get(column.table_key).push(column);
  }
  const orderedViews = orderViewsByDependency(catalog.views, catalog.viewDependencies);

  const statements = [
    "-- ECL substrate schema baseline",
    "-- Generated from the lab Postgres catalog by scripts/ops/emit-ecl-substrate-baseline.mjs.",
    "-- Definitions use Postgres catalog renderers where available; table columns are assembled from pg_attribute.",
    "",
    section("1. schemas", catalog.schemas.map(createSchemaSql)),
    "",
    section(
      "2. tables, columns only",
      catalog.tables.map((table) => renderCreateTable(table, columnsByTable.get(table.table_key) ?? [])),
    ),
    "",
    section("3. primary, unique and check constraints", catalog.tableConstraints.map(renderConstraint)),
    "",
    section("4. foreign keys", catalog.foreignKeys.map(renderConstraint)),
    "",
    section("5. indexes", catalog.indexes.map((index) => `${addIfNotExistsToIndexDef(index.indexdef.trim().replace(/;$/, ""))};`)),
    "",
    section("6. functions", catalog.functions.map(renderFunction)),
    "",
    section("7. views by dependency depth", orderedViews.map(renderView)),
    "",
    section("8. row-level security and policies", [
      ...catalog.tables.map(renderRls),
      ...catalog.policies.map(renderPolicy),
    ]),
    "",
  ];
  for (const table of catalog.tables) {
    if (!tablesByKey.has(table.table_key)) throw new Error(`internal table key drift: ${table.table_key}`);
  }
  return statements.join("\n");
}

async function readCatalog(client, schemas) {
  const schemaRows = await client.query(
    `select nspname as schema_name
       from pg_namespace
      where nspname = any($1)
      order by nspname`,
    [schemas],
  );
  const tables = await client.query(
    `select n.nspname as schema_name,
            c.relname as table_name,
            n.nspname || '.' || c.relname as table_key,
            c.relpersistence,
            c.relrowsecurity,
            c.relforcerowsecurity
       from pg_class c
       join pg_namespace n on n.oid = c.relnamespace
      where n.nspname = any($1)
        and c.relkind = 'r'
      order by n.nspname, c.relname`,
    [schemas],
  );
  const columns = await client.query(
    `select n.nspname as schema_name,
            c.relname as table_name,
            n.nspname || '.' || c.relname as table_key,
            a.attname as column_name,
            format_type(a.atttypid, a.atttypmod) as data_type,
            a.attnotnull,
            a.attidentity,
            a.attgenerated,
            pg_get_expr(d.adbin, d.adrelid) as default_expr,
            case when a.attgenerated <> '' then pg_get_expr(d.adbin, d.adrelid) else null end as generated_expr,
            a.attnum
       from pg_attribute a
       join pg_class c on c.oid = a.attrelid
       join pg_namespace n on n.oid = c.relnamespace
       left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
      where n.nspname = any($1)
        and c.relkind = 'r'
        and a.attnum > 0
        and not a.attisdropped
      order by n.nspname, c.relname, a.attnum`,
    [schemas],
  );
  const constraints = await client.query(
    `select n.nspname as schema_name,
            c.relname as table_name,
            k.conname as constraint_name,
            k.contype,
            pg_get_constraintdef(k.oid, true) as definition
       from pg_constraint k
       join pg_class c on c.oid = k.conrelid
       join pg_namespace n on n.oid = c.relnamespace
      where n.nspname = any($1)
        and k.contype in ('p', 'u', 'c', 'f')
      order by case k.contype when 'p' then 1 when 'u' then 2 when 'c' then 3 when 'f' then 4 else 5 end,
               n.nspname, c.relname, k.conname`,
    [schemas],
  );
  const indexes = await client.query(
    `select i.schemaname,
            i.tablename,
            i.indexname,
            i.indexdef
       from pg_indexes i
      where i.schemaname = any($1)
        and not exists (
          select 1
            from pg_constraint k
            join pg_class ic on ic.oid = k.conindid
            join pg_namespace ins on ins.oid = ic.relnamespace
           where ins.nspname = i.schemaname
             and ic.relname = i.indexname
        )
      order by i.schemaname, i.tablename, i.indexname`,
    [schemas],
  );
  const functions = await client.query(
    `select n.nspname as schema_name,
            p.proname as function_name,
            pg_get_function_identity_arguments(p.oid) as identity_arguments,
            pg_get_functiondef(p.oid) as definition
       from pg_proc p
       join pg_namespace n on n.oid = p.pronamespace
      where n.nspname = any($1)
      order by n.nspname, p.proname, pg_get_function_identity_arguments(p.oid)`,
    [schemas],
  );
  const views = await client.query(
    `select n.nspname as schema_name,
            c.relname as view_name,
            n.nspname || '.' || c.relname as view_key,
            c.relkind,
            pg_get_viewdef(c.oid, true) as definition
       from pg_class c
       join pg_namespace n on n.oid = c.relnamespace
      where n.nspname = any($1)
        and c.relkind in ('v', 'm')
      order by n.nspname, c.relkind, c.relname`,
    [schemas],
  );
  const viewDependencies = await client.query(
    `select distinct
            vn.nspname || '.' || vc.relname as view_key,
            rn.nspname || '.' || rc.relname as depends_on_key
       from pg_rewrite rw
       join pg_class vc on vc.oid = rw.ev_class
       join pg_namespace vn on vn.oid = vc.relnamespace
       join pg_depend d on d.objid = rw.oid
       join pg_class rc on rc.oid = d.refobjid
       join pg_namespace rn on rn.oid = rc.relnamespace
      where vn.nspname = any($1)
        and rn.nspname = any($1)
        and vc.relkind in ('v', 'm')
        and rc.relkind in ('v', 'm')
        and vc.oid <> rc.oid
      order by view_key, depends_on_key`,
    [schemas],
  );
  const policies = await client.query(
    `select schemaname,
            tablename,
            policyname,
            permissive,
            roles,
            cmd,
            qual,
            with_check
       from pg_policies
      where schemaname = any($1)
      order by schemaname, tablename, policyname`,
    [schemas],
  );

  return {
    schemas: schemaRows.rows.map((row) => row.schema_name),
    tables: tables.rows,
    columns: columns.rows,
    tableConstraints: constraints.rows.filter((row) => row.contype !== "f"),
    foreignKeys: constraints.rows.filter((row) => row.contype === "f"),
    indexes: indexes.rows,
    functions: functions.rows,
    views: views.rows,
    viewDependencies: viewDependencies.rows,
    policies: policies.rows,
  };
}

function buildSummary(catalog, sql) {
  return {
    event: "ecl_substrate_baseline_emitted",
    status: "ok",
    generated_at: new Date().toISOString(),
    schemas: catalog.schemas,
    counts: {
      tables: catalog.tables.length,
      columns: catalog.columns.length,
      table_constraints: catalog.tableConstraints.length,
      foreign_keys: catalog.foreignKeys.length,
      indexes: catalog.indexes.length,
      functions: catalog.functions.length,
      views: catalog.views.length,
      view_dependencies: catalog.viewDependencies.length,
      rls_enabled_tables: catalog.tables.filter((table) => table.relrowsecurity).length,
      policies: catalog.policies.length,
    },
    sql_sha256: sha256(sql),
  };
}

async function writeOutputs(options, catalog, sql) {
  await fs.mkdir(options.outDir, { recursive: true });
  const outFile = options.outFile || path.join(options.outDir, "ecl_substrate_baseline.sql");
  const summary = buildSummary(catalog, sql);
  await fs.writeFile(outFile, sql);
  await fs.writeFile(path.join(options.outDir, "summary.json"), `${JSON.stringify(summary, null, 2)}\n`);
  await fs.writeFile(
    path.join(options.outDir, "object-order.json"),
    `${JSON.stringify(
      {
        schemas: catalog.schemas,
        tables: catalog.tables.map((table) => table.table_key),
        functions: catalog.functions.map((fn) => `${fn.schema_name}.${fn.function_name}(${fn.identity_arguments})`),
        views: orderViewsByDependency(catalog.views, catalog.viewDependencies).map((view) => ({
          key: view.view_key,
          depth: view.depth,
        })),
      },
      null,
      2,
    )}\n`,
  );
  return { outFile, summary };
}

function emitProofBundle(outDir) {
  const tarPath = path.join(os.tmpdir(), `ecl-substrate-baseline-proof-${stamp()}.tgz`);
  const result = spawnSync("tar", ["-czf", tarPath, "-C", outDir, "."], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
  if (result.status !== 0) throw new Error(result.stderr || result.stdout || "tar proof bundle failed");
  const encoded = fsSync.readFileSync(tarPath).toString("base64");
  console.log(PROOF_BEGIN_MARKER);
  console.log(encoded);
  console.log(PROOF_END_MARKER);
}

function selfTest() {
  const catalog = {
    schemas: ["ecl_source", "serving"],
    tables: [
      {
        schema_name: "ecl_source",
        table_name: "source_record",
        table_key: "ecl_source.source_record",
        relpersistence: "p",
        relrowsecurity: true,
        relforcerowsecurity: false,
      },
    ],
    columns: [
      {
        table_key: "ecl_source.source_record",
        column_name: "id",
        data_type: "uuid",
        default_expr: "gen_random_uuid()",
        attnotnull: true,
        attidentity: "",
        attgenerated: "",
      },
      {
        table_key: "ecl_source.source_record",
        column_name: "tenant_key",
        data_type: "text",
        default_expr: null,
        attnotnull: true,
        attidentity: "",
        attgenerated: "",
      },
    ],
    tableConstraints: [
      {
        schema_name: "ecl_source",
        table_name: "source_record",
        constraint_name: "source_record_pkey",
        definition: "PRIMARY KEY (id)",
      },
    ],
    foreignKeys: [],
    indexes: [
      {
        indexdef: "CREATE INDEX source_record_tenant_idx ON ecl_source.source_record USING btree (tenant_key)",
      },
    ],
    functions: [
      {
        schema_name: "serving",
        function_name: "active_keys",
        identity_arguments: "",
        definition: "CREATE FUNCTION serving.active_keys()\n RETURNS TABLE(tenant_key text)\n LANGUAGE sql\nAS $function$ select 'x'::text $function$",
      },
    ],
    views: [
      {
        schema_name: "serving",
        view_name: "source_record_v1",
        view_key: "serving.source_record_v1",
        relkind: "v",
        definition: " SELECT source_record.tenant_key\n   FROM ecl_source.source_record;",
      },
    ],
    viewDependencies: [],
    policies: [
      {
        schemaname: "ecl_source",
        tablename: "source_record",
        policyname: "source_record_tenant_select",
        permissive: "PERMISSIVE",
        roles: ["public"],
        cmd: "SELECT",
        qual: "tenant_key = current_setting('app.tenant_key'::text, true)",
        with_check: null,
      },
    ],
  };
  const sql = renderBaselineSql(catalog);
  const required = [
    "create schema if not exists \"ecl_source\";",
    "create table if not exists \"ecl_source\".\"source_record\"",
    "alter table \"ecl_source\".\"source_record\" add constraint \"source_record_pkey\" PRIMARY KEY (id);",
    "CREATE INDEX IF NOT EXISTS source_record_tenant_idx",
    "CREATE OR REPLACE FUNCTION serving.active_keys()",
    "create or replace view \"serving\".\"source_record_v1\" as",
    "alter table \"ecl_source\".\"source_record\" enable row level security;",
    "create policy \"source_record_tenant_select\" on \"ecl_source\".\"source_record\"",
  ];
  for (const value of required) {
    if (!sql.includes(value)) throw new Error(`self-test missing SQL fragment: ${value}`);
  }
  console.log("self-test passed");
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  if (options.help) {
    process.stdout.write(usage());
    return;
  }
  if (options.selfTest) {
    selfTest();
    return;
  }

  const url = process.env.DATABASE_URL;
  if (!url) throw new Error("DATABASE_URL is required");
  const { default: pg } = await import("pg");
  const client = new pg.Client({
    connectionString: url,
    ssl: { rejectUnauthorized: false },
  });
  await client.connect();
  try {
    const catalog = await readCatalog(client, options.schemas);
    const sql = renderBaselineSql(catalog);
    const { outFile, summary } = await writeOutputs(options, catalog, sql);
    console.log(JSON.stringify({ ...summary, out_file: outFile }, null, 2));
    if (options.emitProofBundle) emitProofBundle(options.outDir);
  } finally {
    await client.end();
  }
}

const invokedAsScript = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (invokedAsScript) {
  main().catch((error) => {
    console.error(`ECL_SUBSTRATE_BASELINE_ERR\t${error.message}`);
    process.exit(1);
  });
}
