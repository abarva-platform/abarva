"""Generate the character-width table embedded in sdk.py.

WHY A TABLE AND NOT A HEURISTIC

The first measure_text was per-character weights tuned by eye. It under-measured
badly, fit_text under-wrapped, title boxes were sized for fewer lines than the
text needed, and the overflow collided with whatever was beneath — visible text
on text on the cover and four other slides of the first composed deck.

WHY THE WIDEST LIKELY FONT AND NOT THE BRAND FONT

The deck declares Inter. Inter is frequently NOT installed — LibreOffice here
substitutes Verdana, and a client's PowerPoint will substitute something too.
Measuring against Inter would be measuring a font the renderer may never use. So
the table is built from a deliberately WIDE fallback: if the real font is
narrower, the text merely has slack, which costs nothing. Under-measuring costs
a broken slide.

The table is generated at build time and embedded as data, because the sandbox
cannot open font files — reads are confined to the interpreter prefix, the SDK
directory and scratch.

Run: build_width_table.py > widths.py
"""

from __future__ import annotations

import sys

from PIL import ImageFont

# Wide, and present on macOS, Windows and most Linux font packages.
CANDIDATES = [
    "/System/Library/Fonts/Supplemental/Verdana.ttf",
    "/System/Library/Fonts/Supplemental/Tahoma.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
]
REFERENCE_PT = 100


def main() -> int:
    path = next((p for p in CANDIDATES if __import__("os").path.exists(p)), None)
    if not path:
        print("no candidate font found", file=sys.stderr)
        return 1
    regular = ImageFont.truetype(path, REFERENCE_PT)
    bold_path = path.replace(".ttf", " Bold.ttf")
    try:
        bold = ImageFont.truetype(bold_path, REFERENCE_PT)
    except OSError:
        bold = regular

    def widths(font) -> dict[int, float]:
        out = {}
        for code in range(32, 127):
            ch = chr(code)
            out[code] = round(font.getlength(ch) / REFERENCE_PT, 4)
        return out

    reg = widths(regular)
    bld = widths(bold)
    print(f"# Generated by build_width_table.py from {path}")
    print(f"# Widths are in EM units at 1pt; multiply by point size for inches/72.")
    print("CHAR_W = {")
    for code, w in reg.items():
        print(f"    {code}: {w},")
    print("}")
    print("CHAR_W_BOLD = {")
    for code, w in bld.items():
        print(f"    {code}: {w},")
    print("}")
    print(f"DEFAULT_W = {round(sum(reg.values()) / len(reg), 4)}")
    print(f"DEFAULT_W_BOLD = {round(sum(bld.values()) / len(bld), 4)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
