/**
 * A declared relationship row from `12_relationships.csv`, as exposed on
 * `buildCanonicalTenantDataReport(...).relationshipCandidates` -- NOT the same structure as
 * `records` filtered to `objectType === "relationship_source_row"`. That path merges rows by
 * source-entity display name before they ever reach here (the entity-record dedup logic, correct
 * for "the same system mentioned in five files," is wrong for "this system's five distinct
 * relationships" -- it silently kept only one relationship per source entity, losing roughly
 * two-thirds of a 2,302-row file in the process). `relationshipCandidates` is the loader's
 * one-candidate-per-row structure and does not go through that merge, so it is the correct source
 * for real per-row relationship facts. This type mirrors the subset of fields this file needs from
 * the loader's internal (unexported) `RelationshipCandidate` shape.
 */
export interface RelationshipRow {
  relationshipType: string;
  sourceObjectType: string;
  sourceObjectName: string;
  targetObjectType: string;
  targetObjectName: string;
  sourcePath: string;
  resolutionStatus?: "resolved" | "unresolved";
}

export function buildDecisionContext(records: Record_[], relationshipRows: RelationshipRow[] = []): DecisionContext {
  const of = (t: string) => records.filter((r) => r.objectType === t);

  const profile = of("tenant_profile")[0]?.attributes ?? {};
  const functions = of("business_function");
  const apps = of("application_system");
  const vendors = of("vendor_contract");
  const programs = of("program_initiative");
  const metrics = of("metric_outcome");
  const risks = of("risk_or_control");
  const interviews = of("ai_value_interview_evidence");

  // ---- business ----
  const business = {
    revenue: num(profile.revenueUsd),
    employeeCount: num(profile.employeeCount),
    businessModel: str(profile.businessModel),
    industry: [str(profile.industry), str(profile.subIndustry)].filter(Boolean).join(" — ") || null,
    operatingSegments: [...new Set(functions.map((f) => str(f.attributes.businessSegment)).filter((v): v is string => Boolean(v)))],
    customerSegments: list(profile.customerSegments),
    operatingRegions: list(profile.operatingRegions),
  };

  // ---- strategy ----
  // Deliberately empty unless a canonical record explicitly links a program to a priority. No
  // fuzzy text-matching here — that belongs in the candidate-relationship engine, not the
  // authoritative decision context, per the standing rule: candidate relationships are never facts.
  const strategy = {
    mission: str(profile.mission),
    statedPriorities: list(profile.strategicPriorities),
    priorityToProgramLinks: [] as Array<{ priority: string; programs: string[] }>,
  };

  // ---- portfolio ----
  const totalBudget = programs.reduce((s, p) => s + (num(p.attributes.budgetUsd) ?? 0), 0);
  const totalExpectedValue = programs.reduce((s, p) => s + (num(p.attributes.expectedValueUsd) ?? 0), 0);
  const stalledPrograms = programs
    .filter((p) => {
      const pct = num(p.attributes.pctComplete);
      const blocked = str(p.attributes.blockedReason);
      return blocked !== null || (pct !== null && pct < 15 && str(p.attributes.status)?.toLowerCase() !== "not_started");
    })
    .map((p) => ({
      name: str(p.attributes.programName) ?? "(unnamed)",
      pctComplete: num(p.attributes.pctComplete) ?? 0,
      blockedReason: str(p.attributes.blockedReason),
    }));
  const topByValue = programs
    .map((p) => ({ name: str(p.attributes.programName) ?? "(unnamed)", expectedValue: num(p.attributes.expectedValueUsd) ?? 0 }))
    .filter((p) => p.expectedValue > 0)
    .sort((a, b) => b.expectedValue - a.expectedValue)
    .slice(0, 5);

  // ---- technology ----
  const spendFacts = of("spend_value_fact");
  const technologyBudget = spendFacts.reduce((s, r) => s + (num(r.attributes.annualSpendUsd) ?? 0), 0);
  const thirdPartyContracted = vendors.reduce((s, v) => s + (num(v.attributes.annualSpendUsd) ?? 0), 0);
  const byFunctionMap = new Map<string, { count: number; cost: number }>();
  for (const a of apps) {
    const fn = str(a.attributes.businessFunction) ?? str(a.attributes.supportedFunction) ?? "Unclassified";
    const entry = byFunctionMap.get(fn) ?? { count: 0, cost: 0 };
    entry.count += 1;
    entry.cost += num(a.attributes.annualCostUsd) ?? 0;
    byFunctionMap.set(fn, entry);
  }
  const byFunction = [...byFunctionMap.entries()]
    .map(([fn, v]) => ({ function: fn, count: v.count, cost: v.cost }))
    .sort((a, b) => b.cost - a.cost);
  const replaceable = apps.filter((a) => str(a.attributes.replacementCandidate) === "yes");
  const technology = {
    applicationCount: apps.length,
    technologyBudget,
    thirdPartyContracted,
    byFunction,
    replacementCandidates: {
      count: replaceable.length,
      cost: replaceable.reduce((s, a) => s + (num(a.attributes.annualCostUsd) ?? 0), 0),
    },
  };

  // ---- vendors ----
  const totalVendorSpend = vendors.reduce((s, v) => s + (num(v.attributes.annualSpendUsd) ?? 0), 0);
  const topByShare = vendors
    .map((v) => ({
      name: str(v.attributes.vendorName) ?? "(unnamed)",
      spend: num(v.attributes.annualSpendUsd) ?? 0,
      share: totalVendorSpend > 0 ? (num(v.attributes.annualSpendUsd) ?? 0) / totalVendorSpend : 0,
      supportedFunctions: list(v.attributes.supportedFunctions),
    }))
    .sort((a, b) => b.spend - a.spend)
    .slice(0, 8);

  // ---- organization ----
  const organization = {
    functionCount: functions.length,
    orgUnitCount: of("org_owner").length,
    leadershipTeam: list(profile.leadershipTeam),
  };

  // ---- performance ----
  // Direction-of-good inferred from where the client placed the target relative to the baseline —
  // the same logic the orientation pack's "standing" block uses, kept consistent across layers.
  function measurement(v: Value): { quantity: number } | null {
    const raw = v?.value;
    if (typeof raw === "number") return Number.isFinite(raw) ? { quantity: raw } : null;
    if (typeof raw !== "string") return null;
    const match = raw.trim().match(/^-?[\d,]+(?:\.\d+)?/);
    if (!match) return null;
    const quantity = Number(match[0].replace(/,/g, ""));
    return Number.isFinite(quantity) ? { quantity } : null;
  }
  let improving = 0, worsening = 0, notComparable = 0, inconsistentNotation = 0;
  for (const m of metrics) {
    const base = measurement(m.attributes.baselineValue);
    const target = measurement(m.attributes.targetValue);
    const actual = measurement(m.attributes.actualValue);
    if (!base || !target || !actual || target.quantity === base.quantity) { notComparable++; continue; }
    const rawBase = str(m.attributes.baselineValue) ?? "";
    const rawTarget = str(m.attributes.targetValue) ?? "";
    const rawActual = str(m.attributes.actualValue) ?? "";
    const notations = new Set([rawBase.includes("%"), rawTarget.includes("%"), rawActual.includes("%")]);
    if (notations.size > 1) inconsistentNotation++;
    const intended = Math.sign(target.quantity - base.quantity);
    const moved = Math.sign(actual.quantity - base.quantity);
    if (moved === intended && moved !== 0) improving++;
    else if (moved !== intended) worsening++;
  }
  const performance = {
    metricCount: metrics.length,
    comparable: improving + worsening,
    improving,
    worsening,
    notComparable,
    inconsistentNotation,
  };

  // ---- risk ----
  const systemRiskCounts = new Map<string, number>();
  for (const r of risks) {
    for (const sys of list(r.attributes.systemsImpacted)) {
      systemRiskCounts.set(sys, (systemRiskCounts.get(sys) ?? 0) + 1);
    }
  }
  const bySystemConcentration = [...systemRiskCounts.entries()]
    .map(([system, riskCount]) => ({ system, riskCount }))
    .sort((a, b) => b.riskCount - a.riskCount)
    .slice(0, 5);
  const highSeverity = risks
    .filter((r) => (str(r.attributes.severity) ?? "").toLowerCase() === "high" || (num(r.attributes.inherentRiskScore) ?? 0) >= 9)
    .map((r) => ({
      name: str(r.attributes.riskOrControlName) ?? "(unnamed)",
      severity: str(r.attributes.severity) ?? "unspecified",
      system: list(r.attributes.systemsImpacted)[0] ?? null,
    }));
  const risk = { riskCount: risks.length, bySystemConcentration, highSeverity };

  // ---- leadership voice ----
  const leaderSet = new Set(interviews.map((i) => str(i.attributes.stakeholderRole)).filter(Boolean));
  const themeCounts = new Map<string, Set<string>>();
  for (const row of interviews) {
    const theme = str(row.attributes.themeTags);
    const role = str(row.attributes.stakeholderRole);
    if (!theme || !role) continue;
    if (!themeCounts.has(theme)) themeCounts.set(theme, new Set());
    themeCounts.get(theme)!.add(role);
  }
  const themeFrequency = [...themeCounts.entries()]
    .map(([theme, roles]) => ({ theme, leaderCount: roles.size }))
    .sort((a, b) => b.leaderCount - a.leaderCount);
  const contradictionCount = interviews.filter((i) => (str(i.attributes.contradictsRecord) ?? "").startsWith("yes")).length;

  // Real quotes, selected deterministically -- never summarized. consent_to_attribute is a real
  // governance field on this file; a quote with no consent, or no quote text at all, is never
  // eligible regardless of how well it would illustrate a theme.
  // consent_to_attribute is "named" | "anonymous" | "role_only" -- not yes/no. The signal below
  // attributes by role only ("A {role} said..."), never by name, so both "named" and "role_only"
  // consent cover it; "anonymous" means even role-level attribution was not consented to.
  const roleAttributionConsented = new Set(["named", "role_only"]);
  const consented = interviews.filter(
    (i) => roleAttributionConsented.has((str(i.attributes.consentToAttribute) ?? "").toLowerCase()) && str(i.attributes.verbatimQuote),
  );
  const testimony: DecisionContext["leadershipVoice"]["testimony"] = [];
  const quotedThemes = new Set<string>();
  for (const [theme, roles] of themeCounts.entries()) {
    const candidate = consented.find((i) => str(i.attributes.themeTags) === theme);
    if (!candidate || quotedThemes.has(theme)) continue;
    quotedThemes.add(theme);
    const tag = roles.size === THRESHOLDS.dissentLeaderCount ? "dissent" : roles.size >= Math.ceil(interviews.length ? leaderSet.size * THRESHOLDS.consensusLeaderShare : 0) ? "consensus" : null;
    if (!tag) continue;
    testimony.push({
      quote: str(candidate.attributes.verbatimQuote)!,
      role: str(candidate.attributes.stakeholderRole) ?? "unspecified",
      theme,
      sentiment: str(candidate.attributes.sentiment),
      tag,
    });
  }
  for (const row of consented.filter((i) => (str(i.attributes.contradictsRecord) ?? "").startsWith("yes")).slice(0, 2)) {
    testimony.push({
      quote: str(row.attributes.verbatimQuote)!,
      role: str(row.attributes.stakeholderRole) ?? "unspecified",
      theme: str(row.attributes.themeTags) ?? "unspecified",
      sentiment: str(row.attributes.sentiment),
      tag: "contradiction",
    });
  }

  const leadershipVoice = {
    interviewCount: interviews.length,
    leaderCount: leaderSet.size,
    themeFrequency,
    contradictionCount,
    testimony,
  };

  // ---- workforce ----
  const workforceRoles = of("workforce_role");
  const automationOpportunityRoles = workforceRoles
    .filter((r) => str(r.attributes.automationOpportunity))
    .map((r) => ({
      role: str(r.attributes.personaOrRole) ?? "(unnamed)",
      function: str(r.attributes.functionName) ?? "(unclassified)",
      count: num(r.attributes.roleCount) ?? 0,
      opportunity: str(r.attributes.automationOpportunity) ?? "",
    }))
    .sort((a, b) => b.count - a.count);
  const workforce = {
    roleCount: workforceRoles.length,
    totalHeadcount: workforceRoles.reduce((s, r) => s + (num(r.attributes.roleCount) ?? 0), 0),
    automationOpportunityRoles,
  };

  // ---- infrastructure ----
  const infraPlatforms = of("infrastructure_platform");
  const coldDrTiers = new Set(["tier3_backup_only", "tier2_warm"]);
  const atRiskPlatforms = infraPlatforms
    .filter((p) => {
      const criticality = (str(p.attributes.criticality) ?? "").toLowerCase();
      const headroom = num(p.attributes.capacityHeadroomPct);
      const drTier = (str(p.attributes.drTier) ?? "").toLowerCase();
      const highCriticality = criticality === "tier1" || criticality === "tier2";
      return highCriticality && ((headroom !== null && headroom < THRESHOLDS.lowCapacityHeadroomPct) || coldDrTiers.has(drTier));
    })
    .map((p) => ({
      name: str(p.attributes.platformName) ?? "(unnamed)",
      criticality: str(p.attributes.criticality) ?? "unspecified",
      drTier: str(p.attributes.drTier),
      capacityHeadroomPct: num(p.attributes.capacityHeadroomPct),
    }));
  const infrastructure = {
    platformCount: infraPlatforms.length,
    totalAnnualCost: infraPlatforms.reduce((s, p) => s + (num(p.attributes.annualCostUsd) ?? 0), 0),
    atRiskPlatforms,
  };

  // ---- data estate ----
  const dataAssets = of("data_asset_or_integration");
  const dataEstate = {
    assetCount: dataAssets.length,
    regulatedCount: dataAssets.filter((a) => (str(a.attributes.regulatedDataFlag) ?? "").toLowerCase() === "true" || (str(a.attributes.regulatedDataFlag) ?? "").toLowerCase() === "yes").length,
    notAtTargetStateCount: dataAssets.filter((a) => (str(a.attributes.currentStateOrTargetState) ?? "").toLowerCase() === "current_state").length,
  };

  // ---- AI portfolio (use cases + realization + tool adoption) ----
  const aiUseCases = of("ai_automation_use_case");
  const aiRealization = of("ai_value_realization_signal");
  const aiToolUsage = of("ai_tool_usage_observation");
  const statusCounts = new Map<string, number>();
  for (const u of aiUseCases) {
    const status = str(u.attributes.currentStatus) ?? "unspecified";
    statusCounts.set(status, (statusCounts.get(status) ?? 0) + 1);
  }
  const toolAdoptionGaps = aiToolUsage
    .map((t) => ({ tool: str(t.attributes.toolName) ?? "(unnamed)", adoptionGapPct: num(t.attributes.adoptionGapPct) ?? 0 }))
    .filter((t) => t.adoptionGapPct >= THRESHOLDS.materialAdoptionGapPct)
    .sort((a, b) => b.adoptionGapPct - a.adoptionGapPct);
  const aiPortfolio = {
    useCaseCount: aiUseCases.length,
    byStatus: [...statusCounts.entries()].map(([status, count]) => ({ status, count })).sort((a, b) => b.count - a.count),
    promisedValue: aiRealization.reduce((s, r) => s + (num(r.attributes.promisedValueUsd) ?? 0), 0),
    financeValidatedValue: aiRealization.reduce((s, r) => s + (num(r.attributes.financeValidatedValueUsd) ?? 0), 0),
    toolAdoptionGaps,
  };

  // ---- relationships (declared canonical links, read from the loader's undeduplicated
  // relationshipCandidates -- not the candidate-relationship *engine*, and not the merged
  // relationship_source_row canonical records, which lose most of this file's rows -- see the
  // RelationshipRow doc comment) ----
  const declaredRels = relationshipRows.filter(
    (r) => r.sourcePath.endsWith("12_relationships.csv") && r.resolutionStatus !== "unresolved",
  );
  const integrationCounts = new Map<string, number>();
  for (const r of declaredRels) {
    if (r.relationshipType === "integrates_with" && r.sourceObjectType === "system") {
      integrationCounts.set(r.sourceObjectName, (integrationCounts.get(r.sourceObjectName) ?? 0) + 1);
    }
  }
  const hubSystems = [...integrationCounts.entries()]
    .map(([system, integrationCount]) => ({ system, integrationCount }))
    .filter((s) => s.integrationCount >= THRESHOLDS.hubIntegrationCount)
    .sort((a, b) => b.integrationCount - a.integrationCount)
    .slice(0, 5);
  const riskToProgramImpacts = declaredRels
    .filter((r) => r.sourceObjectType === "risk_or_control" && r.targetObjectType === "program" && r.relationshipType === "impacts")
    .map((r) => ({ risk: r.sourceObjectName, program: r.targetObjectName }));
  const programSponsorship = declaredRels
    .filter((r) => r.sourceObjectType === "program" && r.targetObjectType === "org_unit" && r.relationshipType === "sponsored_by")
    .map((r) => ({ program: r.sourceObjectName, sponsor: r.targetObjectName }));
  const relationships = { totalRows: declaredRels.length, hubSystems, riskToProgramImpacts, programSponsorship };

  // ---- evidence governance ----
  const evidenceSources = of("evidence_source");
  const evidenceGovernance = {
    sourceCount: evidenceSources.length,
    notApprovedCount: evidenceSources.filter((s) => (str(s.attributes.approvedForLoading) ?? "").toLowerCase() !== "true" && (str(s.attributes.approvedForLoading) ?? "").toLowerCase() !== "yes").length,
  };

  // ---- managed services ----
  const managedServiceRows = of("managed_service_scope");
  const managedServices = {
    serviceCount: managedServiceRows.length,
    totalRunCost: managedServiceRows.reduce((s, r) => s + (num(r.attributes.runCostUsd) ?? 0), 0),
    services: managedServiceRows
      .map((r) => ({
        tower: str(r.attributes.serviceTower) ?? "(unclassified)",
        name: str(r.attributes.serviceName) ?? "(unnamed)",
        provider: str(r.attributes.currentProvider) ?? "(unspecified)",
        runCost: num(r.attributes.runCostUsd) ?? 0,
      }))
      .sort((a, b) => b.runCost - a.runCost)
      .slice(0, 5),
  };

  // ---- operational process evidence ----
  const processRows = of("operational_process_evidence");
  const highFrictionProcesses = processRows
    .filter((p) => {
      const errorRate = num(p.attributes.errorRatePct);
      const automationPct = num(p.attributes.automationPct);
      const candidate = (str(p.attributes.automationCandidate) ?? "").toLowerCase();
      return (errorRate !== null && errorRate >= THRESHOLDS.highErrorRatePct) || (candidate === "high" && automationPct !== null && automationPct < THRESHOLDS.lowAutomationPct);
    })
    .map((p) => ({
      name: str(p.attributes.processName) ?? "(unnamed)",
      errorRatePct: num(p.attributes.errorRatePct) ?? 0,
      automationPct: num(p.attributes.automationPct) ?? 0,
      automationCandidate: str(p.attributes.automationCandidate) ?? "unspecified",
    }))
    .sort((a, b) => b.errorRatePct - a.errorRatePct);
  const operationalProcesses = { processCount: processRows.length, highFrictionProcesses };

  // ---- platform / data-analytics maturity ----
  const maturityRows = of("platform_maturity_assessment");
  const maturityGaps = maturityRows
    .map((m) => ({
      platform: str(m.attributes.platformOrCapability) ?? "(unnamed)",
      dimension: str(m.attributes.maturityDimension) ?? "(unspecified)",
      currentLevel: num(m.attributes.currentLevel) ?? 0,
      targetLevel: num(m.attributes.targetLevel) ?? 0,
    }))
    .filter((m) => m.targetLevel - m.currentLevel >= THRESHOLDS.materialMaturityGap);
  const platformMaturity = { dimensionCount: maturityRows.length, gaps: maturityGaps };

  // ---- analytical lenses (never tenant fact) ----
  const industryPatterns = of("industry_context_pattern");
  const expertLenses = of("expert_lens");
  const analyticalLenses: DecisionContext["analyticalLenses"] = [
    ...industryPatterns.map((p) => ({ kind: "industry_pattern" as const, label: str(p.attributes.patternName) ?? "(unnamed pattern)" })),
    ...expertLenses.map((l) => ({ kind: "expert_lens" as const, label: str(l.attributes.lensName) ?? "(unnamed lens)" })),
  ];

  return {
    business, strategy,
    portfolio: { programCount: programs.length, totalBudget, totalExpectedValue, stalledPrograms, topByValue },
    technology, vendors: { vendorCount: vendors.length, totalSpend: totalVendorSpend, topByShare },
    organization, performance, risk, leadershipVoice,
    workforce, infrastructure, dataEstate, aiPortfolio, relationships, evidenceGovernance,
    managedServices, operationalProcesses, platformMaturity, analyticalLenses,
  };
}

/* ------------------------------------------------------------------------------------------------
 * Context quality manifest
 *
 * Every number here is a coverage fact, not a content fact, and every one exists because it
 * changes what the thesis is allowed to conclude. The leadership-linkage figure isn't reported
 * because it's interesting; it's reported because "leaders worry about value realization" plus
 * "Program X has high spend" is a plausible-sounding sentence with nothing underneath it unless
 * this manifest is in front of the model when it writes.
 * ---------------------------------------------------------------------------------------------- */

export function buildContextQualityManifest(
  records: Record_[],
  crosswalkRows: Array<{ canonicalObjectType: string; canonicalObjectName?: string }>,
  /**
   * Names of contracts with document-level evidence extraction behind them. Passed in explicitly
   * rather than inferred from a canonical attribute, because that evidence lives in a completely
   * separate data root (the golden evidence packet) that never merges into the canonical
   * vendor_contract object -- confirmed this session when tracing what feeds Tower and Source
   * directly, bypassing canonical. There is no field on vendor_contract this function could check;
   * pretending there was one would silently report zero for the right number and the wrong reason.
   */
  goldenEvidenceContractNames: readonly string[] = [],
): ContextQualityManifest {
  const of = (t: string) => records.filter((r) => r.objectType === t);
  const byType = new Map<string, Record_[]>();
  for (const r of records) {
    if (!byType.has(r.objectType)) byType.set(r.objectType, []);
    byType.get(r.objectType)!.push(r);
  }

  // sourcePath is the universal evidence-reference field -- present on every one of the 28
  // canonical object types checked this session. sourceFile is missing on exactly six of them
  // (the AI-usage and service-performance types among others), and checking sourceFile alone
  // reported those six as 0% evidenced when they are fully sourced -- a false, alarming
  // data-quality signal that would have flowed straight into the EnterpriseThesis prompt as a
  // fabricated-sounding limitation. Checking both, preferring sourcePath, covers every type seen
  // and degrades safely if a future type only carries one of the two.
  const dimensionCoverage = [...byType.entries()].map(([key, rows]) => ({
    key,
    recordCount: rows.length,
    evidencedShare: rows.length
      ? rows.filter((r) => str(r.attributes.sourcePath) ?? str(r.attributes.sourceFile)).length / rows.length
      : 0,
  }));

  const resolvable = crosswalkRows.filter((r) => r.canonicalObjectType !== "no_canonical_match");
  // Distinct programs, not rows -- two crosswalk rows can name the same program from two different
  // interview mentions, and counting rows would overstate linkage on any tenant where that happens
  // to occur (it does not happen to occur in this dataset, which is exactly how this bug would have
  // shipped unnoticed).
  const linkedPrograms = new Set(
    crosswalkRows
      .filter((r) => r.canonicalObjectType === "program" || r.canonicalObjectType === "tower_initiative")
      .map((r) => r.canonicalObjectName)
      .filter(Boolean),
  ).size;
  const coveragePct = crosswalkRows.length ? Math.round((resolvable.length / crosswalkRows.length) * 1000) / 10 : 0;
  const leadershipToPortfolioLinkage = {
    resolvableRows: resolvable.length,
    totalRows: crosswalkRows.length,
    coveragePct,
    linkedPrograms,
    interpretation:
      `Program-specific leadership sentiment is sparsely linked (${coveragePct}% of interview mentions resolve to a ` +
      `canonical object). Do not generalize enterprise-wide leadership themes into program-specific sentiment unless ` +
      `an explicit resolved crosswalk row supports that specific connection.`,
  };

  // Vendor document-evidence coverage: how many of the declared contracts have anything beyond
  // the declared register behind them (the doc.* / golden-evidence extraction layer).
  const vendors = of("vendor_contract");
  const goldenSet = new Set(goldenEvidenceContractNames.map((n) => n.toLowerCase()));
  const withExtraction = vendors.filter((v) => {
    const name = (str(v.attributes.contractName) ?? str(v.attributes.vendorName) ?? "").toLowerCase();
    return [...goldenSet].some((g) => name.includes(g) || g.includes(name));
  }).length;
  const vendorDocumentEvidence = {
    contractsWithExtraction: withExtraction,
    totalContracts: vendors.length,
    interpretation:
      withExtraction === 0
        ? `None of the ${vendors.length} declared vendor contracts have document-level evidence extraction behind ` +
          `them in this packet. ${goldenEvidenceContractNames.length > 0
            ? `Document-level evidence exists for ${goldenEvidenceContractNames.length} contracts (${goldenEvidenceContractNames.join(", ")}) that do not correspond by name to any entry in this tenant's declared vendor register — a separate, unreconciled evidence set, not partial coverage of the 65.`
            : `Contract-level claims (pricing terms, SLA history, invoice detail) are not available at the enterprise level — only the declared register (name, value, term).`}`
        : `${withExtraction} of ${vendors.length} declared vendor contracts have document-level evidence extraction; ` +
          `the remainder carry only the declared register.`,
  };

  const dc = buildDecisionContext(records);
  const metricComparability = {
    comparable: dc.performance.comparable,
    total: dc.performance.metricCount,
    inconsistentNotation: dc.performance.inconsistentNotation,
    interpretation:
      `${dc.performance.comparable} of ${dc.performance.metricCount} tracked metrics have a comparable baseline, ` +
      `target and actual; ${dc.performance.notComparable} do not, and ${dc.performance.inconsistentNotation} of the ` +
      `comparable set mix notation between those three fields. Metric-level performance claims outside the ` +
      `comparable set are unsupported.`,
  };

  return {
    dimensionCoverage,
    leadershipToPortfolioLinkage,
    vendorDocumentEvidence,
    metricComparability,
    prohibitedComparisons: [
      "Do not compare this organization against industry benchmarks for a different industry than its declared one.",
      "Do not state a priority-to-program, priority-to-spend, or priority-to-KPI linkage as fact — no canonical field " +
        "currently links them. Only the candidate-relationship engine may propose such a link, and only as labeled, " +
        "non-authoritative, client-unattested output.",
    ],
  };
}

/* ------------------------------------------------------------------------------------------------
 * Enterprise signal packet
 *
 * Where materiality thresholds live. Every one is stated as a number in this function, not felt —
 * that's the whole discipline this layer exists to enforce. Change a threshold, the change is a
 * one-line diff someone can review, not a drift in what "big" happens to mean this week.
 * ---------------------------------------------------------------------------------------------- */

/**
 * Deterministic context facts, each citeable by id -- enterprise identity, business economics,
 * declared customer segments, declared strategic priorities. No relationships are asserted here
 * (e.g. no priority-to-program link); each item is a single standalone fact. Connections between
 * facts are the signal layer's job, not this one's.
 */
function buildContextItems(dc: DecisionContext): ContextItem[] {
  const items: ContextItem[] = [];
  let n = 0;
  const id = (kind: string) => `ctx_${kind}_${String(++n).padStart(3, "0")}`;

  if (dc.business.businessModel) {
    items.push({ id: id("identity"), statement: `Business model: ${dc.business.businessModel}.`, domains: ["tenant_profile"] });
  }
  if (dc.business.industry) {
    items.push({ id: id("identity"), statement: `Industry: ${dc.business.industry}.`, domains: ["tenant_profile"] });
  }
  if (dc.business.revenue !== null) {
    items.push({ id: id("identity"), statement: `Annual revenue: ${usd(dc.business.revenue)}.`, domains: ["tenant_profile"] });
  }
  if (dc.business.employeeCount !== null) {
    items.push({ id: id("identity"), statement: `Employee count: ${dc.business.employeeCount.toLocaleString()}.`, domains: ["tenant_profile"] });
  }
  if (dc.strategy.mission) {
    items.push({ id: id("identity"), statement: `Declared mission: ${dc.strategy.mission}.`, domains: ["tenant_profile"] });
  }
  if (dc.business.operatingSegments.length) {
    items.push({ id: id("economics"), statement: `Operating segments: ${dc.business.operatingSegments.join(", ")}.`, domains: ["business_function"] });
  }
  if (dc.technology.technologyBudget > 0 && dc.business.revenue) {
    const pct = ((dc.technology.technologyBudget / dc.business.revenue) * 100).toFixed(2);
    items.push({
      id: id("economics"),
      statement: `Technology budget is ${usd(dc.technology.technologyBudget)}, ${pct}% of revenue.`,
      domains: ["spend_value_fact", "tenant_profile"],
    });
  }
  if (dc.business.operatingRegions.length) {
    items.push({ id: id("economics"), statement: `Declared operating regions: ${dc.business.operatingRegions.join(", ")}.`, domains: ["tenant_profile"] });
  }
  for (const seg of dc.business.customerSegments) {
    items.push({ id: id("segment"), statement: `Declared customer segment: ${seg}.`, domains: ["tenant_profile"] });
  }
  for (const p of dc.strategy.statedPriorities) {
    items.push({ id: id("priority"), statement: `Declared strategic priority: ${p}.`, domains: ["tenant_profile"] });
  }

  return items;
}

/**
 * Named, precomputed datasets a chapter can point a visual at. Every value here is arithmetic
 * already done in this file -- a model choosing to visualize `vendor_spend_concentration` gets
 * the real rows, never a chance to invent or adjust one. Names are the only thing the model is
 * allowed to reference (`dataset_ref`); the allowlist of what a name may be plotted as lives in
 * the thesis prompt, not here.
 */
export function buildVisualDatasets(dc: DecisionContext): Record<string, Array<Record<string, unknown>>> {
  const datasets: Record<string, Array<Record<string, unknown>>> = {};

  if (dc.technology.technologyBudget > 0) {
    datasets.technology_spend_mix = [
      { category: "Third-party contracted", amount: dc.vendors.totalSpend },
      { category: "Other technology spend", amount: Math.max(0, dc.technology.technologyBudget - dc.vendors.totalSpend) },
    ];
  }

  if (dc.vendors.topByShare.length) {
    datasets.vendor_spend_concentration = dc.vendors.topByShare.map((v) => ({
      vendor: v.name, spend: v.spend, sharePct: Math.round(v.share * 1000) / 10,
    }));
  }

  if (dc.technology.byFunction.length) {
    datasets.application_landscape_by_function = dc.technology.byFunction.map((f) => ({
      function: f.function, applicationCount: f.count, annualCost: f.cost,
    }));
  }

  if (dc.portfolio.topByValue.length) {
    datasets.program_investment_distribution = dc.portfolio.topByValue.map((p) => ({
      program: p.name, expectedValue: p.expectedValue,
    }));
  }

  if (dc.portfolio.stalledPrograms.length) {
    datasets.stalled_programs = dc.portfolio.stalledPrograms.map((p) => ({
      program: p.name, pctComplete: p.pctComplete, blocked: p.blockedReason ?? null,
    }));
  }

  if (dc.leadershipVoice.themeFrequency.length) {
    datasets.leadership_theme_frequency = dc.leadershipVoice.themeFrequency.map((t) => ({
      theme: t.theme, leaderCount: t.leaderCount,
    }));
  }

  if (dc.leadershipVoice.interviewCount > 0) {
    datasets.leadership_evidence_alignment = [
      { category: "Consistent with system record", count: dc.leadershipVoice.interviewCount - dc.leadershipVoice.contradictionCount },
      { category: "Contradicts system record", count: dc.leadershipVoice.contradictionCount },
    ];
  }

  if (dc.performance.metricCount > 0) {
    datasets.metric_target_attainment = [
      { category: "Improving toward target", count: dc.performance.improving },
      { category: "Moving away from target", count: dc.performance.worsening },
      { category: "Not comparable", count: dc.performance.notComparable },
    ];
  }

  if (dc.risk.bySystemConcentration.length) {
    datasets.risk_system_concentration = dc.risk.bySystemConcentration.map((s) => ({
      system: s.system, riskCount: s.riskCount,
    }));
  }

  return datasets;
}

export function buildEnterpriseSignalPacket(dc: DecisionContext, quality: ContextQualityManifest) {
  const signals: Signal[] = [];
  let n = 0;
  const id = (kind: string) => `sig_${kind}_${String(++n).padStart(3, "0")}`;

  // ---- concentrations ----
  for (const v of dc.vendors.topByShare) {
    if (v.share >= THRESHOLDS.vendorConcentrationShare) {
      signals.push({
        id: id("concentration"),
        kind: "concentration",
        statement: `${v.name} represents ${(v.share * 100).toFixed(1)}% of total vendor spend (${usd(v.spend)} of ${usd(dc.vendors.totalSpend)})${v.supportedFunctions.length ? `, supporting ${v.supportedFunctions.join(", ")}` : ""}.`,
        domains: ["vendor_contract"],
        value: v.share,
        evidenceRefs: [v.name],
      });
    }
  }
  if (dc.technology.applicationCount > 0) {
    const share = dc.technology.replacementCandidates.count / dc.technology.applicationCount;
    signals.push({
      id: id("concentration"),
      kind: "concentration",
      statement: `${dc.technology.replacementCandidates.count} applications (${(share * 100).toFixed(0)}% of the estate, ${usd(dc.technology.replacementCandidates.cost)}) are already identified as replacement candidates.`,
      domains: ["application_system"],
      value: share,
      evidenceRefs: [],
    });
  }

  // ---- dependencies ----
  for (const s of dc.risk.bySystemConcentration) {
    if (s.riskCount >= THRESHOLDS.systemRiskDependencyCount) {
      signals.push({
        id: id("dependency"),
        kind: "dependency",
        statement: `${s.system} is named in ${s.riskCount} separate risk or control entries — a concentration of risk exposure on one system.`,
        domains: ["risk_or_control"],
        value: s.riskCount,
        evidenceRefs: [s.system],
      });
    }
  }

  // ---- gaps ----
  signals.push({
    id: id("gap"),
    kind: "gap",
    statement: quality.metricComparability.interpretation,
    domains: ["metric_outcome"],
    value: quality.metricComparability.comparable / Math.max(1, quality.metricComparability.total),
    evidenceRefs: [],
  });
  signals.push({
    id: id("gap"),
    kind: "gap",
    statement: quality.vendorDocumentEvidence.interpretation,
    domains: ["vendor_contract"],
    evidenceRefs: [],
  });
  signals.push({
    id: id("gap"),
    kind: "gap",
    statement: quality.leadershipToPortfolioLinkage.interpretation,
    domains: ["ai_value_interview_evidence", "program_initiative"],
    value: quality.leadershipToPortfolioLinkage.coveragePct,
    evidenceRefs: [],
  });

  // ---- risks ----
  for (const r of dc.risk.highSeverity.slice(0, 6)) {
    signals.push({
      id: id("risk"),
      kind: "risk",
      statement: `${r.name} is rated ${r.severity} severity${r.system ? `, tied to ${r.system}` : ""}.`,
      domains: ["risk_or_control"],
      evidenceRefs: [r.name],
    });
  }

  // ---- contradictions ----
  if (dc.leadershipVoice.contradictionCount > 0) {
    signals.push({
      id: id("contradiction"),
      kind: "contradiction",
      statement: `${dc.leadershipVoice.contradictionCount} of ${dc.leadershipVoice.interviewCount} leadership interview responses contradict the system-of-record evidence on the same topic.`,
      domains: ["ai_value_interview_evidence"],
      value: dc.leadershipVoice.contradictionCount,
      evidenceRefs: [],
    });
  }

  // ---- consensus / dissent ----
  const consensusThreshold = Math.ceil(dc.leadershipVoice.leaderCount * THRESHOLDS.consensusLeaderShare);
  for (const t of dc.leadershipVoice.themeFrequency) {
    // Dissent is checked first, deliberately. With a small leader population, "exactly one" and
    // "50% or more" can be the same theme -- two leaders total means a 50% threshold of one, so a
    // theme one person raised would otherwise satisfy the consensus branch and get called a
    // consensus view, which is backwards: one voice out of a small population is a minority view,
    // not agreement. Checking dissent first means a lone voice is never miscounted as consensus
    // regardless of how small the interviewed population is.
    if (t.leaderCount === THRESHOLDS.dissentLeaderCount) {
      signals.push({
        id: id("dissent"),
        kind: "dissent",
        statement: `"${t.theme}" was raised by exactly one interviewed leader — a minority view with no corroboration elsewhere in the interview set.`,
        domains: ["ai_value_interview_evidence"],
        evidenceRefs: [],
      });
    } else if (t.leaderCount >= consensusThreshold && dc.leadershipVoice.leaderCount > 0) {
      signals.push({
        id: id("consensus"),
        kind: "consensus",
        statement: `"${t.theme}" was raised by ${t.leaderCount} of ${dc.leadershipVoice.leaderCount} interviewed leaders — a consensus view, not an isolated opinion.`,
        domains: ["ai_value_interview_evidence"],
        value: t.leaderCount,
        evidenceRefs: [],
      });
    }
  }

  // ---- performance outliers ----
  if (dc.performance.worsening > 0) {
    signals.push({
      id: id("outlier"),
      kind: "outlier",
      statement: `${dc.performance.worsening} of ${dc.performance.comparable} comparable metrics are moving away from their target, not toward it.`,
      domains: ["metric_outcome"],
      value: dc.performance.worsening,
      evidenceRefs: [],
    });
  }

  // ---- portfolio signals ----
  if (dc.portfolio.stalledPrograms.length > 0) {
    for (const p of dc.portfolio.stalledPrograms.slice(0, 5)) {
      signals.push({
        id: id("portfolio"),
        kind: "portfolio",
        statement: `${p.name} is ${p.pctComplete}% complete${p.blockedReason ? ` and blocked: ${p.blockedReason}` : ""}.`,
        domains: ["program_initiative"],
        evidenceRefs: [p.name],
      });
    }
  }
  const valueToBudgetRatio = dc.portfolio.totalBudget > 0 ? dc.portfolio.totalExpectedValue / dc.portfolio.totalBudget : null;
  if (valueToBudgetRatio !== null) {
    signals.push({
      id: id("portfolio"),
      kind: "portfolio",
      statement: `The declared portfolio carries ${usd(dc.portfolio.totalBudget)} of budget against ${usd(dc.portfolio.totalExpectedValue)} of expected value across ${dc.portfolio.programCount} programs (a declared ${valueToBudgetRatio.toFixed(2)}x return) — declared, not yet finance-confirmed.`,
      domains: ["program_initiative"],
      evidenceRefs: [],
    });
  }

  // ---- technology complexity ----
  if (dc.technology.byFunction.length > 0) {
    const top = dc.technology.byFunction[0];
    signals.push({
      id: id("complexity"),
      kind: "complexity",
      statement: `${top.function} carries the largest technology footprint by cost: ${top.count} applications, ${usd(top.cost)} annually.`,
      domains: ["application_system"],
      evidenceRefs: [],
    });
  }
  signals.push({
    id: id("complexity"),
    kind: "complexity",
    statement: `Third-party contracted spend (${usd(dc.vendors.totalSpend)}) represents ${dc.technology.technologyBudget > 0 ? ((dc.vendors.totalSpend / dc.technology.technologyBudget) * 100).toFixed(0) : "0"}% of the total technology budget (${usd(dc.technology.technologyBudget)}).`,
    domains: ["vendor_contract", "spend_value_fact"],
    evidenceRefs: [],
  });

  // ---- data quality constraints (surfaced as signals, not buried in the manifest alone) ----
  const thinDimensions = quality.dimensionCoverage.filter((d) => d.recordCount > 0 && d.evidencedShare < 0.5);
  for (const d of thinDimensions) {
    signals.push({
      id: id("data_quality"),
      kind: "data_quality",
      statement: `${d.key}: only ${(d.evidencedShare * 100).toFixed(0)}% of ${d.recordCount} records carry a source reference.`,
      domains: [d.key],
      evidenceRefs: [],
    });
  }

  // ---- leadership testimony (real quotes, deterministically selected -- see leadershipVoice.testimony) ----
  for (const t of dc.leadershipVoice.testimony) {
    signals.push({
      id: id("testimony"),
      kind: "testimony",
      statement: `A ${t.role} said, on the theme of "${t.theme}"${t.sentiment ? ` (${t.sentiment} sentiment)` : ""}: "${t.quote}"`,
      domains: ["ai_value_interview_evidence"],
      evidenceRefs: [t.role],
    });
  }

  // ---- workforce ----
  for (const r of dc.workforce.automationOpportunityRoles.slice(0, 5)) {
    signals.push({
      id: id("workforce"),
      kind: "workforce",
      statement: `${r.role} (${r.function}, ${r.count.toLocaleString()} people) has a documented automation opportunity: ${r.opportunity}`,
      domains: ["workforce_role"],
      evidenceRefs: [r.role],
    });
  }

  // ---- infrastructure risk ----
  for (const p of dc.infrastructure.atRiskPlatforms.slice(0, 5)) {
    signals.push({
      id: id("infra"),
      kind: "risk",
      statement:
        `${p.name} is ${p.criticality}-critical` +
        `${p.capacityHeadroomPct !== null ? ` with only ${p.capacityHeadroomPct}% capacity headroom` : ""}` +
        `${p.drTier ? `, DR tier ${p.drTier}` : ""}.`,
      domains: ["infrastructure_platform"],
      evidenceRefs: [p.name],
    });
  }

  // ---- data estate ----
  if (dc.dataEstate.assetCount > 0 && dc.dataEstate.regulatedCount > 0) {
    signals.push({
      id: id("complexity"),
      kind: "complexity",
      statement: `${dc.dataEstate.regulatedCount} of ${dc.dataEstate.assetCount} tracked data assets/integrations carry regulated data.`,
      domains: ["data_asset_or_integration"],
      value: dc.dataEstate.regulatedCount,
      evidenceRefs: [],
    });
  }

  // ---- AI portfolio ----
  if (dc.aiPortfolio.useCaseCount > 0) {
    const statusSummary = dc.aiPortfolio.byStatus.map((s) => `${s.count} ${s.status}`).join(", ");
    signals.push({
      id: id("ai_value"),
      kind: "ai_value",
      statement: `${dc.aiPortfolio.useCaseCount} declared AI/automation use cases by status: ${statusSummary}.`,
      domains: ["ai_automation_use_case"],
      evidenceRefs: [],
    });
  }
  if (dc.aiPortfolio.promisedValue > 0) {
    signals.push({
      id: id("ai_value"),
      kind: "ai_value",
      statement:
        `AI value realization tracking shows ${usd(dc.aiPortfolio.promisedValue)} of promised value against ` +
        `${usd(dc.aiPortfolio.financeValidatedValue)} finance-validated — ` +
        `${dc.aiPortfolio.financeValidatedValue > 0 ? `${((dc.aiPortfolio.financeValidatedValue / dc.aiPortfolio.promisedValue) * 100).toFixed(0)}% confirmed` : "none yet confirmed"}.`,
      domains: ["ai_value_realization_signal"],
      evidenceRefs: [],
    });
  }
  for (const t of dc.aiPortfolio.toolAdoptionGaps.slice(0, 3)) {
    signals.push({
      id: id("ai_value"),
      kind: "ai_value",
      statement: `${t.tool} adoption is ${t.adoptionGapPct} points below its adoption target.`,
      domains: ["ai_tool_usage_observation"],
      evidenceRefs: [t.tool],
    });
  }

  // ---- relationships (declared canonical links) ----
  for (const h of dc.relationships.hubSystems) {
    signals.push({
      id: id("dependency"),
      kind: "dependency",
      statement: `${h.system} integrates with ${h.integrationCount} other systems — a concentration point in the integration graph.`,
      domains: ["relationship_source_row"],
      value: h.integrationCount,
      evidenceRefs: [h.system],
    });
  }
  for (const r of dc.relationships.riskToProgramImpacts.slice(0, 5)) {
    signals.push({
      id: id("risk"),
      kind: "risk",
      statement: `${r.risk} is declared as directly impacting ${r.program} (a canonical link, not inferred).`,
      domains: ["relationship_source_row", "risk_or_control", "program_initiative"],
      evidenceRefs: [r.risk, r.program],
    });
  }

  // ---- evidence governance ----
  if (dc.evidenceGovernance.sourceCount > 0 && dc.evidenceGovernance.notApprovedCount > 0) {
    signals.push({
      id: id("data_quality"),
      kind: "data_quality",
      statement: `${dc.evidenceGovernance.notApprovedCount} of ${dc.evidenceGovernance.sourceCount} declared evidence sources are not yet approved for loading.`,
      domains: ["evidence_source"],
      evidenceRefs: [],
    });
  }

  // ---- managed services ----
  for (const s of dc.managedServices.services.slice(0, 3)) {
    signals.push({
      id: id("complexity"),
      kind: "complexity",
      statement: `${s.name} (${s.tower}) runs at ${usd(s.runCost)} annually via ${s.provider}.`,
      domains: ["managed_service_scope"],
      evidenceRefs: [s.name],
    });
  }

  // ---- operational process friction ----
  for (const p of dc.operationalProcesses.highFrictionProcesses.slice(0, 5)) {
    signals.push({
      id: id("operational"),
      kind: "operational",
      statement: `${p.name} runs a ${p.errorRatePct}% error rate at ${p.automationPct}% automation, despite a "${p.automationCandidate}" automation-candidate rating.`,
      domains: ["operational_process_evidence"],
      value: p.errorRatePct,
      evidenceRefs: [p.name],
    });
  }

  // ---- platform / data-analytics maturity gaps ----
  for (const g of dc.platformMaturity.gaps.slice(0, 5)) {
    signals.push({
      id: id("gap"),
      kind: "gap",
      statement: `${g.platform}: ${g.dimension} sits at maturity level ${g.currentLevel} against a target of ${g.targetLevel}.`,
      domains: ["platform_maturity_assessment"],
      value: g.targetLevel - g.currentLevel,
      evidenceRefs: [g.platform],
    });
  }

  return {
    enterpriseIdentity: {
      businessModel: dc.business.businessModel,
      industry: dc.business.industry,
      revenue: dc.business.revenue,
      employeeCount: dc.business.employeeCount,
    },
    businessEconomics: {
      operatingSegments: dc.business.operatingSegments,
      customerSegments: dc.business.customerSegments,
      technologyBudget: dc.technology.technologyBudget,
      technologyBudgetShareOfRevenue: dc.business.revenue ? dc.technology.technologyBudget / dc.business.revenue : null,
    },
    strategicPriorities: dc.strategy.statedPriorities,
    signals,
    contextItems: buildContextItems(dc),
    visualDatasets: buildVisualDatasets(dc),
    /** Framing material, not evidence -- kept structurally separate from signals/contextItems so
     * a claim can never cite an industry pattern or named expert lens as if it were a fact about
     * this specific enterprise. The thesis prompt is told explicitly never to cite these as
     * evidence_ids. */
    analyticalLenses: dc.analyticalLenses,
    coverageManifest: quality,
  };
}
