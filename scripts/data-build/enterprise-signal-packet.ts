/**
 * The decision-context compiler, the quality manifest, and the enterprise signal packet.
 *
 * Three deterministic layers, in this order, sitting between the canonical model and the
 * EnterpriseThesis prompt:
 *
 *   canonical records → decision context → quality manifest → signal packet → (Claude) → thesis
 *
 * None of what's in this file calls a model. Every sentence a function here produces is a
 * template filled with a real number pulled from a real record, the same discipline the
 * orientation-pack generator uses for its fact cards. The reason to build this as a *separate*
 * layer from that generator, rather than extending it, is what this session spent an afternoon
 * discovering the hard way: a model asked to reason over an undifferentiated pile of 4,026
 * records has no way to know which sixty of them matter. This file's whole job is deciding that,
 * with arithmetic, before a model ever sees anything.
 *
 * Three honesty rules run through every function here, because they are the three ways this kind
 * of compiler quietly lies:
 *
 * 1. A signal is only "material" if a threshold says so, and the threshold is stated in the code,
 *    not felt. "Big" is not a category; ">= 10% of total spend" is.
 * 2. Every signal carries the record names that produced it (`evidenceRefs`), because a signal
 *    with no way back to its source is exactly the kind of confident, unverifiable assertion the
 *    validator built this afternoon exists to catch — and this compiler feeds that same gate.
 * 3. Coverage gaps are signals too, not silent absences. A dimension where 90% of an expected
 *    linkage doesn't resolve is not a footnote; it's a fact the thesis has to reason with,
 *    which is why `contextQuality` is its own object and not a comment.
 */

type Value = { value?: unknown } | undefined;

const str = (v: Value): string | null => {
  const raw = v?.value;
  if (Array.isArray(raw)) {
    const parts = raw.map((x) => String(x ?? "").trim()).filter(Boolean);
    return parts.length ? parts.join("; ") : null;
  }
  if (typeof raw === "number") return Number.isFinite(raw) ? String(raw) : null;
  return typeof raw === "string" && raw.trim() ? raw.trim() : null;
};
const list = (v: Value): string[] => {
  const raw = v?.value;
  if (Array.isArray(raw)) return raw.map((x) => String(x ?? "").trim()).filter(Boolean);
  const single = str(v);
  return single ? [single] : [];
};
const num = (v: Value): number | null => {
  const raw = v?.value;
  if (typeof raw === "number") return Number.isFinite(raw) ? raw : null;
  if (typeof raw !== "string") return null;
  const cleaned = raw.trim().replace(/[$,\s]/g, "");
  if (!/^-?\d+(\.\d+)?$/.test(cleaned)) return null;
  const n = Number(cleaned);
  return Number.isFinite(n) ? n : null;
};
const usd = (n: number): string =>
  n >= 1e9 ? `$${(n / 1e9).toFixed(2)}B` : n >= 1e6 ? `$${(n / 1e6).toFixed(1)}M` : `$${n.toLocaleString()}`;

interface Record_ {
  objectType: string;
  attributes: Record<string, Value>;
}

/** A single citable unit of derived reasoning. This is the atom the whole packet is built from. */
export interface Signal {
  id: string;
  kind:
    | "concentration" | "change" | "gap" | "risk" | "dependency" | "contradiction"
    | "consensus" | "dissent" | "outlier" | "portfolio" | "complexity" | "data_quality";
  /** A deterministic sentence. Never generated by a model. */
  statement: string;
  /** Canonical object types this signal draws from — the mechanism for enforcing "cross-domain". */
  domains: string[];
  value?: number;
  /** Names of the specific records backing this signal. What a reader would check to verify it. */
  evidenceRefs: string[];
}

/** A relationship the compiler could not confirm from an explicit canonical link, only propose. */
export interface CandidateRelationship {
  id: string;
  relationship: string;
  candidateRelationship: true;
  clientAttested: false;
  confidence: "low" | "medium";
  reason: string;
  supportingEvidenceIds: string[];
}

export interface DecisionContext {
  business: {
    revenue: number | null;
    employeeCount: number | null;
    businessModel: string | null;
    industry: string | null;
    operatingSegments: string[];
    customerSegments: string[];
    operatingRegions: string[];
  };
  strategy: {
    mission: string | null;
    statedPriorities: string[];
    /** Real linkage only. If empty, say so — do not fill with candidates. */
    priorityToProgramLinks: Array<{ priority: string; programs: string[] }>;
  };
  portfolio: {
    programCount: number;
    totalBudget: number;
    totalExpectedValue: number;
    stalledPrograms: Array<{ name: string; pctComplete: number; blockedReason: string | null }>;
    topByValue: Array<{ name: string; expectedValue: number }>;
  };
  technology: {
    applicationCount: number;
    technologyBudget: number;
    thirdPartyContracted: number;
    byFunction: Array<{ function: string; count: number; cost: number }>;
    replacementCandidates: { count: number; cost: number };
  };
  vendors: {
    vendorCount: number;
    totalSpend: number;
    topByShare: Array<{ name: string; spend: number; share: number; supportedFunctions: string[] }>;
  };
  organization: {
    functionCount: number;
    orgUnitCount: number;
    leadershipTeam: string[];
  };
  performance: {
    metricCount: number;
    comparable: number;
    improving: number;
    worsening: number;
    notComparable: number;
    inconsistentNotation: number;
  };
  risk: {
    riskCount: number;
    bySystemConcentration: Array<{ system: string; riskCount: number }>;
    highSeverity: Array<{ name: string; severity: string; system: string | null }>;
  };
  leadershipVoice: {
    interviewCount: number;
    leaderCount: number;
    themeFrequency: Array<{ theme: string; leaderCount: number }>;
    contradictionCount: number;
  };
}

export interface ContextQualityManifest {
  dimensionCoverage: Array<{ key: string; recordCount: number; evidencedShare: number }>;
  leadershipToPortfolioLinkage: {
    resolvableRows: number;
    totalRows: number;
    coveragePct: number;
    linkedPrograms: number;
    interpretation: string;
  };
  vendorDocumentEvidence: {
    contractsWithExtraction: number;
    totalContracts: number;
    interpretation: string;
  };
  metricComparability: {
    comparable: number;
    total: number;
    inconsistentNotation: number;
    interpretation: string;
  };
  prohibitedComparisons: string[];
}

/* ------------------------------------------------------------------------------------------------
 * Decision context
 * ---------------------------------------------------------------------------------------------- */

export function buildDecisionContext(records: Record_[]): DecisionContext {
  const of = (t: string) => records.filter((r) => r.objectType === t);

  const profile = of("tenant_profile")[0]?.attributes ?? {};
  const functions = of("business_function");
  const apps = of("application_system");
  const vendors = of("vendor_contract");
  const programs = of("program_initiative");
  const metrics = of("metric_outcome");
  const risks = of("risk_or_control");
  const interviews = of("ai_value_interview_evidence");

  // ---- business ----
  const business = {
    revenue: num(profile.revenueUsd),
    employeeCount: num(profile.employeeCount),
    businessModel: str(profile.businessModel),
    industry: [str(profile.industry), str(profile.subIndustry)].filter(Boolean).join(" — ") || null,
    operatingSegments: [...new Set(functions.map((f) => str(f.attributes.businessSegment)).filter((v): v is string => Boolean(v)))],
    customerSegments: list(profile.customerSegments),
    operatingRegions: list(profile.operatingRegions),
  };

  // ---- strategy ----
  // Deliberately empty unless a canonical record explicitly links a program to a priority. No
  // fuzzy text-matching here — that belongs in the candidate-relationship engine, not the
  // authoritative decision context, per the standing rule: candidate relationships are never facts.
  const strategy = {
    mission: str(profile.mission),
    statedPriorities: list(profile.strategicPriorities),
    priorityToProgramLinks: [] as Array<{ priority: string; programs: string[] }>,
  };

  // ---- portfolio ----
  const totalBudget = programs.reduce((s, p) => s + (num(p.attributes.budgetUsd) ?? 0), 0);
  const totalExpectedValue = programs.reduce((s, p) => s + (num(p.attributes.expectedValueUsd) ?? 0), 0);
  const stalledPrograms = programs
    .filter((p) => {
      const pct = num(p.attributes.pctComplete);
      const blocked = str(p.attributes.blockedReason);
      return blocked !== null || (pct !== null && pct < 15 && str(p.attributes.status)?.toLowerCase() !== "not_started");
    })
    .map((p) => ({
      name: str(p.attributes.programName) ?? "(unnamed)",
      pctComplete: num(p.attributes.pctComplete) ?? 0,
      blockedReason: str(p.attributes.blockedReason),
    }));
  const topByValue = programs
    .map((p) => ({ name: str(p.attributes.programName) ?? "(unnamed)", expectedValue: num(p.attributes.expectedValueUsd) ?? 0 }))
    .filter((p) => p.expectedValue > 0)
    .sort((a, b) => b.expectedValue - a.expectedValue)
    .slice(0, 5);

  // ---- technology ----
  const spendFacts = of("spend_value_fact");
  const technologyBudget = spendFacts.reduce((s, r) => s + (num(r.attributes.annualSpendUsd) ?? 0), 0);
  const thirdPartyContracted = vendors.reduce((s, v) => s + (num(v.attributes.annualSpendUsd) ?? 0), 0);
  const byFunctionMap = new Map<string, { count: number; cost: number }>();
  for (const a of apps) {
    const fn = str(a.attributes.businessFunction) ?? str(a.attributes.supportedFunction) ?? "Unclassified";
    const entry = byFunctionMap.get(fn) ?? { count: 0, cost: 0 };
    entry.count += 1;
    entry.cost += num(a.attributes.annualCostUsd) ?? 0;
    byFunctionMap.set(fn, entry);
  }
  const byFunction = [...byFunctionMap.entries()]
    .map(([fn, v]) => ({ function: fn, count: v.count, cost: v.cost }))
    .sort((a, b) => b.cost - a.cost);
  const replaceable = apps.filter((a) => str(a.attributes.replacementCandidate) === "yes");
  const technology = {
    applicationCount: apps.length,
    technologyBudget,
    thirdPartyContracted,
    byFunction,
    replacementCandidates: {
      count: replaceable.length,
      cost: replaceable.reduce((s, a) => s + (num(a.attributes.annualCostUsd) ?? 0), 0),
    },
  };

  // ---- vendors ----
  const totalVendorSpend = vendors.reduce((s, v) => s + (num(v.attributes.annualSpendUsd) ?? 0), 0);
  const topByShare = vendors
    .map((v) => ({
      name: str(v.attributes.vendorName) ?? "(unnamed)",
      spend: num(v.attributes.annualSpendUsd) ?? 0,
      share: totalVendorSpend > 0 ? (num(v.attributes.annualSpendUsd) ?? 0) / totalVendorSpend : 0,
      supportedFunctions: list(v.attributes.supportedFunctions),
    }))
    .sort((a, b) => b.spend - a.spend)
    .slice(0, 8);

  // ---- organization ----
  const organization = {
    functionCount: functions.length,
    orgUnitCount: of("org_owner").length,
    leadershipTeam: list(profile.leadershipTeam),
  };

  // ---- performance ----
  // Direction-of-good inferred from where the client placed the target relative to the baseline —
  // the same logic the orientation pack's "standing" block uses, kept consistent across layers.
  function measurement(v: Value): { quantity: number } | null {
    const raw = v?.value;
    if (typeof raw === "number") return Number.isFinite(raw) ? { quantity: raw } : null;
    if (typeof raw !== "string") return null;
    const match = raw.trim().match(/^-?[\d,]+(?:\.\d+)?/);
    if (!match) return null;
    const quantity = Number(match[0].replace(/,/g, ""));
    return Number.isFinite(quantity) ? { quantity } : null;
  }
  let improving = 0, worsening = 0, notComparable = 0, inconsistentNotation = 0;
  for (const m of metrics) {
    const base = measurement(m.attributes.baselineValue);
    const target = measurement(m.attributes.targetValue);
    const actual = measurement(m.attributes.actualValue);
    if (!base || !target || !actual || target.quantity === base.quantity) { notComparable++; continue; }
    const rawBase = str(m.attributes.baselineValue) ?? "";
    const rawTarget = str(m.attributes.targetValue) ?? "";
    const rawActual = str(m.attributes.actualValue) ?? "";
    const notations = new Set([rawBase.includes("%"), rawTarget.includes("%"), rawActual.includes("%")]);
    if (notations.size > 1) inconsistentNotation++;
    const intended = Math.sign(target.quantity - base.quantity);
    const moved = Math.sign(actual.quantity - base.quantity);
    if (moved === intended && moved !== 0) improving++;
    else if (moved !== intended) worsening++;
  }
  const performance = {
    metricCount: metrics.length,
    comparable: improving + worsening,
    improving,
    worsening,
    notComparable,
    inconsistentNotation,
  };

  // ---- risk ----
  const systemRiskCounts = new Map<string, number>();
  for (const r of risks) {
    for (const sys of list(r.attributes.systemsImpacted)) {
      systemRiskCounts.set(sys, (systemRiskCounts.get(sys) ?? 0) + 1);
    }
  }
  const bySystemConcentration = [...systemRiskCounts.entries()]
    .map(([system, riskCount]) => ({ system, riskCount }))
    .sort((a, b) => b.riskCount - a.riskCount)
    .slice(0, 5);
  const highSeverity = risks
    .filter((r) => (str(r.attributes.severity) ?? "").toLowerCase() === "high" || (num(r.attributes.inherentRiskScore) ?? 0) >= 9)
    .map((r) => ({
      name: str(r.attributes.riskOrControlName) ?? "(unnamed)",
      severity: str(r.attributes.severity) ?? "unspecified",
      system: list(r.attributes.systemsImpacted)[0] ?? null,
    }));
  const risk = { riskCount: risks.length, bySystemConcentration, highSeverity };

  // ---- leadership voice ----
  const leaderSet = new Set(interviews.map((i) => str(i.attributes.stakeholderRole)).filter(Boolean));
  const themeCounts = new Map<string, Set<string>>();
  for (const row of interviews) {
    const theme = str(row.attributes.themeTags);
    const role = str(row.attributes.stakeholderRole);
    if (!theme || !role) continue;
    if (!themeCounts.has(theme)) themeCounts.set(theme, new Set());
    themeCounts.get(theme)!.add(role);
  }
  const themeFrequency = [...themeCounts.entries()]
    .map(([theme, roles]) => ({ theme, leaderCount: roles.size }))
    .sort((a, b) => b.leaderCount - a.leaderCount);
  const contradictionCount = interviews.filter((i) => (str(i.attributes.contradictsRecord) ?? "").startsWith("yes")).length;
  const leadershipVoice = {
    interviewCount: interviews.length,
    leaderCount: leaderSet.size,
    themeFrequency,
    contradictionCount,
  };

  return { business, strategy, portfolio: { programCount: programs.length, totalBudget, totalExpectedValue, stalledPrograms, topByValue }, technology, vendors: { vendorCount: vendors.length, totalSpend: totalVendorSpend, topByShare }, organization, performance, risk, leadershipVoice };
}

/* ------------------------------------------------------------------------------------------------
 * Context quality manifest
 *
 * Every number here is a coverage fact, not a content fact, and every one exists because it
 * changes what the thesis is allowed to conclude. The leadership-linkage figure isn't reported
 * because it's interesting; it's reported because "leaders worry about value realization" plus
 * "Program X has high spend" is a plausible-sounding sentence with nothing underneath it unless
 * this manifest is in front of the model when it writes.
 * ---------------------------------------------------------------------------------------------- */

export function buildContextQualityManifest(
  records: Record_[],
  crosswalkRows: Array<{ canonicalObjectType: string; canonicalObjectName?: string }>,
  /**
   * Names of contracts with document-level evidence extraction behind them. Passed in explicitly
   * rather than inferred from a canonical attribute, because that evidence lives in a completely
   * separate data root (the golden evidence packet) that never merges into the canonical
   * vendor_contract object -- confirmed this session when tracing what feeds Tower and Source
   * directly, bypassing canonical. There is no field on vendor_contract this function could check;
   * pretending there was one would silently report zero for the right number and the wrong reason.
   */
  goldenEvidenceContractNames: readonly string[] = [],
): ContextQualityManifest {
  const of = (t: string) => records.filter((r) => r.objectType === t);
  const byType = new Map<string, Record_[]>();
  for (const r of records) {
    if (!byType.has(r.objectType)) byType.set(r.objectType, []);
    byType.get(r.objectType)!.push(r);
  }

  // sourcePath is the universal evidence-reference field -- present on every one of the 28
  // canonical object types checked this session. sourceFile is missing on exactly six of them
  // (the AI-usage and service-performance types among others), and checking sourceFile alone
  // reported those six as 0% evidenced when they are fully sourced -- a false, alarming
  // data-quality signal that would have flowed straight into the EnterpriseThesis prompt as a
  // fabricated-sounding limitation. Checking both, preferring sourcePath, covers every type seen
  // and degrades safely if a future type only carries one of the two.
  const dimensionCoverage = [...byType.entries()].map(([key, rows]) => ({
    key,
    recordCount: rows.length,
    evidencedShare: rows.length
      ? rows.filter((r) => str(r.attributes.sourcePath) ?? str(r.attributes.sourceFile)).length / rows.length
      : 0,
  }));

  const resolvable = crosswalkRows.filter((r) => r.canonicalObjectType !== "no_canonical_match");
  // Distinct programs, not rows -- two crosswalk rows can name the same program from two different
  // interview mentions, and counting rows would overstate linkage on any tenant where that happens
  // to occur (it does not happen to occur in this dataset, which is exactly how this bug would have
  // shipped unnoticed).
  const linkedPrograms = new Set(
    crosswalkRows
      .filter((r) => r.canonicalObjectType === "program" || r.canonicalObjectType === "tower_initiative")
      .map((r) => r.canonicalObjectName)
      .filter(Boolean),
  ).size;
  const coveragePct = crosswalkRows.length ? Math.round((resolvable.length / crosswalkRows.length) * 1000) / 10 : 0;
  const leadershipToPortfolioLinkage = {
    resolvableRows: resolvable.length,
    totalRows: crosswalkRows.length,
    coveragePct,
    linkedPrograms,
    interpretation:
      `Program-specific leadership sentiment is sparsely linked (${coveragePct}% of interview mentions resolve to a ` +
      `canonical object). Do not generalize enterprise-wide leadership themes into program-specific sentiment unless ` +
      `an explicit resolved crosswalk row supports that specific connection.`,
  };

  // Vendor document-evidence coverage: how many of the declared contracts have anything beyond
  // the declared register behind them (the doc.* / golden-evidence extraction layer).
  const vendors = of("vendor_contract");
  const goldenSet = new Set(goldenEvidenceContractNames.map((n) => n.toLowerCase()));
  const withExtraction = vendors.filter((v) => {
    const name = (str(v.attributes.contractName) ?? str(v.attributes.vendorName) ?? "").toLowerCase();
    return [...goldenSet].some((g) => name.includes(g) || g.includes(name));
  }).length;
  const vendorDocumentEvidence = {
    contractsWithExtraction: withExtraction,
    totalContracts: vendors.length,
    interpretation:
      withExtraction === 0
        ? `None of the ${vendors.length} declared vendor contracts have document-level evidence extraction behind ` +
          `them in this packet. ${goldenEvidenceContractNames.length > 0
            ? `Document-level evidence exists for ${goldenEvidenceContractNames.length} contracts (${goldenEvidenceContractNames.join(", ")}) that do not correspond by name to any entry in this tenant's declared vendor register — a separate, unreconciled evidence set, not partial coverage of the 65.`
            : `Contract-level claims (pricing terms, SLA history, invoice detail) are not available at the enterprise level — only the declared register (name, value, term).`}`
        : `${withExtraction} of ${vendors.length} declared vendor contracts have document-level evidence extraction; ` +
          `the remainder carry only the declared register.`,
  };

  const dc = buildDecisionContext(records);
  const metricComparability = {
    comparable: dc.performance.comparable,
    total: dc.performance.metricCount,
    inconsistentNotation: dc.performance.inconsistentNotation,
    interpretation:
      `${dc.performance.comparable} of ${dc.performance.metricCount} tracked metrics have a comparable baseline, ` +
      `target and actual; ${dc.performance.notComparable} do not, and ${dc.performance.inconsistentNotation} of the ` +
      `comparable set mix notation between those three fields. Metric-level performance claims outside the ` +
      `comparable set are unsupported.`,
  };

  return {
    dimensionCoverage,
    leadershipToPortfolioLinkage,
    vendorDocumentEvidence,
    metricComparability,
    prohibitedComparisons: [
      "Do not compare this organization against industry benchmarks for a different industry than its declared one.",
      "Do not state a priority-to-program, priority-to-spend, or priority-to-KPI linkage as fact — no canonical field " +
        "currently links them. Only the candidate-relationship engine may propose such a link, and only as labeled, " +
        "non-authoritative, client-unattested output.",
    ],
  };
}

/* ------------------------------------------------------------------------------------------------
 * Enterprise signal packet
 *
 * Where materiality thresholds live. Every one is stated as a number in this function, not felt —
 * that's the whole discipline this layer exists to enforce. Change a threshold, the change is a
 * one-line diff someone can review, not a drift in what "big" happens to mean this week.
 * ---------------------------------------------------------------------------------------------- */

const THRESHOLDS = {
  /** A vendor holding this share of total vendor spend or more is a material concentration. */
  vendorConcentrationShare: 0.08,
  /** A risk system-linkage this deep or more is a material dependency. */
  systemRiskDependencyCount: 2,
  /** A leadership theme raised by this many leaders or more is treated as consensus. */
  consensusLeaderShare: 0.5,
  /** A theme raised by exactly this many leaders is treated as dissent, worth naming as a minority view. */
  dissentLeaderCount: 1,
};

export function buildEnterpriseSignalPacket(dc: DecisionContext, quality: ContextQualityManifest) {
  const signals: Signal[] = [];
  let n = 0;
  const id = (kind: string) => `sig_${kind}_${String(++n).padStart(3, "0")}`;

  // ---- concentrations ----
  for (const v of dc.vendors.topByShare) {
    if (v.share >= THRESHOLDS.vendorConcentrationShare) {
      signals.push({
        id: id("concentration"),
        kind: "concentration",
        statement: `${v.name} represents ${(v.share * 100).toFixed(1)}% of total vendor spend (${usd(v.spend)} of ${usd(dc.vendors.totalSpend)})${v.supportedFunctions.length ? `, supporting ${v.supportedFunctions.join(", ")}` : ""}.`,
        domains: ["vendor_contract"],
        value: v.share,
        evidenceRefs: [v.name],
      });
    }
  }
  if (dc.technology.applicationCount > 0) {
    const share = dc.technology.replacementCandidates.count / dc.technology.applicationCount;
    signals.push({
      id: id("concentration"),
      kind: "concentration",
      statement: `${dc.technology.replacementCandidates.count} applications (${(share * 100).toFixed(0)}% of the estate, ${usd(dc.technology.replacementCandidates.cost)}) are already identified as replacement candidates.`,
      domains: ["application_system"],
      value: share,
      evidenceRefs: [],
    });
  }

  // ---- dependencies ----
  for (const s of dc.risk.bySystemConcentration) {
    if (s.riskCount >= THRESHOLDS.systemRiskDependencyCount) {
      signals.push({
        id: id("dependency"),
        kind: "dependency",
        statement: `${s.system} is named in ${s.riskCount} separate risk or control entries — a concentration of risk exposure on one system.`,
        domains: ["risk_or_control"],
        value: s.riskCount,
        evidenceRefs: [s.system],
      });
    }
  }

  // ---- gaps ----
  signals.push({
    id: id("gap"),
    kind: "gap",
    statement: quality.metricComparability.interpretation,
    domains: ["metric_outcome"],
    value: quality.metricComparability.comparable / Math.max(1, quality.metricComparability.total),
    evidenceRefs: [],
  });
  signals.push({
    id: id("gap"),
    kind: "gap",
    statement: quality.vendorDocumentEvidence.interpretation,
    domains: ["vendor_contract"],
    evidenceRefs: [],
  });
  signals.push({
    id: id("gap"),
    kind: "gap",
    statement: quality.leadershipToPortfolioLinkage.interpretation,
    domains: ["ai_value_interview_evidence", "program_initiative"],
    value: quality.leadershipToPortfolioLinkage.coveragePct,
    evidenceRefs: [],
  });

  // ---- risks ----
  for (const r of dc.risk.highSeverity.slice(0, 6)) {
    signals.push({
      id: id("risk"),
      kind: "risk",
      statement: `${r.name} is rated ${r.severity} severity${r.system ? `, tied to ${r.system}` : ""}.`,
      domains: ["risk_or_control"],
      evidenceRefs: [r.name],
    });
  }

  // ---- contradictions ----
  if (dc.leadershipVoice.contradictionCount > 0) {
    signals.push({
      id: id("contradiction"),
      kind: "contradiction",
      statement: `${dc.leadershipVoice.contradictionCount} of ${dc.leadershipVoice.interviewCount} leadership interview responses contradict the system-of-record evidence on the same topic.`,
      domains: ["ai_value_interview_evidence"],
      value: dc.leadershipVoice.contradictionCount,
      evidenceRefs: [],
    });
  }

  // ---- consensus / dissent ----
  const consensusThreshold = Math.ceil(dc.leadershipVoice.leaderCount * THRESHOLDS.consensusLeaderShare);
  for (const t of dc.leadershipVoice.themeFrequency) {
    // Dissent is checked first, deliberately. With a small leader population, "exactly one" and
    // "50% or more" can be the same theme -- two leaders total means a 50% threshold of one, so a
    // theme one person raised would otherwise satisfy the consensus branch and get called a
    // consensus view, which is backwards: one voice out of a small population is a minority view,
    // not agreement. Checking dissent first means a lone voice is never miscounted as consensus
    // regardless of how small the interviewed population is.
    if (t.leaderCount === THRESHOLDS.dissentLeaderCount) {
      signals.push({
        id: id("dissent"),
        kind: "dissent",
        statement: `"${t.theme}" was raised by exactly one interviewed leader — a minority view with no corroboration elsewhere in the interview set.`,
        domains: ["ai_value_interview_evidence"],
        evidenceRefs: [],
      });
    } else if (t.leaderCount >= consensusThreshold && dc.leadershipVoice.leaderCount > 0) {
      signals.push({
        id: id("consensus"),
        kind: "consensus",
        statement: `"${t.theme}" was raised by ${t.leaderCount} of ${dc.leadershipVoice.leaderCount} interviewed leaders — a consensus view, not an isolated opinion.`,
        domains: ["ai_value_interview_evidence"],
        value: t.leaderCount,
        evidenceRefs: [],
      });
    }
  }

  // ---- performance outliers ----
  if (dc.performance.worsening > 0) {
    signals.push({
      id: id("outlier"),
      kind: "outlier",
      statement: `${dc.performance.worsening} of ${dc.performance.comparable} comparable metrics are moving away from their target, not toward it.`,
      domains: ["metric_outcome"],
      value: dc.performance.worsening,
      evidenceRefs: [],
    });
  }

  // ---- portfolio signals ----
  if (dc.portfolio.stalledPrograms.length > 0) {
    for (const p of dc.portfolio.stalledPrograms.slice(0, 5)) {
      signals.push({
        id: id("portfolio"),
        kind: "portfolio",
        statement: `${p.name} is ${p.pctComplete}% complete${p.blockedReason ? ` and blocked: ${p.blockedReason}` : ""}.`,
        domains: ["program_initiative"],
        evidenceRefs: [p.name],
      });
    }
  }
  const valueToBudgetRatio = dc.portfolio.totalBudget > 0 ? dc.portfolio.totalExpectedValue / dc.portfolio.totalBudget : null;
  if (valueToBudgetRatio !== null) {
    signals.push({
      id: id("portfolio"),
      kind: "portfolio",
      statement: `The declared portfolio carries ${usd(dc.portfolio.totalBudget)} of budget against ${usd(dc.portfolio.totalExpectedValue)} of expected value across ${dc.portfolio.programCount} programs (a declared ${valueToBudgetRatio.toFixed(2)}x return) — declared, not yet finance-confirmed.`,
      domains: ["program_initiative"],
      evidenceRefs: [],
    });
  }

  // ---- technology complexity ----
  if (dc.technology.byFunction.length > 0) {
    const top = dc.technology.byFunction[0];
    signals.push({
      id: id("complexity"),
      kind: "complexity",
      statement: `${top.function} carries the largest technology footprint by cost: ${top.count} applications, ${usd(top.cost)} annually.`,
      domains: ["application_system"],
      evidenceRefs: [],
    });
  }
  signals.push({
    id: id("complexity"),
    kind: "complexity",
    statement: `Third-party contracted spend (${usd(dc.vendors.totalSpend)}) represents ${dc.technology.technologyBudget > 0 ? ((dc.vendors.totalSpend / dc.technology.technologyBudget) * 100).toFixed(0) : "0"}% of the total technology budget (${usd(dc.technology.technologyBudget)}).`,
    domains: ["vendor_contract", "spend_value_fact"],
    evidenceRefs: [],
  });

  // ---- data quality constraints (surfaced as signals, not buried in the manifest alone) ----
  const thinDimensions = quality.dimensionCoverage.filter((d) => d.recordCount > 0 && d.evidencedShare < 0.5);
  for (const d of thinDimensions) {
    signals.push({
      id: id("data_quality"),
      kind: "data_quality",
      statement: `${d.key}: only ${(d.evidencedShare * 100).toFixed(0)}% of ${d.recordCount} records carry a source reference.`,
      domains: [d.key],
      evidenceRefs: [],
    });
  }

  return {
    enterpriseIdentity: {
      businessModel: dc.business.businessModel,
      industry: dc.business.industry,
      revenue: dc.business.revenue,
      employeeCount: dc.business.employeeCount,
    },
    businessEconomics: {
      operatingSegments: dc.business.operatingSegments,
      customerSegments: dc.business.customerSegments,
      technologyBudget: dc.technology.technologyBudget,
      technologyBudgetShareOfRevenue: dc.business.revenue ? dc.technology.technologyBudget / dc.business.revenue : null,
    },
    strategicPriorities: dc.strategy.statedPriorities,
    signals,
    coverageManifest: quality,
  };
}
