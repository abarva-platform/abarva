/**
 * Materiality thresholds -- every one is stated as a number here, not felt. Change a threshold,
 * the change is a one-line diff someone can review, not a drift in what "material" happens to
 * mean this week. Used by both buildDecisionContext (which domains count as "at risk" etc.) and
 * buildEnterpriseSignalPacket (which of those become a citeable signal).
 */
const THRESHOLDS = {
  /** A vendor holding this share of total vendor spend or more is a material concentration. */
  vendorConcentrationShare: 0.08,
  /** A risk system-linkage this deep or more is a material dependency. */
  systemRiskDependencyCount: 2,
  /** A leadership theme raised by this many leaders or more is treated as consensus. */
  consensusLeaderShare: 0.5,
  /** A theme raised by exactly this many leaders is treated as dissent, worth naming as a minority view. */
  dissentLeaderCount: 1,
  /** A tier1/tier2-critical platform below this capacity headroom is a material operational risk. */
  lowCapacityHeadroomPct: 20,
  /** A tool adoption gap (target minus actual) this large or more is material underperformance. */
  materialAdoptionGapPct: 20,
  /** A system integrating with at least this many other systems is a material dependency hub. */
  hubIntegrationCount: 4,
  /** An operational process with an error rate at or above this is material friction. */
  highErrorRatePct: 5,
  /** A high-automation-candidate process below this automation level is a material gap. */
  lowAutomationPct: 50,
  /** A target-minus-current maturity gap this large or more is material. */
  materialMaturityGap: 1,
};

